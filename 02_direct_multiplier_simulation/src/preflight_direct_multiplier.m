function report = preflight_direct_multiplier(experimentRoot)
%PREFLIGHT_DIRECT_MULTIPLIER Validate inputs without fitting the model.

    cfg = matched_config('smoke');
    assert(isfolder(cfg.baseSourceRoot), ...
        'Model source directory is missing: %s', cfg.baseSourceRoot);
    assert(all(diff(cfg.candidateM) > 0));
    assert(all(diff(cfg.referenceM) > 0));
    assert(cfg.klTolerance > 0 && cfg.referenceTolerance > 0);
    candidateJ = sqrt(cfg.candidateM);
    assert(all(candidateJ == round(candidateJ)), ...
        'The two-dimensional candidate ranks must be square numbers.');

    retainedFile = fullfile(experimentRoot, 'input', ...
        'four_method_summary.csv');
    assert(isfile(retainedFile), ...
        'Retained direct-multiplier summary is missing.');
    retained = readtable(retainedFile, 'TextType', 'string');
    requiredMethods = ["numerical_inversion_reference"; ...
        "fixed_high_rank_hsgp"; "frequency_adaptive_hsgp"];
    assert(all(ismember(requiredMethods, retained.method)));

    report = table(string(version), cfg.nSites, cfg.T, ...
        numel(cfg.candidateM), numel(cfg.referenceM), ...
        height(retained), true, ...
        'VariableNames', {'matlabVersion','smokeNumberOfSites', ...
        'smokeRecordLength','numberOfCandidateRanks', ...
        'numberOfReferenceRanks','numberOfRetainedMethods','passed'});
end

