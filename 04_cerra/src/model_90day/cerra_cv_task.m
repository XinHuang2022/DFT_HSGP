function task=cerra_cv_task(cfg,subset,fold,method,J,boundaryFactor,fullDomainXy)
%CERRA_CV_TASK Resume-safe exact or HSGP fit for one spatial fold.
    label=string(method);
    if label=="hsgp"
        % Keep the method label as one scalar table value.  sprintf returns
        % a character vector, which TABLE otherwise interprets as one row
        % per character when it is combined with scalar numeric variables.
        label=cerra_hsgp_label(boundaryFactor,J);
    end
    taskDir=fullfile(cfg.paths.stage3Dir,'tasks');ensure_directory(taskDir);
    taskFile=fullfile(taskDir,sprintf('%s_fold_%02d.mat',label,fold.foldID));
    if isfile(taskFile)
        S=load(taskFile,'task');
        taskCompatible=isfield(S,'task') && isfield(S.task,'version') && ...
            isequal(string(S.task.version),string(cfg.version));
        if taskCompatible
            fprintf('%s fold %d loaded from checkpoint.\n',label,fold.foldID);task=S.task;return;
        end
    end
    timerValue=tic;targetIndex=fold.targetIndex;
    observedIndex=setdiff((1:size(subset.U,2))',targetIndex,'stable');
    Yobserved=subset.U(:,observedIndex);Ytarget=subset.U(:,targetIndex);
    [observed,target]=cerra_fold_geometry(subset,observedIndex,targetIndex,cfg);
    [foldCfg,varianceReference]=cerra_fold_config(cfg,Yobserved, ...
        observed.xyKm,cfg.stage3.optimizer);
    basis=[];warm=[];
    if method=="hsgp"
        basis=make_cerra_hsgp_basis(fullDomainXy,boundaryFactor,J,cfg);
        warmFile=fullfile(cfg.paths.stage2Dir,'tasks',sprintf('c%s_J_%03d.mat', ...
            cerra_boundary_tag(boundaryFactor),J));
        if isfile(warmFile)
            W=load(warmFile,'task');if isfield(W,'task'),warm=W.task.fullFit.theta;end
        end
    end
    fitCheckpointFile=fullfile(taskDir,sprintf('%s_fold_%02d_fit.mat',label,fold.foldID));
    fitLoaded=false;
    if isfile(fitCheckpointFile)
        C=load(fitCheckpointFile,'checkpoint');
        fitLoaded=isfield(C,'checkpoint');
        if fitLoaded
            checkpoint=C.checkpoint;
            fitLoaded=isfield(checkpoint,'version') && ...
                isequal(string(checkpoint.version),string(cfg.version)) && ...
                isfield(checkpoint,'method') && ...
                isequal(string(checkpoint.method),label) && ...
                isfield(checkpoint,'J') && isequal(checkpoint.J,J) && ...
                isfield(checkpoint,'boundaryFactor') && ...
                isequal(checkpoint.boundaryFactor,boundaryFactor);
        end
    end
    if fitLoaded
        separableFit=C.checkpoint.separableFit;fullFit=C.checkpoint.fullFit;
        fitSeconds=C.checkpoint.fitSeconds;
        fprintf('%s fold %d fit loaded from checkpoint.\n',label,fold.foldID);
    else
        fitTimer=tic;
        [separableFit,fullFit]=cerra_fit_model_pair(method,Yobserved,observed, ...
            foldCfg,basis,cfg.stage3.optimizer,cfg.seed.optimizer+1009*fold.foldID+J,warm);
        fitSeconds=toc(fitTimer);
        checkpoint=struct('version',string(cfg.version),'method',label,'J',J, ...
            'boundaryFactor',boundaryFactor, ...
            'foldID',fold.foldID,'separableFit',separableFit,'fullFit',fullFit, ...
            'fitSeconds',fitSeconds);
        save(fitCheckpointFile,'checkpoint','-v7.3');
    end
    predictionTimer=tic;
    prediction=cerra_predict_fit(method,Yobserved,observed,target,fullFit,foldCfg,basis);
    predictionSeconds=toc(predictionTimer);
    sites=subset.siteTable(targetIndex,:);nTarget=numel(targetIndex);
    metrics=cell(nTarget,1);predictions=cell(nTarget,1);
    for s=1:nTarget
        nearest=min(sqrt(sum((observed.xyKm-target.xyKm(s,:)).^2,2)));
        value=eq9_prediction_metrics(Ytarget(:,s),prediction.mean(:,s), ...
            prediction.observationVariance(:,s),cfg.cv.nominalCoverage);
        metrics{s}=table(label,fold.foldID,string(sites.stationID(s)), ...
            sites.gridRow(s),sites.gridColumn(s),sites.latitude(s), ...
            sites.longitude(s),nearest,value.rmse,value.mae,value.correlation, ...
            value.nlpd,value.crps,value.coverage,value.meanIntervalWidth, ...
            'VariableNames',{'method','foldID','targetStation','gridRow', ...
            'gridColumn','latitude','longitude','nearestTrainingDistanceKm', ...
            'rmse','mae','correlation','nlpd','crps','coverage95', ...
            'meanIntervalWidth95'});
        T=size(Ytarget,1);predictions{s}=table(repmat(label,T,1), ...
            repmat(fold.foldID,T,1),repmat(string(sites.stationID(s)),T,1), ...
            subset.timeIndex,subset.relativeHours,Ytarget(:,s),prediction.mean(:,s), ...
            prediction.observationVariance(:,s), ...
            'VariableNames',{'method','foldID','targetStation','timeIndex', ...
            'relativeHours','truthUWindMps','predictionUWindMps', ...
            'observationVariance'});
    end
    metrics=vertcat(metrics{:});predictions=vertcat(predictions{:});
    nScalar=numel(Yobserved);details=fullFit.details;
    if method=="hsgp"
        minCondition=details.minimumFeatureReciprocalCondition;
        maxJitter=details.maximumFeatureJitter;featureRank=details.hsgpFeatureRank;
        rankDef=details.rankDeficientDirectionsBeforeNugget;
    else
        minCondition=NaN;maxJitter=details.maximumSpectralJitter;
        featureRank=NaN;rankDef=NaN;
    end
    fitDiagnostics=table(label,fold.foldID,boundaryFactor,J,J^2, ...
        numel(observedIndex),nTarget, ...
        fullFit.objective,fullFit.objective/nScalar,fullFit.theta.signalVariance, ...
        fullFit.theta.alpha,fullFit.theta.beta,fullFit.theta.epsilon, ...
        fullFit.theta.noiseVariance,foldCfg.bounds.noiseVariance(1), ...
        varianceReference,fullFit.convergenceCertified,fullFit.boundaryHit, ...
        featureRank,rankDef,minCondition,maxJitter,fitSeconds,predictionSeconds, ...
        cerra_worker_id(),'VariableNames',{'method','foldID','boundaryFactor','J','M', ...
        'nTrainingSites','nTargetSites','objective','objectivePerObservation', ...
        'signalVariance','alphaPer100Km','betaPerSixHours','epsilon', ...
        'noiseVariance','trainingOnlyNuggetFloor','residualVarianceReference', ...
        'convergenceCertified','boundaryHit','featureRank', ...
        'rankDeficientDirectionsBeforeNugget','minimumReciprocalCondition', ...
        'maximumJitter','fitSeconds','predictionSeconds','workerID'});
    checks=table(["indices disjoint";"finite predictions"; ...
        "positive predictive variance";"imaginary residue controlled"], ...
        [isempty(intersect(observedIndex,targetIndex)); ...
        all(isfinite(prediction.mean),'all'); ...
        all(prediction.observationVariance>0,'all'); ...
        prediction.maximumImaginaryPrediction<=cfg.cv.maximumAllowedImaginary], ...
        'VariableNames',{'check','passed'});
    checks.method=repmat(label,height(checks),1);checks.foldID=repmat(fold.foldID,height(checks),1);
    timing=table(label,fold.foldID,boundaryFactor,J,J^2,fitSeconds,predictionSeconds, ...
        toc(timerValue),cerra_worker_id(),'VariableNames',{'method','foldID', ...
        'boundaryFactor','J','M','fitSeconds','predictionSeconds', ...
        'taskElapsedSeconds','workerID'});
    task=struct('version',string(cfg.version),'method',label,'J',J, ...
        'boundaryFactor',boundaryFactor, ...
        'metrics',metrics,'predictions',predictions,'fitDiagnostics',fitDiagnostics, ...
        'checks',checks,'timing',timing,'fullFit',fullFit, ...
        'separableFit',separableFit,'observedIndex',observedIndex, ...
        'targetIndex',targetIndex);
    save(taskFile,'task','-v7.3');
    fprintf('%s fold %d complete in %.1f min.\n',label,fold.foldID,toc(timerValue)/60);
end

