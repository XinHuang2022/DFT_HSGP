function [summary,bySite]=cerra_dense_prediction_summary(method,M,nTraining, ...
        truth,prediction,targetSiteTable,fit,cfg)
%CERRA_DENSE_PREDICTION_SUMMARY Aggregate and sitewise held-out metrics.

    metric=eq9_prediction_metrics(truth(:),prediction.mean(:), ...
        prediction.observationVariance(:),cfg.cv.nominalCoverage);
    summary=table(string(method),M,nTraining,metric.rmse,metric.mae, ...
        metric.correlation,metric.nlpd,metric.crps,metric.coverage, ...
        metric.meanIntervalWidth,fit.objective/(nTraining*size(truth,1)),fit.elapsedSeconds, ...
        fit.convergenceCertified,fit.boundaryHit,fit.theta.signalVariance, ...
        fit.theta.alpha,fit.theta.beta,fit.theta.epsilon,fit.theta.noiseVariance, ...
        'VariableNames',{'method','M','nTrainingSites','pooledRmse','pooledMae', ...
        'correlation','nlpd','crps','coverage95','meanIntervalWidth', ...
        'objectivePerObservation','fitSeconds','convergenceCertified','boundaryHit', ...
        'signalVariance','alphaPer100Km','betaPerSixHours','epsilon','noiseVariance'});
    nTarget=size(truth,2);rows=cell(nTarget,1);
    for j=1:nTarget
        point=cerra_point_metrics(truth(:,j),prediction.mean(:,j));
        rows{j}=table(string(method),M,nTraining,string(targetSiteTable.stationID(j)), ...
            targetSiteTable.latitude(j),targetSiteTable.longitude(j), ...
            point.rmse,point.mae,point.correlation, ...
            'VariableNames',{'method','M','nTrainingSites','stationID', ...
            'latitude','longitude','rmse','mae','correlation'});
    end
    bySite=vertcat(rows{:});
end
