function [separableFit, fullFit] = cerra_fit_model_pair(method, ...
        Yobserved, observed, foldCfg, basis, optimizer, seed, warmTheta)
%CERRA_FIT_MODEL_PAIR Fit separable then nonseparable Equation-9 models.

    if nargin < 8, warmTheta = []; end
    method = lower(string(method));
    if method == "exact"
        separableFit = fit_cerra_eq9_model(Yobserved, ...
            observed.xyCovariance, observed.design, foldCfg, 1, ...
            optimizer, seed + 1, [], warmTheta);
        initial = separableFit.theta;
        initial.epsilon = min(foldCfg.bounds.epsilon(2), ...
            max(foldCfg.bounds.epsilon(1), foldCfg.start.epsilon));
        fullOptimizer = optimizer;
        fullOptimizer.additionalStartZ = eq9_pack_parameters(initial, foldCfg);
        fullFit = fit_cerra_eq9_model(Yobserved, ...
            observed.xyCovariance, observed.design, foldCfg, [], ...
            fullOptimizer, seed + 2, [], initial);
    elseif method == "hsgp"
        separableFit = fit_cerra_eq9_hsgp(Yobserved, ...
            observed.xyCovariance, observed.design, foldCfg, basis, ...
            warmTheta, 1, [], optimizer, seed + 1);
        initial = separableFit.theta;
        initial.epsilon = min(foldCfg.bounds.epsilon(2), ...
            max(foldCfg.bounds.epsilon(1), foldCfg.start.epsilon));
        fullFit = fit_cerra_eq9_hsgp(Yobserved, ...
            observed.xyCovariance, observed.design, foldCfg, basis, ...
            initial, [], [], optimizer, seed + 2);
    else
        error('Unknown method: %s', method);
    end
end

