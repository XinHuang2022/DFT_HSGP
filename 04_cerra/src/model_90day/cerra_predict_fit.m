function prediction = cerra_predict_fit(method, Yobserved, observed, ...
        target, fit, cfg, basis)
%CERRA_PREDICT_FIT Dispatch exact or HSGP held-site reconstruction.

    if lower(string(method)) == "exact"
        prediction = predict_cerra_eq9(Yobserved, ...
            observed.xyCovariance, target.xyCovariance, ...
            observed.design, target.design, fit, cfg);
    else
        prediction = predict_cerra_eq9_hsgp(Yobserved, ...
            observed.xyCovariance, target.xyCovariance, ...
            observed.design, target.design, fit, cfg, basis);
    end
end

