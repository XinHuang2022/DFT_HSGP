function summary=cerra_dense_hsgp_start_task(cfg,referenceFile,M,startID)
%CERRA_DENSE_HSGP_START_TASK One independently checkpointed HSGP start.

    taskDir=fullfile(cfg.paths.stage2Dir,'tasks');ensure_directory(taskDir);
    taskFile=fullfile(taskDir,sprintf('M_%04d_start_%02d.mat',M,startID));
    if isfile(taskFile)
        S=load(taskFile,'checkpoint');
        if isfield(S,'checkpoint')&&S.checkpoint.version==string(cfg.version)&& ...
                S.checkpoint.M==M&&S.checkpoint.startID==startID
            fprintf('Stage 2 M=%d start %d loaded from checkpoint.\n',M,startID);
            summary=S.checkpoint.summary;return;
        end
    end
    S=load(referenceFile,'reference');R=S.reference;
    basis=make_cerra_hsgp_basis(R.domainXy,cfg.hsgp.boundaryFactor,M,cfg);
    startTheta=cerra_independent_start_theta(R.exactFit.theta,cfg,startID, ...
        cfg.seed.optimizer+M);
    optimizer=cfg.stage2.singleStartOptimizer;
    timerValue=tic;
    fit=fit_cerra_eq9_hsgp(R.Yfull,R.fullObserved.xyCovariance, ...
        R.fullObserved.design,R.fullCfg,basis,startTheta,[],[],optimizer, ...
        cfg.seed.optimizer+1009*M+startID);
    elapsed=toc(timerValue);
    summary=table(M,startID,fit.objective,fit.objective/numel(R.Yfull), ...
        fit.convergenceCertified,fit.exitFlag,fit.boundaryHit, ...
        fit.totalFunctionEvaluations,fit.totalIterations,elapsed, ...
        fit.theta.signalVariance,fit.theta.alpha,fit.theta.beta, ...
        fit.theta.epsilon,fit.theta.noiseVariance,cerra_worker_id(), ...
        'VariableNames',{'M','startID','objective','objectivePerObservation', ...
        'convergenceCertified','exitFlag','boundaryHit','functionEvaluations', ...
        'iterations','fitSeconds','signalVariance','alphaPer100Km', ...
        'betaPerSixHours','epsilon','noiseVariance','workerID'});
    checkpoint=struct('version',string(cfg.version),'M',M,'startID',startID, ...
        'basis',basis,'fit',fit,'summary',summary);
    save(taskFile,'checkpoint','-v7.3');
    fprintf('Stage 2 M=%d start %d complete in %.1f min.\n',M,startID,elapsed/60);
end
