function summary=cerra_dense_exact_start_task(cfg,referenceFile,nCoarse,startID)
%CERRA_DENSE_EXACT_START_TASK One checkpointed exact Equation-9 start.

    taskDir=fullfile(cfg.paths.stage3Dir,'tasks');ensure_directory(taskDir);
    taskFile=fullfile(taskDir,sprintf('n_%04d_start_%02d.mat',nCoarse,startID));
    if isfile(taskFile)
        S=load(taskFile,'checkpoint');
        if isfield(S,'checkpoint')&&S.checkpoint.version==string(cfg.version)&& ...
                S.checkpoint.nCoarse==nCoarse&&S.checkpoint.startID==startID
            fprintf('Stage 3 exact n=%d start %d loaded from checkpoint.\n', ...
                nCoarse,startID);summary=S.checkpoint.summary;return;
        end
    end
    S=load(referenceFile,'reference');R=S.reference;
    observedIndex=R.split.coarseOrder(1:nCoarse);
    [observed,~]=cerra_fold_geometry(R.contract,observedIndex, ...
        R.targetIndex,cfg);
    Y=R.contract.U(:,observedIndex);
    [fitCfg,varianceReference]=cerra_fold_config(cfg,Y,observed.xyKm, ...
        cfg.stage3.singleStartOptimizer);
    if nCoarse==cfg.stage1.referenceExactSize&&startID==1
        fit=R.exactFit;elapsed=fit.elapsedSeconds;
    else
        startTheta=cerra_independent_start_theta(R.exactFit.theta,cfg,startID, ...
            cfg.seed.optimizer+31*nCoarse);
        timerValue=tic;
        fit=fit_cerra_eq9_model(Y,observed.xyCovariance,observed.design,fitCfg, ...
            [],cfg.stage3.singleStartOptimizer, ...
            cfg.seed.optimizer+1009*nCoarse+startID,[],startTheta);
        elapsed=toc(timerValue);
    end
    summary=table(nCoarse,startID,fit.objective,fit.objective/numel(Y), ...
        fit.convergenceCertified,fit.exitFlag,fit.boundaryHit, ...
        fit.totalFunctionEvaluations,fit.totalIterations,elapsed, ...
        varianceReference,fit.theta.signalVariance,fit.theta.alpha,fit.theta.beta, ...
        fit.theta.epsilon,fit.theta.noiseVariance,cerra_worker_id(), ...
        'VariableNames',{'nCoarseSites','startID','objective', ...
        'objectivePerObservation','convergenceCertified','exitFlag','boundaryHit', ...
        'functionEvaluations','iterations','fitSeconds','residualVarianceReference', ...
        'signalVariance','alphaPer100Km','betaPerSixHours','epsilon', ...
        'noiseVariance','workerID'});
    checkpoint=struct('version',string(cfg.version),'nCoarse',nCoarse, ...
        'startID',startID,'observedIndex',observedIndex,'fitCfg',fitCfg, ...
        'fit',fit,'summary',summary);
    save(taskFile,'checkpoint','-v7.3');
    fprintf('Stage 3 exact n=%d start %d complete in %.1f min.\n', ...
        nCoarse,startID,elapsed/60);
end
