function report=run_cerra_dense_preflight(cfg)
%RUN_CERRA_DENSE_PREFLIGHT Validate data, split, basis and reduced-rank branch.

    if nargin<1,cfg=cerra_northsea_config();end
    outputDir=fullfile(cfg.paths.resultsDir,'preflight');ensure_directory(outputDir);
    contract=load_cerra_wind_data(cfg);split=make_cerra_dense_split(contract,cfg);
    domainXy=(contract.xyKm-mean(contract.xyKm,1))/cfg.spatial.coordinateScaleKm;
    basis=make_cerra_hsgp_basis(domainXy,cfg.hsgp.boundaryFactor, ...
        min(cfg.hsgp.candidateM),cfg);
    Phi=cerra_hsgp_features(domainXy(split.fullTrainingIndex,:),basis);
    gramTimer=tic;G=Phi'*Phi;gramSeconds=toc(gramTimer);
    gramReciprocalCondition=rcond((G+G')/2);
    numericalFeatureRank=rank(Phi);
    checks=[height(contract.siteTable)==cfg.data.expectedFullStations; ...
        size(contract.U,1)==cfg.data.expectedTimePoints; ...
        numel(split.testIndex)==cfg.split.nTestSites; ...
        isempty(intersect(split.testIndex,split.fullTrainingIndex)); ...
        max(cfg.hsgp.candidateM)<numel(split.fullTrainingIndex); ...
        all(isfinite(G),'all');numericalFeatureRank==basis.nFeatures];
    report=table(string(cfg.version),size(contract.U,1),height(contract.siteTable), ...
        numel(split.fullTrainingIndex),numel(split.testIndex),basis.nFeatures, ...
        basis.maximumIndexByDimension(1),basis.maximumIndexByDimension(2), ...
        basis.maximumRadialFrequency,gramSeconds,gramReciprocalCondition, ...
        numericalFeatureRank,all(checks), ...
        'VariableNames',{'version','nTimePoints','nFullSites','nTrainingSites', ...
        'nTestSites','smokeM','maximumIndexX','maximumIndexY', ...
        'maximumRadialFrequency','gramSeconds','gramReciprocalCondition', ...
        'numericalFeatureRank','allChecksPassed'});
    writetable(report,fullfile(outputDir,'preflight_summary.csv'));
    if ~all(checks),error('Dense CERRA preflight failed.');end
    fprintf(['Preflight passed: T=%d, full sites=%d, training=%d, test=%d, ' ...
        'M=%d Gram %.1f s.\n'],size(contract.U,1),height(contract.siteTable), ...
        numel(split.fullTrainingIndex),numel(split.testIndex),basis.nFeatures, ...
        gramSeconds);
end
