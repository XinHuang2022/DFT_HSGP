function result=run_cerra_dense_stage1_fixed_theta_screen(cfg)
%RUN_CERRA_DENSE_STAGE1_FIXED_THETA_SCREEN Exact-250 reference and HSGP M screen.

    if nargin<1,cfg=cerra_northsea_config();end
    ensure_directory(cfg.paths.stage1Dir);
    ensure_directory(fullfile(cfg.paths.stage1Dir,'tasks'));
    ensure_directory(fullfile(cfg.paths.stage1Dir,'figures'));
    referenceFile=fullfile(cfg.paths.stage1Dir,'reference.mat');
    if isfile(referenceFile)
        S=load(referenceFile,'reference');reference=S.reference;
        compatible=isfield(reference,'version') && ...
            reference.version==string(cfg.version) && ...
            size(reference.contract.U,1)==cfg.data.expectedTimePoints;
        if ~compatible,error('Stage 1 reference checkpoint is incompatible.');end
        fprintf('Stage 1 reference loaded from checkpoint.\n');
    else
        contract=load_cerra_wind_data(cfg);
        split=make_cerra_dense_split(contract,cfg);
        [siteRoles,coarseMembership]=cerra_dense_split_tables(contract,split);
        writetable(siteRoles,fullfile(cfg.paths.stage1Dir,'site_role_manifest.csv'));
        writetable(coarseMembership,fullfile(cfg.paths.stage1Dir, ...
            'nested_coarse_subset_manifest.csv'));
        targetIndex=split.testIndex;
        exactIndex=split.coarseOrder(1:cfg.stage1.referenceExactSize);
        [exactObserved,target]=cerra_fold_geometry(contract,exactIndex,targetIndex,cfg);
        Yexact=contract.U(:,exactIndex);Ytarget=contract.U(:,targetIndex);
        [exactCfg,exactVarianceReference]=cerra_fold_config(cfg,Yexact, ...
            exactObserved.xyKm,cfg.stage1.optimizer);
        fprintf('Stage 1 exact n=%d reference fit starting.\n',numel(exactIndex));
        exactFit=fit_cerra_eq9_model(Yexact,exactObserved.xyCovariance, ...
            exactObserved.design,exactCfg,[],cfg.stage1.optimizer, ...
            cfg.seed.optimizer+11,[],[]);
        exactPrediction=cerra_predict_fit("exact",Yexact,exactObserved, ...
            target,exactFit,exactCfg,[]);
        exactMetric=eq9_prediction_metrics(Ytarget(:),exactPrediction.mean(:), ...
            exactPrediction.observationVariance(:),cfg.cv.nominalCoverage);
        fullIndex=split.fullTrainingIndex;
        [fullObserved,fullTarget]=cerra_fold_geometry(contract,fullIndex, ...
            targetIndex,cfg);
        Yfull=contract.U(:,fullIndex);
        [fullCfg,fullVarianceReference]=cerra_fold_config(cfg,Yfull, ...
            fullObserved.xyKm,cfg.stage2.singleStartOptimizer);
        lambdaAll=eq9_fourier_frequencies(size(Yfull,1));
        selected=unique(round(linspace(1,numel(lambdaAll), ...
            cfg.hsgp.auditFrequencyCount)));
        auditLambda=lambdaAll(selected);
        exactSignal=eq9_frequency_covariances(exactFit.theta, ...
            exactObserved.xyCovariance,auditLambda,exactCfg,false);
        domainXy=(contract.xyKm-mean(contract.xyKm,1))./ ...
            cfg.spatial.coordinateScaleKm;
        reference=struct('version',string(cfg.version),'contract',contract, ...
            'split',split,'targetIndex',targetIndex,'Ytarget',Ytarget, ...
            'targetSiteTable',contract.siteTable(targetIndex,:), ...
            'exactIndex',exactIndex,'exactObserved',exactObserved, ...
            'Yexact',Yexact,'exactCfg',exactCfg,'exactFit',exactFit, ...
            'exactPrediction',exactPrediction,'exactMetric',exactMetric, ...
            'fullIndex',fullIndex,'fullObserved',fullObserved, ...
            'fullTarget',fullTarget,'Yfull',Yfull,'fullCfg',fullCfg, ...
            'auditLambda',auditLambda,'exactSignal',exactSignal, ...
            'domainXy',domainXy,'exactVarianceReference',exactVarianceReference, ...
            'fullVarianceReference',fullVarianceReference);
        save(referenceFile,'reference','-v7.3');
        fprintf('Stage 1 reference saved.\n');
    end
    Mvalues=cfg.hsgp.candidateM(:);
    writetable(table(Mvalues,repmat(cfg.hsgp.boundaryFactor,numel(Mvalues),1), ...
        'VariableNames',{'M','boundaryFactor'}), ...
        fullfile(cfg.paths.stage1Dir,'task_plan.csv'));
    tasks=cell(numel(Mvalues),1);
    [parallelUsed,poolWorkers]=cerra_open_pool(cfg,numel(Mvalues));
    if parallelUsed
        parfor q=1:numel(Mvalues)
            tasks{q}=cerra_dense_stage1_task(cfg,referenceFile,Mvalues(q));
        end
    else
        for q=1:numel(Mvalues)
            tasks{q}=cerra_dense_stage1_task(cfg,referenceFile,Mvalues(q));
        end
    end
    summaryParts=cellfun(@(x)x.summary,tasks,'UniformOutput',false);
    bySiteParts=cellfun(@(x)x.bySite,tasks,'UniformOutput',false);
    summary=vertcat(summaryParts{:});
    bySite=vertcat(bySiteParts{:});
    writetable(summary,fullfile(cfg.paths.stage1Dir,'fixed_theta_screen.csv'));
    writetable(bySite,fullfile(cfg.paths.stage1Dir,'fixed_theta_metrics_by_site.csv'));
    referenceSummary=table(string(cfg.version),cfg.data.expectedTimePoints, ...
        height(reference.contract.siteTable),numel(reference.fullIndex), ...
        numel(reference.targetIndex),numel(reference.exactIndex), ...
        reference.exactMetric.rmse,reference.exactMetric.mae, ...
        reference.exactMetric.coverage,reference.exactFit.objective, ...
        reference.exactFit.elapsedSeconds,parallelUsed,poolWorkers, ...
        'VariableNames',{'version','nTimePoints','nFullSites','nFullTrainingSites', ...
        'nTestSites','nReferenceExactSites','exactReferenceRmse', ...
        'exactReferenceMae','exactReferenceCoverage95','exactReferenceObjective', ...
        'exactReferenceFitSeconds','parallelUsed','poolWorkers'});
    writetable(referenceSummary,fullfile(cfg.paths.stage1Dir,'run_summary.csv'));
    make_cerra_dense_stage1_figure(summary,reference.exactMetric.rmse,cfg);
    save(fullfile(cfg.paths.stage1Dir,'complete_result.mat'),'cfg','summary', ...
        'bySite','referenceSummary','-v7.3');
    result=struct('summary',summary,'bySite',bySite,'runSummary',referenceSummary);
end
