function report = preflight_cerra_package(experimentRoot, cfg, windowLabel)
%PREFLIGHT_CERRA_PACKAGE Validate local data, split, and model interfaces.

    contract = load_cerra_wind_data(cfg);
    split = make_cerra_dense_split(contract, cfg);
    retainedPath = fullfile(experimentRoot, 'input', 'retained', ...
        "fixed_rank_" + windowLabel, 'stage1_fixed_theta_dense_screen', ...
        'site_role_manifest.csv');
    retained = readtable(retainedPath, 'VariableNamingRule', 'preserve');
    retainedTest = string(retained.stationID( ...
        string(retained.role) == "held_out_test"));
    generatedTest = string(contract.siteTable.stationID(split.testIndex));
    sameStationOrder = isequal(string(retained.stationID), ...
        string(contract.siteTable.stationID));
    sameTestSet = isequal(sort(retainedTest), sort(generatedTest));
    interfaceReport = run_cerra_dense_preflight(cfg);

    check = ["finite extracted wind matrix"; "retained station order"; ...
        "retained 300-site evaluation set"; "dense HSGP interface checks"];
    passed = [all(isfinite(contract.U), 'all') && ...
        size(contract.U, 2) == 3701; sameStationOrder; sameTestSet; ...
        interfaceReport.allChecksPassed];
    detail = [string(sprintf('%d-by-%d', size(contract.U))); ...
        string(sprintf('%d sites', height(contract.siteTable))); ...
        string(sprintf('%d evaluation sites', numel(split.testIndex))); ...
        string(sprintf('M=%d smoke basis', interfaceReport.smokeM))];
    report = table(check, passed, detail);
    disp(report);
    if ~all(passed), error('CERRA reproducibility-package preflight failed.'); end
end
