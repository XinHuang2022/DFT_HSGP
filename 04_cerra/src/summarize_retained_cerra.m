function result = summarize_retained_cerra(experimentRoot)
%SUMMARIZE_RETAINED_CERRA Read the preserved 31-day and 90-day summaries.

    retainedRoot = fullfile(experimentRoot, 'input', 'retained');
    result.summary31Day = readtable(fullfile(retainedRoot, ...
        'fixed_rank_31day', 'stage3_coarse_exact_baselines', ...
        'accuracy_cost_frontier.csv'), 'VariableNamingRule', 'preserve');
    result.summary90Day = readtable(fullfile(retainedRoot, ...
        'fixed_rank_90day', 'stage3_coarse_exact_baselines', ...
        'accuracy_cost_frontier.csv'), 'VariableNamingRule', 'preserve');
    result.hsgp31Day = result.summary31Day(startsWith( ...
        string(result.summary31Day.method), "hsgp_full"), :);
    result.hsgp90Day = result.summary90Day(startsWith( ...
        string(result.summary90Day.method), "hsgp_full"), :);
end
