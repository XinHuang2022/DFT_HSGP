function report = preflight_fuentes_simulation(cfg)
%PREFLIGHT_FUENTES_SIMULATION Validate inputs without fitting the model.

    requiredFiles = {cfg.oracleResultFile, cfg.fittedParameterFile, ...
        cfg.trustedPredictionFile};
    for j = 1:numel(requiredFiles)
        assert(isfile(requiredFiles{j}), ...
            'Required Fuentes input is missing: %s', requiredFiles{j});
    end
    assert(isfolder(cfg.sourceSuiteRoot), ...
        'Model source directory is missing: %s', cfg.sourceSuiteRoot);
    assert(all(diff(cfg.candidateJ) > 0), ...
        'Candidate basis sizes must be strictly increasing.');
    assert(cfg.klPerFittingSiteTolerance > 0, ...
        'The KL tolerance must be positive.');

    metadata = load(cfg.oracleResultFile, 'result');
    requiredFields = {'sourceCfg','sites','configurations', ...
        'foldManifest','klRankProfiles'};
    for j = 1:numel(requiredFields)
        assert(isfield(metadata.result, requiredFields{j}), ...
            'Reference metadata lack field %s.', requiredFields{j});
    end

    P = [2.0, 0.3; 0.3, 1.0];
    Q = [1.8, 0.2; 0.2, 1.2];
    [zeroDiscrepancy, ~, ~] = gaussian_kl_covariance(P, P, 0.5);
    [positiveDiscrepancy, ~, ~] = gaussian_kl_covariance(P, Q, 1.0);
    assert(abs(zeroDiscrepancy) < 1e-10);
    assert(positiveDiscrepancy > 0);

    report = table(string(version), cfg.nReplicates, ...
        height(metadata.result.configurations), ...
        height(metadata.result.klRankProfiles), ...
        cfg.klPerFittingSiteTolerance, true, ...
        'VariableNames', {'matlabVersion','numberOfReplicates', ...
        'numberOfConfigurations','numberOfReferenceProfileRows', ...
        'klTolerancePerFittingSite','passed'});
end

