function task = era5_stage2_j_task(cfg, referenceFile, J)
%ERA5_STAGE2_J_TASK Refit theta with one HSGP basis and cross-audit engines.

    taskDir = fullfile(cfg.paths.stage2Dir,'tasks'); ensure_directory(taskDir);
    taskFile = fullfile(taskDir,sprintf('J_%03d.mat',J));
    if isfile(taskFile)
        S = load(taskFile,'task');
        if isfield(S,'task') && S.task.version == string(cfg.version)
            fprintf('Stage 2 J=%d loaded from checkpoint.\n',J); task=S.task; return;
        end
    end
    timerValue=tic; S=load(referenceFile,'reference'); R=S.reference;
    basis=make_era5_hsgp_basis(R.fullDomainXy,cfg.hsgp.boundaryFactor,J,cfg);
    [foldCfg,varianceReference]=era5_fold_config(cfg,R.Yobserved, ...
        R.observed.xyKm,cfg.stage2.optimizer);
    fitCheckpointFile=fullfile(taskDir,sprintf('J_%03d_fit.mat',J));
    fitLoaded=false;
    if isfile(fitCheckpointFile)
        C=load(fitCheckpointFile,'checkpoint');
        fitLoaded=isfield(C,'checkpoint') && ...
            C.checkpoint.version==string(cfg.version) && C.checkpoint.J==J;
    end
    if fitLoaded
        separableFit=C.checkpoint.separableFit;fullFit=C.checkpoint.fullFit;
        fprintf('Stage 2 J=%d fit loaded from checkpoint.\n',J);
    else
        [separableFit,fullFit]=era5_fit_model_pair("hsgp",R.Yobserved, ...
            R.observed,foldCfg,basis,cfg.stage2.optimizer, ...
            cfg.seed.optimizer+7001+J,R.exactFit.theta);
        checkpoint=struct('version',string(cfg.version),'J',J, ...
            'separableFit',separableFit,'fullFit',fullFit);
        save(fitCheckpointFile,'checkpoint','-v7.3');
    end
    hsgpPrediction=era5_predict_fit("hsgp",R.Yobserved,R.observed, ...
        R.target,fullFit,foldCfg,basis);
    exactAtHsgp=era5_fixed_theta_fit("exact",fullFit.theta,R.Yobserved, ...
        R.observed,foldCfg,[]);
    exactEnginePrediction=era5_predict_fit("exact",R.Yobserved,R.observed, ...
        R.target,exactAtHsgp,foldCfg,[]);
    hsgpMetric=era5_point_metrics(R.Ytarget(:),hsgpPrediction.mean(:));
    exactEngineMetric=era5_point_metrics(R.Ytarget(:),exactEnginePrediction.mean(:));
    nScalar=numel(R.Yobserved);
    summary=table(J,J^2,fullFit.objective,exactAtHsgp.objective, ...
        (fullFit.objective-exactAtHsgp.objective)/nScalar, ...
        hsgpMetric.rmse,exactEngineMetric.rmse,R.exactRmse, ...
        hsgpMetric.rmse-exactEngineMetric.rmse, ...
        fullFit.theta.signalVariance,fullFit.theta.alpha,fullFit.theta.beta, ...
        fullFit.theta.epsilon,fullFit.theta.noiseVariance, ...
        fullFit.convergenceCertified,fullFit.boundaryHit, ...
        fullFit.details.hsgpFeatureRank, ...
        fullFit.details.rankDeficientDirectionsBeforeNugget, ...
        varianceReference,toc(timerValue),era5_worker_id(), ...
        'VariableNames',{'J','M','hsgpObjective','exactObjectiveAtHsgpTheta', ...
        'hsgpMinusExactNllPerObservation','hsgpEngineRmse', ...
        'hsgpThetaExactEngineRmse','exactFitExactEngineRmse', ...
        'engineRmseDifference','signalVariance','alphaPer100Km', ...
        'betaPerSixHours','epsilon','noiseVariance','convergenceCertified', ...
        'boundaryHit','featureRank','rankDeficientDirectionsBeforeNugget', ...
        'residualVarianceReference','elapsedSeconds','workerID'});
    task=struct('version',string(cfg.version),'summary',summary,'basis',basis, ...
        'separableFit',separableFit,'fullFit',fullFit, ...
        'exactAtHsgp',exactAtHsgp,'hsgpPrediction',hsgpPrediction, ...
        'exactEnginePrediction',exactEnginePrediction);
    save(taskFile,'task','-v7.3');
    fprintf('Stage 2 J=%d complete: RMSE %.4f; engine difference %.4f.\n', ...
        J,hsgpMetric.rmse,summary.engineRmseDifference);
end
