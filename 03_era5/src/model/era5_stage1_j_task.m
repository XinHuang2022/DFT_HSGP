function task = era5_stage1_j_task(cfg, referenceFile, J)
%ERA5_STAGE1_J_TASK Same-theta covariance, likelihood, and prediction audit.

    taskDir = fullfile(cfg.paths.stage1Dir, 'tasks');
    ensure_directory(taskDir);
    taskFile = fullfile(taskDir, sprintf('J_%03d.mat', J));
    if isfile(taskFile)
        S = load(taskFile, 'task');
        if isfield(S, 'task') && S.task.version == string(cfg.version)
            fprintf('Stage 1 J=%d loaded from checkpoint.\n', J);
            task = S.task;
            return;
        end
    end
    timerValue = tic;
    S = load(referenceFile, 'reference');
    R = S.reference;
    basis = make_era5_hsgp_basis(R.fullDomainXy, ...
        cfg.hsgp.boundaryFactor, J, cfg);
    Phi = era5_hsgp_features(R.observed.xyCovariance, basis);
    weights = era5_hsgp_weights(R.exactFit.theta, ...
        R.auditLambda, basis, R.foldCfg);
    nFrequency = numel(R.auditLambda);
    latentError = zeros(nFrequency, 1);
    totalError = zeros(nFrequency, 1);
    diagonalRatio = zeros(nFrequency, 1);
    for q = 1:nFrequency
        approximation = era5_hsgp_covariance(Phi, Phi, ...
            weights(:, q), 0, true);
        exact = R.exactSignal(:, :, q);
        latentError(q) = norm(approximation - exact, 'fro') / ...
            max(norm(exact, 'fro'), eps);
        exactTotal = exact + R.exactFit.theta.noiseVariance * eye(size(exact));
        approximateTotal = approximation + ...
            R.exactFit.theta.noiseVariance * eye(size(exact));
        totalError(q) = norm(approximateTotal - exactTotal, 'fro') / ...
            max(norm(exactTotal, 'fro'), eps);
        diagonalRatio(q) = median(diag(approximation) ./ max(diag(exact), eps));
    end
    fixedFit = era5_fixed_theta_fit("hsgp", R.exactFit.theta, ...
        R.Yobserved, R.observed, R.foldCfg, basis);
    prediction = era5_predict_fit("hsgp", R.Yobserved, R.observed, ...
        R.target, fixedFit, R.foldCfg, basis);
    point = era5_point_metrics(R.Ytarget(:), prediction.mean(:));
    nScalar = numel(R.Yobserved);
    sorted = sort(latentError);
    p90 = sorted(max(1, ceil(0.9 * numel(sorted))));
    nllDelta = (fixedFit.objective - R.exactFit.objective) / nScalar;
    pass = p90 <= cfg.hsgp.acceptance.maximumP90LatentCovarianceError && ...
        max(latentError) <= cfg.hsgp.acceptance.maximumLatentCovarianceError && ...
        abs(nllDelta) <= cfg.hsgp.acceptance.maximumAbsoluteObjectiveDifferencePerObservation && ...
        median(diagonalRatio) >= cfg.hsgp.acceptance.minimumMedianDiagonalRatio && ...
        median(diagonalRatio) <= cfg.hsgp.acceptance.maximumMedianDiagonalRatio;
    summary = table(J, J^2, basis.boundaryFactor, median(latentError), ...
        p90, max(latentError), median(totalError), max(totalError), ...
        median(diagonalRatio), fixedFit.objective, R.exactFit.objective, ...
        nllDelta, point.rmse, R.exactRmse, point.rmse - R.exactRmse, ...
        pass, toc(timerValue), era5_worker_id(), 'VariableNames', ...
        {'J','M','boundaryFactor','medianLatentCovarianceError', ...
        'p90LatentCovarianceError','maximumLatentCovarianceError', ...
        'medianTotalCovarianceError','maximumTotalCovarianceError', ...
        'medianDiagonalRatio','hsgpObjectiveAtExactTheta','exactObjective', ...
        'nllDifferencePerObservation','hsgpSameThetaRmse','exactRmse', ...
        'rmseDifference','passesAudit','elapsedSeconds','workerID'});
    frequency = table(repmat(J,nFrequency,1), repmat(J^2,nFrequency,1), ...
        (1:nFrequency).', R.auditLambda(:), latentError, totalError, ...
        diagonalRatio, 'VariableNames', {'J','M','auditFrequencyIndex', ...
        'lambda','latentCovarianceError','totalCovarianceError','diagonalRatio'});
    task.version = string(cfg.version);
    task.summary = summary;
    task.frequency = frequency;
    task.prediction = prediction;
    task.basis = basis;
    task.fixedFit = fixedFit;
    save(taskFile, 'task', '-v7.3');
    fprintf('Stage 1 J=%d complete: pass=%d, p90 error=%.4g.\n', J, pass, p90);
end
