function result = summarize_retained_pacific(experimentRoot)
%SUMMARIZE_RETAINED_PACIFIC Read preserved manuscript-facing summaries.

    fixedRoot = fullfile(experimentRoot, 'input', 'retained', 'fixed_rank');
    adaptiveRoot = fullfile(experimentRoot, 'input', 'retained', ...
        'adaptive_rank');
    result.fixedMethodSummary = readtable(fullfile(fixedRoot, ...
        'method_summary.csv'), 'VariableNamingRule', 'preserve');
    result.adaptiveMethodSummary = readtable(fullfile(adaptiveRoot, ...
        'method_summary.csv'), 'VariableNamingRule', 'preserve');
    result.adaptiveRankSummary = readtable(fullfile(adaptiveRoot, ...
        'rank_summary_by_fold.csv'), 'VariableNamingRule', 'preserve');
    result.adaptiveTimingSummary = readtable(fullfile(adaptiveRoot, ...
        'timing_summary.csv'), 'VariableNamingRule', 'preserve');
end
