function candidate = fit_pacific_subset_candidate(cfg, subset, ...
        observedIndex, outerGeometry, foldID, candidateID, nuggetRule)
%FIT_PACIFIC_SUBSET_CANDIDATE One training-only covariance prefit.

% The site subset uses coordinates and outer-training membership only.
% After the subset fit, one exact all-training objective evaluation profiles
% the mean and provides a common, response-based selection criterion across
% prespecified subset seeds.  Outer target responses are never accessed.

    nParameter = min(cfg.scalable.parameterSubsetSize, ...
        numel(observedIndex));
    selectionSeed = cfg.scalable.subsetSeed + 1009 * foldID + ...
        7919 * (candidateID - 1);
    selection = make_pacific_parameter_subset(subset.siteTable, ...
        observedIndex, nParameter, cfg.scalable.localPairFraction, ...
        selectionSeed);
    parameterIndex = selection.index;
    [present, parameterPosition] = ismember(parameterIndex, observedIndex);
    if ~all(present)
        error('Parameter subset is not contained in outer training.');
    end
    parameterGeometry.xyCovariance = ...
        outerGeometry.xyCovariance(parameterPosition, :);
    parameterGeometry.xyMean = outerGeometry.xyMean(parameterPosition, :);
    parameterGeometry.design = make_pacific_mean_design( ...
        size(subset.U, 1), parameterGeometry.xyMean);
    Yparameter = subset.U(:, parameterIndex);
    [varianceReference, ~, ~] = ...
        pacific_empirical_residual_variance(Yparameter, ...
        subset.xyKm(parameterIndex, :));
    fitCfg = cfg;
    selectedFloor = cfg.bounds.noiseVariance(1);
    if nuggetRule.mode == "scale_adaptive_floor"
        selectedFloor = max(selectedFloor, ...
            nuggetRule.residualVarianceFraction * varianceReference);
        fitCfg.bounds.noiseVariance(1) = selectedFloor;
    end

    seed = cfg.seed.optimizer + 10007 * foldID + 503 * candidateID;
    separableSubset = fit_pacific_eq9_model(Yparameter, ...
        parameterGeometry.xyCovariance, parameterGeometry.design, ...
        fitCfg, 1, cfg.optimizer, seed + 1, [], []);
    embeddedTheta = separableSubset.theta;
    embeddedTheta.epsilon = fitCfg.bounds.epsilon(2);
    fullOptimizer = cfg.optimizer;
    fullOptimizer.additionalStartZ = ...
        pacific_pack_constrained_parameters(embeddedTheta, fitCfg, [], []);
    fullSubset = fit_pacific_eq9_model(Yparameter, ...
        parameterGeometry.xyCovariance, parameterGeometry.design, ...
        fitCfg, [], fullOptimizer, seed + 2, [], []);

    Yobserved = subset.U(:, observedIndex);
    fullAllTraining = pacific_refit_mean_at_theta(Yobserved, ...
        outerGeometry.xyCovariance, outerGeometry.design, ...
        fullSubset.theta, cfg);
    separableAllTraining = pacific_refit_mean_at_theta(Yobserved, ...
        outerGeometry.xyCovariance, outerGeometry.design, ...
        separableSubset.theta, cfg);

    row = table(foldID, candidateID, selectionSeed, nParameter, ...
        varianceReference, selectedFloor, fullSubset.objective, ...
        fullAllTraining.objective, separableSubset.objective, ...
        separableAllTraining.objective, fullSubset.theta.signalVariance, ...
        fullSubset.theta.alpha, fullSubset.theta.beta, ...
        fullSubset.theta.epsilon, fullSubset.theta.noiseVariance, ...
        fullSubset.convergenceCertified, ...
        separableSubset.convergenceCertified, ...
        fullSubset.elapsedSeconds, separableSubset.elapsedSeconds, ...
        'VariableNames', {'foldID', 'subsetCandidateID', ...
        'subsetSelectionSeed', 'nParameterSites', ...
        'residualVarianceReference', 'noiseVarianceFloor', ...
        'fullSubsetObjective', 'fullAllTrainingObjective', ...
        'separableSubsetObjective', 'separableAllTrainingObjective', ...
        'signalVariance', 'alphaPer100Km', 'betaPerSixHours', ...
        'epsilon', 'noiseVariance', 'fullConvergenceCertified', ...
        'separableConvergenceCertified', 'fullSubsetFitSeconds', ...
        'separableSubsetFitSeconds'});
    manifest = selection.table;
    manifest.foldID = repmat(foldID, height(manifest), 1);
    manifest.subsetCandidateID = repmat(candidateID, height(manifest), 1);

    candidate.row = row;
    candidate.manifest = manifest;
    candidate.parameterIndex = parameterIndex;
    candidate.varianceReference = varianceReference;
    candidate.noiseVarianceFloor = selectedFloor;
    candidate.fullFitSubset = fullSubset;
    candidate.separableFitSubset = separableSubset;
    candidate.fullFit = fullAllTraining;
    candidate.separableFit = separableAllTraining;
end
