function task = run_pacific_hsgp_fold(cfg, subset, targetIndex, ...
        foldID, basis)
%RUN_PACIFIC_HSGP_FOLD Fit and score one held-out-location fold.

    foldTimer = tic;
    targetIndex = unique(targetIndex(:), 'stable');
    nSites = size(subset.U, 2);
    observedIndex = setdiff((1:nSites)', targetIndex, 'stable');
    Yobserved = subset.U(:, observedIndex);
    Ytarget = subset.U(:, targetIndex);
    [observed, target] = fold_geometry(subset, observedIndex, ...
        targetIndex, cfg);

    [varianceReference, ~, ~] = pacific_empirical_residual_variance( ...
        Yobserved, subset.xyKm(observedIndex, :));
    numericalFloor = cfg.bounds.noiseVariance(1);
    adaptiveFloor = cfg.hsgp.nuggetResidualVarianceFraction * ...
        varianceReference;
    foldCfg = cfg;
    foldCfg.bounds.noiseVariance(1) = max(numericalFloor, adaptiveFloor);
    if foldCfg.bounds.noiseVariance(1) >= foldCfg.bounds.noiseVariance(2)
        error('Fold-specific nugget floor is not below its upper bound.');
    end
    fixedNoise = cfg.hsgp.fixedNoiseVariance;
    if ~isempty(fixedNoise) && fixedNoise < foldCfg.bounds.noiseVariance(1)
        error('Configured fixed nugget is below the training-only floor.');
    end
    seed = cfg.seed.optimizer + 1009 * foldID;

    separableTimer = tic;
    separableFit = fit_pacific_eq9_hsgp(Yobserved, ...
        observed.xyCovariance, observed.design, foldCfg, basis, [], 1, ...
        fixedNoise, foldCfg.hsgp.optimizer, seed + 1);
    separableSeconds = toc(separableTimer);
    initialTheta = separableFit.theta;
    initialTheta.epsilon = min(cfg.bounds.epsilon(2), ...
        max(cfg.bounds.epsilon(1), cfg.start.epsilon));
    fullTimer = tic;
    fullFit = fit_pacific_eq9_hsgp(Yobserved, ...
        observed.xyCovariance, observed.design, foldCfg, basis, ...
        initialTheta, [], fixedNoise, foldCfg.hsgp.optimizer, seed + 2);
    fullSeconds = toc(fullTimer);

    predictionTimer = tic;
    fullPrediction = predict_pacific_eq9_hsgp(Yobserved, ...
        observed.xyCovariance, target.xyCovariance, observed.design, ...
        target.design, fullFit, foldCfg, basis);
    fullPredictionSeconds = toc(predictionTimer);
    predictionTimer = tic;
    separablePrediction = predict_pacific_eq9_hsgp(Yobserved, ...
        observed.xyCovariance, target.xyCovariance, observed.design, ...
        target.design, separableFit, foldCfg, basis);
    separablePredictionSeconds = toc(predictionTimer);

    exactFull = [];
    exactSeparableObjective = NaN;
    exactFullObjective = NaN;
    exactPrediction = [];
    exactAuditSeconds = 0;
    exactPredictionSeconds = 0;
    if foldCfg.hsgp.auditExactAtFittedTheta
        exactTimer = tic;
        exactFull = pacific_refit_mean_at_theta(Yobserved, ...
            observed.xyCovariance, observed.design, fullFit.theta, foldCfg);
        exactSeparable = pacific_refit_mean_at_theta(Yobserved, ...
            observed.xyCovariance, observed.design, ...
            separableFit.theta, foldCfg);
        exactFullObjective = exactFull.objective;
        exactSeparableObjective = exactSeparable.objective;
        exactAuditSeconds = toc(exactTimer);
    end
    if foldCfg.hsgp.predictExactAtFittedTheta
        if isempty(exactFull)
            exactFull = pacific_refit_mean_at_theta(Yobserved, ...
                observed.xyCovariance, observed.design, ...
                fullFit.theta, foldCfg);
            exactFullObjective = exactFull.objective;
        end
        exactTimer = tic;
        exactPrediction = predict_pacific_eq9(Yobserved, ...
            observed.xyCovariance, target.xyCovariance, ...
            observed.design, target.design, exactFull, foldCfg);
        exactPredictionSeconds = toc(exactTimer);
    end

    nTarget = numel(targetIndex);
    targetSites = subset.siteTable(targetIndex, :);
    methodsPerTarget = 3 + ~isempty(exactPrediction);
    metricRows = cell(methodsPerTarget * nTarget, 1);
    predictionRows = cell(methodsPerTarget * nTarget, 1);
    cursor = 0;
    for j = 1:nTarget
        nearest = min(sqrt(sum((subset.xyKm(observedIndex, :) - ...
            subset.xyKm(targetIndex(j), :)) .^ 2, 2)));
        [metricRows, predictionRows, cursor] = append_probabilistic( ...
            metricRows, predictionRows, cursor, "hsgp_eq9", foldID, ...
            targetSites(j, :), nearest, subset, Ytarget(:, j), ...
            fullPrediction, j, fullFit.theta.noiseVariance, foldCfg);
        [metricRows, predictionRows, cursor] = append_probabilistic( ...
            metricRows, predictionRows, cursor, "hsgp_separable", ...
            foldID, targetSites(j, :), nearest, subset, Ytarget(:, j), ...
            separablePrediction, j, separableFit.theta.noiseVariance, ...
            foldCfg);
        if ~isempty(exactPrediction)
            [metricRows, predictionRows, cursor] = append_probabilistic( ...
                metricRows, predictionRows, cursor, ...
                "hsgp_theta_exact_engine", foldID, targetSites(j, :), ...
                nearest, subset, Ytarget(:, j), exactPrediction, j, ...
                fullFit.theta.noiseVariance, foldCfg);
        end
        cursor = cursor + 1;
        meanMetrics = pacific_point_metrics(Ytarget(:, j), ...
            fullPrediction.meanOnly(:, j));
        metricRows{cursor} = point_metric_row("mean_only", foldID, ...
            targetSites(j, :), nearest, meanMetrics);
        predictionRows{cursor} = mean_prediction_table(foldID, ...
            targetSites(j, :), subset, Ytarget(:, j), ...
            fullPrediction.meanOnly(:, j));
    end

    nScalar = size(Yobserved, 1) * numel(observedIndex);
    fitDiagnostics = [fit_row("hsgp_eq9", foldID, fullFit, ...
        exactFullObjective, nScalar, basis, foldCfg, ...
        varianceReference, observed.xyCovariance); ...
        fit_row("hsgp_separable", foldID, separableFit, ...
        exactSeparableObjective, nScalar, basis, foldCfg, ...
        varianceReference, observed.xyCovariance)];
    checks = implementation_checks(foldID, fullPrediction, ...
        separablePrediction, fullFit, separableFit, targetIndex, ...
        observedIndex, basis, foldCfg, exactFullObjective, nScalar);
    timing = table(foldID, current_worker_id(), numel(observedIndex), ...
        nTarget, separableSeconds, fullSeconds, ...
        separablePredictionSeconds, fullPredictionSeconds, ...
        exactAuditSeconds, exactPredictionSeconds, toc(foldTimer), ...
        'VariableNames', {'foldID', 'workerID', 'nTrainingSites', ...
        'nTargetSites', 'separableFitSeconds', 'fullFitSeconds', ...
        'separablePredictionSeconds', 'fullPredictionSeconds', ...
        'exactAuditSeconds', 'exactPredictionSeconds', ...
        'foldElapsedSeconds'});

    task.metrics = vertcat(metricRows{:});
    task.predictions = vertcat(predictionRows{:});
    task.fitDiagnostics = fitDiagnostics;
    task.checks = checks;
    task.timing = timing;
    task.fullFit = fullFit;
    task.separableFit = separableFit;
    task.fullPrediction = fullPrediction;
    task.separablePrediction = separablePrediction;
    task.exactPrediction = exactPrediction;
    task.observedIndex = observedIndex;
    task.targetIndex = targetIndex;
    task.version = string(cfg.version);
    task.preset = string(cfg.preset);
    task.basisFeatures = basis.nFeatures;
    task.basisBoundaryFactor = basis.boundaryFactor;
end

function [observed, target] = fold_geometry(subset, observedIndex, ...
        targetIndex, cfg)
    xyObservedKm = subset.xyKm(observedIndex, :);
    xyTargetKm = subset.xyKm(targetIndex, :);
    meanCenter = mean(xyObservedKm, 1);
    meanScale = std(xyObservedKm, 0, 1);
    meanScale(meanScale <= sqrt(eps)) = 1;
    observed.xyMean = (xyObservedKm - meanCenter) ./ meanScale;
    target.xyMean = (xyTargetKm - meanCenter) ./ meanScale;
    % The covariance coordinates use one fixed, geometry-only origin in all
    % folds because a bounded-domain HSGP is not translation invariant.
    covarianceCenter = mean(subset.xyKm, 1);
    observed.xyCovariance = (xyObservedKm - covarianceCenter) ./ ...
        cfg.spatial.coordinateScaleKm;
    target.xyCovariance = (xyTargetKm - covarianceCenter) ./ ...
        cfg.spatial.coordinateScaleKm;
    T = size(subset.U, 1);
    observed.design = make_pacific_mean_design(T, observed.xyMean);
    target.design = make_pacific_mean_design(T, target.xyMean);
end

function [metricRows, predictionRows, cursor] = append_probabilistic( ...
        metricRows, predictionRows, cursor, method, foldID, site, ...
        nearest, subset, truth, prediction, column, noiseVariance, cfg)
    cursor = cursor + 1;
    metrics = eq9_prediction_metrics(truth, prediction.mean(:, column), ...
        prediction.observationVariance(:, column), ...
        cfg.cv.nominalCoverage);
    metricRows{cursor} = metric_row(method, foldID, site, nearest, metrics);
    predictionRows{cursor} = prediction_table(method, foldID, site, ...
        subset, truth, prediction, column, noiseVariance);
end

function row = metric_row(method, foldID, site, distance, metrics)
    row = table(method, foldID, string(site.stationID), site.gridRow, ...
        site.gridColumn, site.xKm, site.yKm, distance, metrics.nValues, ...
        metrics.rmse, metrics.mae, metrics.correlation, metrics.nlpd, ...
        metrics.crps, metrics.coverage, metrics.meanIntervalWidth, ...
        'VariableNames', {'method', 'foldID', 'targetStation', ...
        'gridRow', 'gridColumn', 'xKm', 'yKm', ...
        'nearestTrainingDistanceKm', 'nValues', 'rmse', 'mae', ...
        'correlation', 'nlpd', 'crps', 'coverage95', ...
        'meanIntervalWidth95'});
end

function row = point_metric_row(method, foldID, site, distance, metrics)
    row = table(method, foldID, string(site.stationID), site.gridRow, ...
        site.gridColumn, site.xKm, site.yKm, distance, metrics.nValues, ...
        metrics.rmse, metrics.mae, metrics.correlation, NaN, NaN, NaN, ...
        NaN, 'VariableNames', {'method', 'foldID', 'targetStation', ...
        'gridRow', 'gridColumn', 'xKm', 'yKm', ...
        'nearestTrainingDistanceKm', 'nValues', 'rmse', 'mae', ...
        'correlation', 'nlpd', 'crps', 'coverage95', ...
        'meanIntervalWidth95'});
end

function rows = prediction_table(method, foldID, site, subset, truth, ...
        prediction, column, noiseVariance)
    T = numel(truth);
    meanValue = prediction.mean(:, column);
    observation = prediction.observationVariance(:, column);
    process = prediction.conditionalProcessVariance(:, column);
    fixed = prediction.fixedEffectVariance(:, column);
    nugget = repmat(noiseVariance, T, 1);
    latent = prediction.latentVariance(:, column);
    residual = truth - meanValue;
    standardized = residual ./ sqrt(observation);
    rows = table(repmat(method, T, 1), repmat(foldID, T, 1), ...
        repmat(string(site.stationID), T, 1), ...
        repmat(site.gridRow, T, 1), repmat(site.gridColumn, T, 1), ...
        subset.timeIndex, subset.relativeHours, truth, meanValue, ...
        process, fixed, nugget, latent, observation, residual, ...
        standardized, 'VariableNames', {'method', 'foldID', ...
        'targetStation', 'gridRow', 'gridColumn', 'timeIndex', ...
        'relativeHours', 'truthUWindMps', 'predictionUWindMps', ...
        'conditionalProcessVariance', 'fixedEffectVariance', ...
        'nuggetVariance', 'latentVariance', 'observationVariance', ...
        'residual', 'standardizedResidual'});
end

function rows = mean_prediction_table(foldID, site, subset, truth, meanValue)
    T = numel(truth);
    missing = nan(T, 1);
    rows = table(repmat("mean_only", T, 1), repmat(foldID, T, 1), ...
        repmat(string(site.stationID), T, 1), ...
        repmat(site.gridRow, T, 1), repmat(site.gridColumn, T, 1), ...
        subset.timeIndex, subset.relativeHours, truth, meanValue, ...
        missing, missing, missing, missing, missing, truth - meanValue, ...
        missing, 'VariableNames', {'method', 'foldID', ...
        'targetStation', 'gridRow', 'gridColumn', 'timeIndex', ...
        'relativeHours', 'truthUWindMps', 'predictionUWindMps', ...
        'conditionalProcessVariance', 'fixedEffectVariance', ...
        'nuggetVariance', 'latentVariance', 'observationVariance', ...
        'residual', 'standardizedResidual'});
end

function row = fit_row(method, foldID, fit, exactObjective, nScalar, ...
        basis, cfg, varianceReference, xyObserved)
    exactDifference = (fit.objective - exactObjective) / nScalar;
    if ~isfinite(exactObjective), exactDifference = NaN; end
    nuggetFloor = cfg.bounds.noiseVariance(1);
    nuggetFloorHit = fit.theta.noiseVariance <= nuggetFloor * ...
        (1 + cfg.hsgp.reportNuggetBoundaryTolerance);
    Phi = pacific_hsgp_features(xyObserved, basis);
    phiRank = rank(Phi);
    row = table(method, foldID, size(xyObserved, 1), basis.nFeatures, ...
        phiRank, max(0, size(xyObserved, 1) - phiRank), ...
        fit.objective, fit.objective / nScalar, exactObjective, ...
        exactDifference, fit.theta.signalVariance, fit.theta.alpha, ...
        fit.theta.beta, fit.theta.epsilon, fit.theta.noiseVariance, ...
        nuggetFloor, varianceReference, nuggetFloorHit, ...
        fit.convergenceCertified, fit.boundaryHit, fit.elapsedSeconds, ...
        fit.totalFunctionEvaluations, ...
        fit.details.minimumFeatureReciprocalCondition, ...
        fit.details.maximumFeatureJitter, ...
        fit.details.featureQrFrequencyCount, ...
        fit.details.siteCholeskyFrequencyCount, ...
        'VariableNames', {'method', 'foldID', 'nTrainingSites', ...
        'nFeatures', 'featureRank', ...
        'rankDeficientDirectionsBeforeNugget', 'hsgpObjective', ...
        'hsgpObjectivePerObservation', 'exactObjectiveAtHsgpTheta', ...
        'hsgpMinusExactObjectivePerObservation', 'signalVariance', ...
        'alphaPer100Km', 'betaPerSixHours', 'epsilon', ...
        'noiseVariance', 'trainingOnlyNuggetFloor', ...
        'residualVarianceReference', 'nuggetFloorHit', ...
        'convergenceCertified', 'boundaryHit', 'elapsedSeconds', ...
        'totalFunctionEvaluations', 'minimumReciprocalCondition', ...
        'maximumJitter', 'featureQrFrequencyCount', ...
        'siteCholeskyFrequencyCount'});
end

function checks = implementation_checks(foldID, fullPrediction, ...
        separablePrediction, fullFit, separableFit, targetIndex, ...
        observedIndex, basis, cfg, exactObjective, nScalar)
    names = ["training and target indices disjoint"; ...
        "full predictions finite"; "full predictive variances positive"; ...
        "separable predictions finite"; ...
        "separable predictive variances positive"; ...
        "full imaginary residue controlled"; ...
        "full reciprocal condition passes"; ...
        "full jitter passes"; "basis fixed before response fitting"; ...
        "full fit remains inside audited parameter box"; ...
        "separable spatial/temporal parameters remain inside audit box"; ...
        "exact likelihood displacement passes when audited"];
    passed = [isempty(intersect(targetIndex, observedIndex)); ...
        all(isfinite(fullPrediction.mean), 'all'); ...
        all(fullPrediction.observationVariance > 0, 'all'); ...
        all(isfinite(separablePrediction.mean), 'all'); ...
        all(separablePrediction.observationVariance > 0, 'all'); ...
        fullPrediction.maximumImaginaryPrediction <= ...
            cfg.cv.maximumAllowedImaginary; ...
        fullFit.details.minimumFeatureReciprocalCondition >= ...
            cfg.hsgp.minimumReciprocalCondition; ...
        fullFit.details.maximumFeatureJitter <= ...
            cfg.hsgp.maximumAllowedJitter; ...
        strcmpi(basis.method, 'HSGP'); ...
        inside_audit_box(fullFit.theta, cfg, true); ...
        inside_audit_box(separableFit.theta, cfg, false); ...
        likelihood_displacement_passes(fullFit, exactObjective, ...
            nScalar, cfg)];
    checks = table(repmat(foldID, numel(names), 1), names, passed, ...
        'VariableNames', {'foldID', 'check', 'passed'});
end

function passed = likelihood_displacement_passes(fit, exactObjective, ...
        nScalar, cfg)
    % The exact audit is optional for the full grid.  When present, it is a
    % mandatory numerical gate at the fitted HSGP parameters.
    if ~cfg.hsgp.auditExactAtFittedTheta
        passed = true;
        return;
    end
    displacement = (fit.objective - exactObjective) / nScalar;
    passed = isfinite(displacement) && abs(displacement) <= ...
        cfg.hsgp.acceptance. ...
        maximumAbsoluteObjectiveDifferencePerObservation;
end

function passed = inside_audit_box(theta, cfg, includeEpsilon)
    passed = theta.alpha >= min(cfg.hsgp.auditAlpha) && ...
        theta.alpha <= max(cfg.hsgp.auditAlpha) && ...
        theta.beta >= min(cfg.hsgp.auditBeta) && ...
        theta.beta <= max(cfg.hsgp.auditBeta);
    if includeEpsilon
        passed = passed && theta.epsilon >= min(cfg.hsgp.auditEpsilon) && ...
            theta.epsilon <= max(cfg.hsgp.auditEpsilon);
    end
end

function id = current_worker_id()
    id = 0;
    try
        currentTask = getCurrentTask();
        if ~isempty(currentTask), id = currentTask.ID; end
    catch
        id = 0;
    end
end
