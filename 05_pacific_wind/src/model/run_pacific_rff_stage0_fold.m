function output = run_pacific_rff_stage0_fold(cfg, stageInput)
%RUN_PACIFIC_RFF_STAGE0_FOLD Fixed-theta exact-versus-RFF comparison.

    validate_stage_input(stageInput);
    foldID = stageInput.foldID;
    Yobserved = stageInput.Yobserved;
    nObserved = size(Yobserved, 2);
    nTarget = stageInput.nTargetSites;
    exactFit = stageInput.exactFit;
    exactPrediction = stageInput.exactPrediction;
    prepared = prepare_pacific_whittle_data(Yobserved, ...
        stageInput.outerGeometry.xyCovariance, ...
        stageInput.outerGeometry.design);
    diagnosticIndex = diagnostic_frequency_indices( ...
        size(Yobserved, 1), cfg.rff.temporalBandEdges);
    lambdaAll = eq9_fourier_frequencies(size(Yobserved, 1));
    diagnosticLambda = lambdaAll(diagnosticIndex);
    exactDiagnosticCovariance = eq9_frequency_covariances( ...
        exactFit.theta, stageInput.outerGeometry.xyCovariance, ...
        diagnosticLambda, cfg, false);
    exactTimer = tic;
    exactObjectiveAudit = pacific_profiled_whittle_theta( ...
        exactFit.theta, prepared, cfg);
    exactObjectiveSeconds = toc(exactTimer);
    exactObjectiveAgreement = abs(exactObjectiveAudit - ...
        exactFit.objective) / max(1, abs(exactFit.objective));

    nFeatureChoice = numel(cfg.rff.featureCounts);
    nSeed = numel(cfg.rff.seeds);
    rows = cell(nFeatureChoice * nSeed, 1);
    cursor = 0;
    for pIndex = 1:nFeatureChoice
        nFeatures = cfg.rff.featureCounts(pIndex);
        for seedIndex = 1:nSeed
            timerValue = tic;
            baseSeed = cfg.rff.seeds(seedIndex);
            seed = baseSeed + 1009 * foldID;
            bank = make_pacific_rff_bank(exactFit.theta, ...
                nFeatures, cfg, seed);
            prepared.rffPhi = pacific_rff_features( ...
                prepared.xy, bank);
            prepared.rffFeatureGram = ...
                prepared.rffPhi' * prepared.rffPhi;
            objectiveTimer = tic;
            [rffObjective, details] = ...
                pacific_profiled_whittle_theta_rff( ...
                exactFit.theta, prepared, cfg, bank);
            rffObjectiveSeconds = toc(objectiveTimer);
            rffFit.theta = exactFit.theta;
            rffFit.eta = details.eta;
            rffFit.covarianceEta = details.covarianceEta;
            rffFit.objective = rffObjective;
            rffFit.details = details;
            predictionTimer = tic;
            prediction = predict_pacific_eq9_rff(Yobserved, ...
                stageInput.outerGeometry.xyCovariance, ...
                stageInput.targetGeometry.xyCovariance, ...
                stageInput.outerGeometry.design, ...
                stageInput.targetGeometry.design, rffFit, cfg, bank);
            rffPredictionSeconds = toc(predictionTimer);
            predictionMeanRmse = sqrt(mean(abs(prediction.mean - ...
                exactPrediction.mean) .^ 2, 'all'));
            observationVarianceError = median(abs( ...
                prediction.observationVariance - ...
                exactPrediction.observationVariance) ./ max( ...
                cfg.cv.minimumPredictiveVariance, ...
                exactPrediction.observationVariance), 'all');
            conditionalVarianceError = median(abs( ...
                prediction.conditionalProcessVariance - ...
                exactPrediction.conditionalProcessVariance) ./ max( ...
                cfg.cv.minimumPredictiveVariance, ...
                exactPrediction.conditionalProcessVariance), 'all');
            [covarianceMedian, covarianceMaximum, diagonalMedian] = ...
                covariance_errors(exactFit.theta, ...
                stageInput.outerGeometry.xyCovariance, ...
                diagnosticLambda, exactDiagnosticCovariance, ...
                bank, cfg);
            nullMultiplicity = max(0, nObserved - nFeatures);
            nuggetFraction = exactFit.theta.noiseVariance / ...
                (exactFit.theta.signalVariance + ...
                exactFit.theta.noiseVariance);
            cursor = cursor + 1;
            featureToSiteRatio = nFeatures / nObserved;
            nFactorFrequencies = numel(prepared.endpointIndices) + ...
                numel(prepared.positiveIndices);
            estimatedFlopRatio = featureToSiteRatio ^ 3 + ...
                3 * featureToSiteRatio ^ 2 / nFactorFrequencies;
            rows{cursor} = table(foldID, nFeatures, baseSeed, seed, ...
                nObserved, nTarget, ...
                nullMultiplicity, featureToSiteRatio, ...
                estimatedFlopRatio, exactFit.theta.noiseVariance, ...
                nuggetFraction, exactFit.objective, rffObjective, ...
                (rffObjective - exactFit.objective) / ...
                (nObserved * size(Yobserved, 1)), ...
                covarianceMedian, covarianceMaximum, diagonalMedian, ...
                prediction.minimumEssFraction, ...
                prediction.medianEssFraction, ...
                prediction.minimumFeatureReciprocalCondition, ...
                predictionMeanRmse, observationVarianceError, ...
                conditionalVarianceError, false, ...
                prediction.maximumImaginaryPrediction, ...
                exactObjectiveAgreement, exactObjectiveSeconds, ...
                rffObjectiveSeconds, rffPredictionSeconds, ...
                toc(timerValue), ...
                'VariableNames', {'foldID', 'nFeatures', ...
                'baseFeatureSeed', 'actualFeatureSeed', ...
                'nConditioningSites', 'nTargetSites', ...
                'rankDeficientDirectionsBeforeNugget', ...
                'featureToSiteRatio', ...
                'estimatedFactorizationFlopRatio', 'noiseVariance', ...
                'modelNuggetFraction', 'exactObjective', 'rffObjective', ...
                'objectiveDifferencePerObservation', ...
                'medianLatentCovarianceRelativeError', ...
                'maximumLatentCovarianceRelativeError', ...
                'medianLatentDiagonalRelativeError', ...
                'minimumEssFraction', 'medianEssFraction', ...
                'minimumFeatureReciprocalCondition', ...
                'predictionMeanRmseMps', ...
                'medianObservationVarianceRelativeError', ...
                'medianConditionalVarianceRelativeError', ...
                'outerTargetResponsesAccessible', ...
                'maximumImaginaryPrediction', ...
                'exactObjectiveRelativeAgreement', ...
                'exactObjectiveSeconds', 'rffObjectiveSeconds', ...
                'rffPredictionSeconds', 'elapsedSeconds'});
        end
    end
    output.comparisons = vertcat(rows{:});
end

function validate_stage_input(stageInput)
% Reject any artifact that could expose outer-target responses or scores.

    required = ["foldID"; "Yobserved"; "nTargetSites"; ...
        "outerGeometry"; "targetGeometry"; "exactFit"; ...
        "exactPrediction"];
    actual = string(fieldnames(stageInput));
    if numel(actual) ~= numel(required) || ...
            ~all(ismember(required, actual))
        error(['RFF stage-0 input must contain exactly the approved ', ...
            'training-only fields. Rerun the subset plug-in stage.']);
    end
    if any(~isfinite(stageInput.Yobserved), 'all')
        error('RFF stage-0 training responses must be finite.');
    end
    if size(stageInput.exactPrediction.mean, 2) ~= ...
            stageInput.nTargetSites
        error('RFF stage-0 target geometry and prediction disagree.');
    end
end

function index = diagnostic_frequency_indices(T, bandEdges)
    lambda = abs(eq9_fourier_frequencies(T)) / pi;
    index = [];
    for b = 1:(numel(bandEdges) - 1)
        if b == numel(bandEdges) - 1
            inBand = find(lambda >= bandEdges(b) & ...
                lambda <= bandEdges(b + 1));
        else
            inBand = find(lambda >= bandEdges(b) & ...
                lambda < bandEdges(b + 1));
        end
        if isempty(inBand)
            continue;
        end
        positions = unique(round(linspace(1, numel(inBand), ...
            min(4, numel(inBand)))));
        index = [index; inBand(positions(:))]; %#ok<AGROW>
    end
    index = unique(index, 'stable');
end

function [medianError, maximumError, medianDiagonalError] = ...
        covariance_errors(theta, xy, lambda, exactCovariance, bank, cfg)
    Phi = pacific_rff_features(xy, bank);
    weights = pacific_rff_weights(theta, lambda, bank, cfg);
    relative = zeros(numel(lambda), 1);
    diagonal = zeros(numel(lambda), 1);
    for k = 1:numel(lambda)
        approximate = pacific_rff_covariance(Phi, Phi, ...
            weights(:, k), 0, true);
        exact = exactCovariance(:, :, k);
        relative(k) = norm(approximate - exact, 'fro') / ...
            max(realmin('double'), norm(exact, 'fro'));
        diagonal(k) = median(abs(diag(approximate) - diag(exact)) ./ ...
            max(realmin('double'), abs(diag(exact))));
    end
    medianError = median(relative);
    maximumError = max(relative);
    medianDiagonalError = median(diagonal);
end
