function result = run_pacific_hsgp_cv(configOrPreset, useParallel)
%RUN_PACIFIC_HSGP_CV Five-fold Pacific HSGP reconstruction experiment.

    if nargin < 1 || isempty(configOrPreset)
        cfg = pacific_hsgp_config('local7_cv5');
    elseif isstruct(configOrPreset)
        cfg = configOrPreset;
    else
        cfg = pacific_hsgp_config(configOrPreset);
    end
    if nargin >= 2 && ~isempty(useParallel)
        cfg.parallel.useParallel = logical(useParallel);
    end
    basisFile = fullfile(cfg.paths.hsgpAuditDir, ...
        'hsgp_basis_package.mat');
    if ~isfile(basisFile)
        error('Run run_pacific_hsgp_basis_audit before HSGP CV.');
    end
    loadedBasis = load(basisFile, 'selectedBasis', ...
        'selectionPassed', 'cfg');
    if ~loadedBasis.selectionPassed
        error('The stored HSGP basis audit did not pass.');
    end
    basis = loadedBasis.selectedBasis;
    if ~strcmpi(loadedBasis.cfg.preset, cfg.preset)
        error('Stored HSGP basis preset does not match the CV preset.');
    end

    timerValue = tic;
    contract = load_pacific_wind_data(cfg);
    subset = make_pacific_subset(contract, cfg.subset.name);
    if any(~isfinite(subset.U), 'all')
        error('HSGP CV requires complete time series at every selected site.');
    end
    [folds, foldManifest, foldSummary] = make_pacific_cv_folds( ...
        subset, cfg.cv.holdoutPattern);
    nFold = numel(folds);
    if nFold ~= 5
        error('The Pacific HSGP pilot requires exactly five folds.');
    end
    if cfg.parallel.numWorkers ~= nFold
        warning(['Requested workers (%d) differ from folds (%d). ', ...
            'Only min(workers, folds) can be effective.'], ...
            cfg.parallel.numWorkers, nFold);
    end

    ensure_directory(cfg.paths.hsgpCvDir);
    ensure_directory(fullfile(cfg.paths.hsgpCvDir, 'tasks'));
    writetable(subset.siteTable, fullfile(cfg.paths.hsgpCvDir, ...
        'selected_subset_manifest.csv'));
    writetable(foldManifest, fullfile(cfg.paths.hsgpCvDir, ...
        'cv_fold_manifest.csv'));
    writetable(foldSummary, fullfile(cfg.paths.hsgpCvDir, ...
        'cv_fold_summary.csv'));
    save(fullfile(cfg.paths.hsgpCvDir, 'configuration.mat'), ...
        'cfg', 'basis');

    tasks = cell(nFold, 1);
    parallelUsed = false;
    actualPoolWorkers = 1;
    if cfg.parallel.useParallel && parallel_available()
        parallelUsed = true;
        pool = gcp('nocreate');
        if isempty(pool) && cfg.parallel.autoStartPool
            pool = parpool(min(cfg.parallel.numWorkers, nFold));
        end
        if isempty(pool)
            error('Parallel execution was requested but no pool is open.');
        end
        actualPoolWorkers = pool.NumWorkers;
        parfor f = 1:nFold
            tasks{f} = run_pacific_hsgp_fold_task( ...
                cfg, subset, folds(f), basis);
        end
    else
        if cfg.parallel.useParallel
            warning('Parallel Computing Toolbox unavailable; using serial folds.');
        end
        for f = 1:nFold
            tasks{f} = run_pacific_hsgp_fold_task( ...
                cfg, subset, folds(f), basis);
        end
    end

    metrics = concatenate(tasks, 'metrics');
    predictions = concatenate(tasks, 'predictions');
    fitDiagnostics = concatenate(tasks, 'fitDiagnostics');
    implementationChecks = concatenate(tasks, 'checks');
    taskTiming = concatenate(tasks, 'timing');
    methodSummary = summarize_methods(metrics);
    likelihoodSummary = summarize_likelihood(fitDiagnostics);
    pairedComparisons = paired_comparisons(metrics);

    writetable(metrics, fullfile(cfg.paths.hsgpCvDir, 'fold_metrics.csv'));
    writetable(predictions, fullfile(cfg.paths.hsgpCvDir, ...
        'predictions.csv'));
    writetable(fitDiagnostics, fullfile(cfg.paths.hsgpCvDir, ...
        'fit_diagnostics.csv'));
    writetable(implementationChecks, fullfile(cfg.paths.hsgpCvDir, ...
        'implementation_checks.csv'));
    writetable(taskTiming, fullfile(cfg.paths.hsgpCvDir, ...
        'task_timing.csv'));
    writetable(methodSummary, fullfile(cfg.paths.hsgpCvDir, ...
        'method_summary.csv'));
    writetable(likelihoodSummary, fullfile(cfg.paths.hsgpCvDir, ...
        'likelihood_summary.csv'));
    writetable(pairedComparisons, fullfile(cfg.paths.hsgpCvDir, ...
        'paired_comparisons.csv'));

    elapsedSeconds = toc(timerValue);
    effectiveWorkers = min(actualPoolWorkers, nFold);
    runSummary = table(string(cfg.version), string(cfg.preset), ...
        string(cfg.subset.name), height(subset.siteTable), nFold, ...
        basis.boundaryFactor, basis.basisPerDimension, basis.nFeatures, ...
        parallelUsed, cfg.parallel.numWorkers, actualPoolWorkers, ...
        effectiveWorkers, elapsedSeconds, ...
        all(implementationChecks.passed), ...
        mean(fitDiagnostics.convergenceCertified), ...
        mean(fitDiagnostics.nuggetFloorHit), ...
        mean(fitDiagnostics.rankDeficientDirectionsBeforeNugget), ...
        'VariableNames', {'version', 'preset', 'subsetName', ...
        'nSites', 'nCvFolds', 'boundaryFactor', ...
        'basisPerDimension', 'nFeatures', 'parallelUsed', ...
        'requestedWorkers', 'actualPoolWorkers', 'effectiveWorkers', ...
        'elapsedSeconds', 'allImplementationChecksPassed', ...
        'convergenceFraction', 'nuggetFloorHitFraction', ...
        'meanRankDeficientDirectionsBeforeNugget'});
    writetable(runSummary, fullfile(cfg.paths.hsgpCvDir, ...
        'run_summary.csv'));
    make_pacific_hsgp_figures(metrics, predictions, fitDiagnostics, ...
        methodSummary, cfg);
    save(fullfile(cfg.paths.hsgpCvDir, 'complete_result.mat'), ...
        'cfg', 'basis', 'subset', 'folds', 'foldManifest', ...
        'foldSummary', 'tasks', 'metrics', 'predictions', ...
        'fitDiagnostics', 'implementationChecks', 'taskTiming', ...
        'methodSummary', 'likelihoodSummary', 'pairedComparisons', ...
        'runSummary', '-v7.3');

    fprintf('\nPacific HSGP CV complete in %.1f minutes.\n', ...
        elapsedSeconds / 60);
    fprintf('  Preset: %s; basis c=%.3g, J=%d, M=%d.\n', ...
        cfg.preset, basis.boundaryFactor, basis.basisPerDimension, ...
        basis.nFeatures);
    fprintf('  Effective workers: %d of %d folds.\n', ...
        effectiveWorkers, nFold);
    fprintf('  Results: %s\n\n', cfg.paths.hsgpCvDir);

    result.cfg = cfg;
    result.basis = basis;
    result.subset = subset;
    result.metrics = metrics;
    result.predictions = predictions;
    result.fitDiagnostics = fitDiagnostics;
    result.methodSummary = methodSummary;
    result.likelihoodSummary = likelihoodSummary;
    result.pairedComparisons = pairedComparisons;
    result.runSummary = runSummary;
end

function value = concatenate(tasks, fieldName)
    parts = cellfun(@(x) x.(fieldName), tasks, 'UniformOutput', false);
    value = vertcat(parts{:});
end

function summary = summarize_methods(metrics)
    methods = unique(metrics.method, 'stable');
    rows = cell(numel(methods), 1);
    for j = 1:numel(methods)
        use = metrics.method == methods(j);
        rows{j} = table(methods(j), sum(use), ...
            mean(metrics.rmse(use), 'omitnan'), ...
            standard_error(metrics.rmse(use)), ...
            mean(metrics.mae(use), 'omitnan'), ...
            mean(metrics.correlation(use), 'omitnan'), ...
            mean(metrics.nlpd(use), 'omitnan'), ...
            mean(metrics.crps(use), 'omitnan'), ...
            mean(metrics.coverage95(use), 'omitnan'), ...
            mean(metrics.meanIntervalWidth95(use), 'omitnan'), ...
            'VariableNames', {'method', 'nTargetSites', 'meanRmse', ...
            'seRmseAcrossSites', 'meanMae', 'meanCorrelation', ...
            'meanNlpd', 'meanCrps', 'meanCoverage95', ...
            'meanIntervalWidth95'});
    end
    summary = vertcat(rows{:});
end

function summary = summarize_likelihood(fitDiagnostics)
    methods = unique(fitDiagnostics.method, 'stable');
    rows = cell(numel(methods), 1);
    for j = 1:numel(methods)
        use = fitDiagnostics.method == methods(j);
        rows{j} = table(methods(j), sum(use), ...
            mean(fitDiagnostics.hsgpObjectivePerObservation(use), ...
                'omitnan'), ...
            mean(fitDiagnostics.hsgpMinusExactObjectivePerObservation(use), ...
                'omitnan'), ...
            mean(fitDiagnostics.convergenceCertified(use)), ...
            mean(fitDiagnostics.nuggetFloorHit(use)), ...
            median(fitDiagnostics.signalVariance(use), 'omitnan'), ...
            median(fitDiagnostics.alphaPer100Km(use), 'omitnan'), ...
            median(fitDiagnostics.betaPerSixHours(use), 'omitnan'), ...
            median(fitDiagnostics.epsilon(use), 'omitnan'), ...
            median(fitDiagnostics.noiseVariance(use), 'omitnan'), ...
            'VariableNames', {'method', 'nFolds', ...
            'meanHsgpObjectivePerObservation', ...
            'meanHsgpMinusExactObjectivePerObservation', ...
            'convergenceFraction', 'nuggetFloorHitFraction', ...
            'medianSignalVariance', 'medianAlphaPer100Km', ...
            'medianBetaPerSixHours', 'medianEpsilon', ...
            'medianNoiseVariance'});
    end
    summary = vertcat(rows{:});
end

function comparisons = paired_comparisons(metrics)
    targets = unique(metrics.targetStation, 'stable');
    comparators = ["hsgp_separable", "mean_only", ...
        "hsgp_theta_exact_engine"];
    rows = cell(numel(targets) * numel(comparators), 1);
    cursor = 0;
    for j = 1:numel(targets)
        base = metrics(metrics.targetStation == targets(j) & ...
            metrics.method == "hsgp_eq9", :);
        for c = 1:numel(comparators)
            other = metrics(metrics.targetStation == targets(j) & ...
                metrics.method == comparators(c), :);
            if height(other) ~= 1, continue; end
            cursor = cursor + 1;
            rows{cursor} = table(base.foldID, targets(j), ...
                comparators(c), base.rmse - other.rmse, ...
                base.mae - other.mae, base.nlpd - other.nlpd, ...
                'VariableNames', {'foldID', 'targetStation', ...
                'comparator', 'hsgpMinusComparatorRmse', ...
                'hsgpMinusComparatorMae', 'hsgpMinusComparatorNlpd'});
        end
    end
    rows = rows(1:cursor);
    comparisons = vertcat(rows{:});
end

function value = standard_error(x)
    x = x(isfinite(x));
    if numel(x) < 2, value = NaN; else, value = std(x) / sqrt(numel(x)); end
end

function available = parallel_available()
    try
        available = license('test', 'Distrib_Computing_Toolbox');
    catch
        available = false;
    end
end
