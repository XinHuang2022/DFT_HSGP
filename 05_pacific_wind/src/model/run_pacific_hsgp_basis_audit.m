function result = run_pacific_hsgp_basis_audit(configOrPreset)
%RUN_PACIFIC_HSGP_BASIS_AUDIT Geometry-only certification of an HSGP basis.
%
% No wind response is used.  Exact and HSGP latent spectral covariance
% matrices are compared on a fixed parameter grid and diagnostic temporal
% frequencies.  The smallest certified tensor-square basis is selected.

    if nargin < 1 || isempty(configOrPreset)
        cfg = pacific_hsgp_config('local7_cv5');
    elseif isstruct(configOrPreset)
        cfg = configOrPreset;
    else
        cfg = pacific_hsgp_config(configOrPreset);
    end
    ensure_directory(cfg.paths.hsgpAuditDir);
    contract = load_pacific_wind_data(cfg);
    subset = make_pacific_subset(contract, cfg.subset.name);
    xyDomain = centered_covariance_coordinates(subset.xyKm, cfg);
    auditIndex = choose_audit_sites(subset.siteTable, ...
        cfg.hsgp.maximumAuditSites);
    xyAudit = xyDomain(auditIndex, :);
    lambda = linspace(0, pi, cfg.hsgp.diagnosticFrequencies);

    [alpha, beta, epsilon] = ndgrid(cfg.hsgp.auditAlpha, ...
        cfg.hsgp.auditBeta, cfg.hsgp.auditEpsilon);
    thetaGrid = [alpha(:), beta(:), epsilon(:)];
    nTheta = size(thetaGrid, 1);
    exact = cell(nTheta, 1);
    for t = 1:nTheta
        theta = audit_theta(thetaGrid(t, :), cfg);
        exact{t} = eq9_frequency_covariances(theta, xyAudit, ...
            lambda, cfg, false);
    end

    nCandidate = numel(cfg.hsgp.boundaryFactors) * ...
        numel(cfg.hsgp.basisPerDimension);
    pointRows = cell(nCandidate * nTheta, 1);
    candidateRows = cell(nCandidate, 1);
    candidates = cell(nCandidate, 1);
    cursor = 0;
    for b = 1:numel(cfg.hsgp.boundaryFactors)
        for j = 1:numel(cfg.hsgp.basisPerDimension)
            cursor = cursor + 1;
            boundaryFactor = cfg.hsgp.boundaryFactors(b);
            J = cfg.hsgp.basisPerDimension(j);
            basis = make_pacific_hsgp_basis(xyDomain, ...
                boundaryFactor, J, cfg);
            PhiAudit = pacific_hsgp_features(xyAudit, basis);
            candidates{cursor} = basis;
            localMedian = nan(nTheta, 1);
            localMaximum = nan(nTheta, 1);
            localDiagonal = nan(nTheta, 1);
            localWhitened = nan(nTheta, 1);
            for t = 1:nTheta
                theta = audit_theta(thetaGrid(t, :), cfg);
                weight = pacific_hsgp_weights(theta, lambda, basis, cfg);
                frequencyError = nan(numel(lambda), 1);
                diagonalRatio = nan(numel(lambda), 1);
                whitenedError = nan(numel(lambda), 1);
                for k = 1:numel(lambda)
                    approximate = pacific_hsgp_covariance( ...
                        PhiAudit, PhiAudit, weight(:, k), 0, true);
                    target = exact{t}(:, :, k);
                    frequencyError(k) = norm(approximate - target, ...
                        'fro') / max(realmin('double'), norm(target, 'fro'));
                    diagonalRatio(k) = median(diag(approximate) ./ ...
                        max(realmin('double'), diag(target)));
                    targetObserved = target + ...
                        cfg.hsgp.auditNoiseVariance * eye(size(target));
                    approximateObserved = approximate + ...
                        cfg.hsgp.auditNoiseVariance * eye(size(target));
                    [Ltarget, ~] = eq9_chol_with_jitter(targetObserved);
                    whitenedDifference = Ltarget \ ...
                        (approximateObserved - targetObserved) / Ltarget';
                    whitenedError(k) = norm(whitenedDifference, 2);
                end
                localMedian(t) = median(frequencyError);
                localMaximum(t) = max(frequencyError);
                localDiagonal(t) = median(diagonalRatio);
                localWhitened(t) = max(whitenedError);
                rowIndex = (cursor - 1) * nTheta + t;
                pointRows{rowIndex} = table(cursor, boundaryFactor, J, ...
                    basis.nFeatures, theta.alpha, theta.beta, ...
                    theta.epsilon, median(frequencyError), ...
                    max(frequencyError), median(diagonalRatio), ...
                    max(whitenedError), ...
                    'VariableNames', {'candidateID', 'boundaryFactor', ...
                    'basisPerDimension', 'nFeatures', 'alphaPer100Km', ...
                    'betaPerSixHours', 'epsilon', ...
                    'medianLatentCovarianceRelativeError', ...
                    'maximumLatentCovarianceRelativeError', ...
                    'medianDiagonalRatio', ...
                    'maximumWhitenedCovarianceError'});
            end
            pass = max(localMedian) <= cfg.hsgp.acceptance. ...
                    maximumMedianLatentCovarianceError && ...
                max(localMaximum) <= cfg.hsgp.acceptance. ...
                    maximumLatentCovarianceError && ...
                max(localWhitened) <= cfg.hsgp.acceptance. ...
                    maximumWhitenedCovarianceError && ...
                min(localDiagonal) >= cfg.hsgp.acceptance. ...
                    minimumMedianDiagonalRatio && ...
                max(localDiagonal) <= cfg.hsgp.acceptance. ...
                    maximumMedianDiagonalRatio;
            candidateRows{cursor} = table(cursor, boundaryFactor, J, ...
                basis.nFeatures, max(localMedian), max(localMaximum), ...
                max(localWhitened), ...
                min(localDiagonal), max(localDiagonal), pass, ...
                'VariableNames', {'candidateID', 'boundaryFactor', ...
                'basisPerDimension', 'nFeatures', ...
                'worstMedianLatentCovarianceRelativeError', ...
                'worstMaximumLatentCovarianceRelativeError', ...
                'worstMaximumWhitenedCovarianceError', ...
                'minimumMedianDiagonalRatio', ...
                'maximumMedianDiagonalRatio', 'certified'});
        end
    end
    auditPoints = vertcat(pointRows{:});
    candidateSummary = vertcat(candidateRows{:});
    passing = candidateSummary(candidateSummary.certified, :);
    if isempty(passing)
        selectedID = NaN;
        selectionPassed = false;
        selectedBasis = struct();
    else
        passing = sortrows(passing, {'nFeatures', ...
            'worstMaximumLatentCovarianceRelativeError', ...
            'boundaryFactor'});
        selectedID = passing.candidateID(1);
        selectionPassed = true;
        selectedBasis = candidates{selectedID};
    end
    if selectionPassed
        selectedRow = candidateSummary( ...
            candidateSummary.candidateID == selectedID, :);
        selectedRow.selectionPassed = true;
        approximateTrainingSites = height(subset.siteTable) - ...
            ceil(height(subset.siteTable) / 5);
        selectedRow.approximateTrainingSites = approximateTrainingSites;
        selectedRow.dimensionReductionExpected = ...
            selectedRow.nFeatures < approximateTrainingSites;
    else
        selectedRow = table(NaN, NaN, NaN, NaN, NaN, NaN, NaN, ...
            NaN, NaN, false, false, NaN, false, 'VariableNames', ...
            {'candidateID', 'boundaryFactor', 'basisPerDimension', ...
            'nFeatures', 'worstMedianLatentCovarianceRelativeError', ...
            'worstMaximumLatentCovarianceRelativeError', ...
            'worstMaximumWhitenedCovarianceError', ...
            'minimumMedianDiagonalRatio', 'maximumMedianDiagonalRatio', ...
            'certified', 'selectionPassed', ...
            'approximateTrainingSites', 'dimensionReductionExpected'});
    end

    writetable(auditPoints, fullfile(cfg.paths.hsgpAuditDir, ...
        'hsgp_audit_points.csv'));
    writetable(candidateSummary, fullfile(cfg.paths.hsgpAuditDir, ...
        'hsgp_candidate_summary.csv'));
    writetable(selectedRow, fullfile(cfg.paths.hsgpAuditDir, ...
        'hsgp_selected_basis.csv'));
    writetable(subset.siteTable(auditIndex, :), ...
        fullfile(cfg.paths.hsgpAuditDir, 'hsgp_audit_sites.csv'));
    save(fullfile(cfg.paths.hsgpAuditDir, 'hsgp_basis_package.mat'), ...
        'selectedBasis', 'selectionPassed', 'selectedID', 'cfg', ...
        'subset', 'xyDomain', 'auditIndex', 'lambda', 'thetaGrid');
    make_audit_figure(candidateSummary, selectedID, cfg);

    if cfg.hsgp.requireCertifiedBasis && ~selectionPassed
        error(['No HSGP basis passed the prespecified covariance gates. ', ...
            'Inspect hsgp_candidate_summary.csv, then enlarge the ', ...
            'candidate J/domain grid before running CV.']);
    end
    result.cfg = cfg;
    result.auditPoints = auditPoints;
    result.candidateSummary = candidateSummary;
    result.selected = selectedRow;
    result.selectedBasis = selectedBasis;
end

function xy = centered_covariance_coordinates(xyKm, cfg)
    xy = (xyKm - mean(xyKm, 1)) ./ cfg.spatial.coordinateScaleKm;
end

function index = choose_audit_sites(siteTable, maximumSites)
    if height(siteTable) <= maximumSites
        index = (1:height(siteTable))';
        return;
    end
    side = max(2, floor(sqrt(maximumSites)));
    rowLevels = unique(siteTable.gridRow, 'sorted');
    columnLevels = unique(siteTable.gridColumn, 'sorted');
    rows = rowLevels(unique(round(linspace(1, numel(rowLevels), side))));
    columns = columnLevels(unique(round(linspace( ...
        1, numel(columnLevels), side))));
    index = find(ismember(siteTable.gridRow, rows) & ...
        ismember(siteTable.gridColumn, columns));
end

function theta = audit_theta(values, cfg)
    theta.signalVariance = cfg.hsgp.auditSignalVariance;
    theta.alpha = values(1);
    theta.beta = values(2);
    theta.epsilon = values(3);
    theta.noiseVariance = cfg.bounds.noiseVariance(1);
    theta.nu = cfg.model.nu;
end

function make_audit_figure(summary, selectedID, cfg)
    h = figure('Visible', cfg.figures.visible, 'Color', 'white', ...
        'Position', [100, 100, 1420, 500]);
    layout = tiledlayout(1, 3, 'Padding', 'compact', ...
        'TileSpacing', 'compact');
    nexttile;
    scatter(summary.nFeatures, ...
        100 * summary.worstMaximumLatentCovarianceRelativeError, ...
        55, summary.boundaryFactor, 'filled');
    yline(100 * cfg.hsgp.acceptance.maximumLatentCovarianceError, ...
        '--k', 'gate');
    xlabel('Number of HSGP features M=J^2');
    ylabel('Worst covariance error (%)'); grid on; colorbar;
    title('Accuracy over the audit box');
    nexttile;
    scatter(summary.nFeatures, ...
        summary.worstMaximumWhitenedCovarianceError, ...
        55, summary.boundaryFactor, 'filled');
    yline(cfg.hsgp.acceptance.maximumWhitenedCovarianceError, ...
        '--k', 'gate');
    set(gca, 'YScale', 'log');
    xlabel('Number of HSGP features M=J^2');
    ylabel('Worst whitened covariance error'); grid on; colorbar;
    title('Weak-eigenvalue accuracy');
    nexttile;
    scatter(summary.nFeatures, summary.maximumMedianDiagonalRatio, ...
        55, summary.boundaryFactor, 'filled'); hold on;
    yline(cfg.hsgp.acceptance.minimumMedianDiagonalRatio, '--k');
    yline(cfg.hsgp.acceptance.maximumMedianDiagonalRatio, '--k');
    xlabel('Number of HSGP features M=J^2');
    ylabel('Largest median diagonal ratio'); grid on; colorbar;
    title('Marginal-variance preservation');
    if isfinite(selectedID)
        selected = summary(summary.candidateID == selectedID, :);
        title(layout, sprintf( ...
            'Selected: c=%.2g, J=%d, M=%d', ...
            selected.boundaryFactor, selected.basisPerDimension, ...
            selected.nFeatures));
    end
    figureDir = fullfile(cfg.paths.hsgpAuditDir, 'figures');
    ensure_directory(figureDir);
    pacific_save_figure(h, figureDir, 'hsgp_basis_audit');
end
