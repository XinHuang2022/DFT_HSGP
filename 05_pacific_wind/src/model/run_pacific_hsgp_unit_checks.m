function checks = run_pacific_hsgp_unit_checks(preset)
%RUN_PACIFIC_HSGP_UNIT_CHECKS Deterministic HSGP implementation tests.

    if nargin < 1 || isempty(preset), preset = 'local7_cv5'; end
    cfg = pacific_hsgp_config(preset);
    contract = load_pacific_wind_data(cfg);
    subset = make_pacific_subset(contract, cfg.subset.name);
    xy = (subset.xyKm - mean(subset.xyKm, 1)) ./ ...
        cfg.spatial.coordinateScaleKm;
    basis = make_pacific_hsgp_basis(xy, 2, 6, cfg);
    theta = cfg.start;
    theta.nu = cfg.model.nu;
    lambda = [0, pi / 3, pi];
    weights = pacific_hsgp_weights(theta, lambda, basis, cfg);
    Phi = pacific_hsgp_features(xy, basis);
    K = pacific_hsgp_covariance(Phi, Phi, weights(:, 1), ...
        theta.noiseVariance, true);

    rng(4421, 'twister');
    PhiTall = randn(9, 4);
    wTall = 0.2 + rand(4, 1);
    rhsTall = randn(9, 2);
    tallCfg = cfg;
    tallCfg.hsgp.factorization = 'auto';
    tallFactor = pacific_hsgp_factor(PhiTall, wTall, 0.3, tallCfg);
    tallExact = ((PhiTall .* wTall.') * PhiTall' + 0.3 * eye(9)) ...
        \ rhsTall;
    tallError = norm(pacific_hsgp_solve(tallFactor, rhsTall) - ...
        tallExact, 'fro') / norm(tallExact, 'fro');

    PhiWide = randn(4, 9);
    wWide = 0.2 + rand(9, 1);
    rhsWide = randn(4, 2);
    wideFactor = pacific_hsgp_factor(PhiWide, wWide, 0.3, tallCfg);
    wideExact = ((PhiWide .* wWide.') * PhiWide' + 0.3 * eye(4)) ...
        \ rhsWide;
    wideError = norm(pacific_hsgp_solve(wideFactor, rhsWide) - ...
        wideExact, 'fro') / norm(wideExact, 'fro');

    name = ["basis feature count is J squared"; ...
        "basis values finite"; "HSGP weights positive and finite"; ...
        "HSGP covariance symmetric"; "HSGP covariance positive definite"; ...
        "auto solver uses feature QR when M below n"; ...
        "feature QR solve agrees with dense solve"; ...
        "auto solver uses site Cholesky when M at least n"; ...
        "site Cholesky solve agrees with dense solve"; ...
        "Pacific panel is complete"];
    passed = [basis.nFeatures == basis.basisPerDimension ^ 2; ...
        all(isfinite(Phi), 'all'); ...
        all(isfinite(weights), 'all') && all(weights > 0, 'all'); ...
        norm(K - K', 'fro') <= 1e-10 * max(1, norm(K, 'fro')); ...
        min(eig((K + K') / 2)) > 0; ...
        tallFactor.mode == "feature_qr"; tallError < 1e-9; ...
        wideFactor.mode == "site_cholesky"; wideError < 1e-9; ...
        all(isfinite(subset.U), 'all')];
    detail = [string(basis.nFeatures); string(max(abs(Phi), [], 'all')); ...
        string(min(weights, [], 'all')); string(norm(K - K', 'fro')); ...
        string(min(eig((K + K') / 2))); tallFactor.mode; ...
        string(tallError); wideFactor.mode; string(wideError); ...
        string(size(subset.U, 1)) + " by " + string(size(subset.U, 2))];
    checks = table(name, passed, detail);
    outputDir = fullfile(cfg.paths.resultsRoot, ...
        [char(cfg.preset), '_hsgp_unit_checks']);
    ensure_directory(outputDir);
    writetable(checks, fullfile(outputDir, 'hsgp_unit_checks.csv'));
    if ~all(checks.passed)
        error('At least one Pacific HSGP unit check failed.');
    end
end
