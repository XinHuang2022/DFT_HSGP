function result = run_pacific_rff_stage0(configOrPreset, useParallel)
%RUN_PACIFIC_RFF_STAGE0 Validate RFF at fixed subset-trained theta.

% This stage deliberately does not optimize an RFF likelihood.  It first
% measures only the finite-feature approximation error against exact
% covariance and prediction at identical covariance parameters.

    if nargin < 1 || isempty(configOrPreset)
        cfg = pacific_scalable_config('full17_cv5');
    elseif isstruct(configOrPreset)
        cfg = configOrPreset;
    else
        cfg = pacific_scalable_config(configOrPreset);
    end
    if nargin >= 2 && ~isempty(useParallel)
        cfg.parallel.useParallel = logical(useParallel);
    end
    fitFile = fullfile(cfg.paths.subsetPluginDir, ...
        'subset_plugin_fits.mat');
    if ~isfile(fitFile)
        error(['Subset plug-in fits are required. Run ', ...
            'run_pacific_subset_plugin_cv first: %s'], fitFile);
    end
    loaded = load(fitFile, 'rffStage0Inputs');
    if ~isfield(loaded, 'rffStage0Inputs')
        error(['The subset fit file predates the target-response-free ', ...
            'RFF input artifact. Rerun run_pacific_subset_plugin_cv.']);
    end
    stageInputs = loaded.rffStage0Inputs;
    nFold = numel(stageInputs);
    ensure_directory(cfg.paths.rffStage0Dir);
    outputs = cell(nFold, 1);
    timerValue = tic;
    if cfg.parallel.useParallel && parallel_available()
        pool = gcp('nocreate');
        if isempty(pool) && cfg.parallel.autoStartPool
            pool = parpool(min(cfg.parallel.numWorkers, nFold));
        end
        parfor f = 1:nFold
            outputs{f} = run_pacific_rff_stage0_fold( ...
                cfg, stageInputs{f});
        end
    else
        for f = 1:nFold
            fprintf('RFF stage-0 fold %d/%d.\n', f, nFold);
            outputs{f} = run_pacific_rff_stage0_fold( ...
                cfg, stageInputs{f});
        end
    end
    elapsedSeconds = toc(timerValue);
    parts = cellfun(@(x) x.comparisons, outputs, ...
        'UniformOutput', false);
    comparisons = vertcat(parts{:});
    [seedSummary, featureSummary, decision] = ...
        summarize_stage0(comparisons, cfg);
    runSummary = table(string(cfg.version), string(cfg.preset), nFold, ...
        numel(cfg.rff.featureCounts), numel(cfg.rff.seeds), ...
        cfg.parallel.useParallel, elapsedSeconds, decision.stage0Passed, ...
        decision.recommendedFeatureCount, ...
        decision.targetResponseFree, ...
        decision.accelerationSupportedAtRecommendedP, ...
        'VariableNames', {'version', 'preset', 'nOuterFolds', ...
        'nFeatureCounts', 'nFeatureSeeds', 'parallelRequested', ...
        'elapsedSeconds', 'stage0Passed', 'recommendedFeatureCount', ...
        'targetResponseFree', ...
        'accelerationSupportedAtRecommendedP'});
    writetable(comparisons, fullfile(cfg.paths.rffStage0Dir, ...
        'rff_exact_comparisons.csv'));
    writetable(seedSummary, fullfile(cfg.paths.rffStage0Dir, ...
        'rff_seed_summary.csv'));
    writetable(featureSummary, fullfile(cfg.paths.rffStage0Dir, ...
        'rff_feature_summary.csv'));
    writetable(decision, fullfile(cfg.paths.rffStage0Dir, ...
        'rff_stage0_decision.csv'));
    writetable(runSummary, fullfile(cfg.paths.rffStage0Dir, ...
        'run_summary.csv'));
    save(fullfile(cfg.paths.rffStage0Dir, 'rff_stage0_results.mat'), ...
        'comparisons', 'seedSummary', 'featureSummary', 'decision', ...
        'cfg', '-v7.3');
    make_stage0_figures(featureSummary, cfg);
    fprintf('\nRFF stage 0 complete in %.1f minutes. Pass: %d.\n', ...
        elapsedSeconds / 60, decision.stage0Passed);
    if decision.stage0Passed
        fprintf('  Smallest accepted p: %d.\n', ...
            decision.recommendedFeatureCount);
    end
    fprintf('  Results: %s\n\n', cfg.paths.rffStage0Dir);
    result.cfg = cfg;
    result.comparisons = comparisons;
    result.seedSummary = seedSummary;
    result.featureSummary = featureSummary;
    result.decision = decision;
end

function [seedSummary, featureSummary, decision] = ...
        summarize_stage0(data, cfg)
    keys = unique(data(:, {'nFeatures', 'baseFeatureSeed'}), ...
        'rows', 'stable');
    rows = cell(height(keys), 1);
    for j = 1:height(keys)
        use = data.nFeatures == keys.nFeatures(j) & ...
            data.baseFeatureSeed == keys.baseFeatureSeed(j);
        part = data(use, :);
        covarianceError = median(part.medianLatentCovarianceRelativeError);
        predictionMeanRmse = max(part.predictionMeanRmseMps);
        observationVarianceError = max( ...
            part.medianObservationVarianceRelativeError);
        conditionalVarianceError = max( ...
            part.medianConditionalVarianceRelativeError);
        objectiveDifference = max(abs( ...
            part.objectiveDifferencePerObservation));
        minimumEss = min(part.minimumEssFraction);
        minimumCondition = min( ...
            part.minimumFeatureReciprocalCondition);
        maximumImaginary = max(part.maximumImaginaryPrediction);
        objectiveTolerance = ...
            cfg.rff.acceptance.maximumAbsoluteObjectiveDifferencePerObservation;
        observationVarianceTolerance = ...
            cfg.rff.acceptance.maximumMedianObservationVarianceRelativeError;
        conditionalVarianceTolerance = ...
            cfg.rff.acceptance.maximumMedianConditionalVarianceRelativeError;
        pass = covarianceError <= ...
            cfg.rff.acceptance.maximumMedianCovarianceError && ...
            predictionMeanRmse <= ...
            cfg.rff.acceptance.maximumPredictionMeanRmseMps && ...
            observationVarianceError <= observationVarianceTolerance && ...
            conditionalVarianceError <= conditionalVarianceTolerance && ...
            objectiveDifference <= objectiveTolerance && ...
            minimumEss >= cfg.rff.minimumEssFraction && ...
            minimumCondition >= 1 / cfg.rff.maximumConditionNumber && ...
            maximumImaginary <= ...
            cfg.rff.acceptance.maximumImaginaryPrediction && ...
            ~any(part.outerTargetResponsesAccessible);
        estimatedFlopRatio = median( ...
            part.estimatedFactorizationFlopRatio);
        observedObjectiveRatio = median(part.rffObjectiveSeconds ./ ...
            max(realmin('double'), part.exactObjectiveSeconds));
        rows{j} = table(keys.nFeatures(j), ...
            keys.baseFeatureSeed(j), ...
            covarianceError, predictionMeanRmse, ...
            observationVarianceError, conditionalVarianceError, ...
            objectiveDifference, minimumEss, ...
            minimumCondition, maximumImaginary, estimatedFlopRatio, ...
            observedObjectiveRatio, pass, ...
            'VariableNames', {'nFeatures', 'baseFeatureSeed', ...
            'medianCovarianceRelativeError', ...
            'maximumPredictionMeanRmseMps', ...
            'maximumMedianObservationVarianceRelativeError', ...
            'maximumMedianConditionalVarianceRelativeError', ...
            'maximumAbsoluteObjectiveDifferencePerObservation', ...
            'minimumEssFraction', ...
            'minimumFeatureReciprocalCondition', ...
            'maximumImaginaryPrediction', ...
            'estimatedFactorizationFlopRatio', ...
            'medianObservedObjectiveTimeRatio', 'passed'});
    end
    seedSummary = vertcat(rows{:});
    counts = unique(seedSummary.nFeatures, 'stable');
    featureRows = cell(numel(counts), 1);
    for j = 1:numel(counts)
        use = seedSummary.nFeatures == counts(j);
        objectiveErrors = ...
            seedSummary.maximumAbsoluteObjectiveDifferencePerObservation(use);
        observationVarianceErrors = ...
            seedSummary.maximumMedianObservationVarianceRelativeError(use);
        conditionalVarianceErrors = ...
            seedSummary.maximumMedianConditionalVarianceRelativeError(use);
        featureRows{j} = table(counts(j), sum(use), mean( ...
            seedSummary.passed(use)), ...
            median(seedSummary.medianCovarianceRelativeError(use)), ...
            median(seedSummary.maximumPredictionMeanRmseMps(use)), ...
            median(observationVarianceErrors), ...
            median(conditionalVarianceErrors), ...
            max(objectiveErrors), ...
            min(seedSummary.minimumEssFraction(use)), ...
            min(seedSummary.minimumFeatureReciprocalCondition(use)), ...
            max(seedSummary.maximumImaginaryPrediction(use)), ...
            median(seedSummary.estimatedFactorizationFlopRatio(use)), ...
            median(seedSummary.medianObservedObjectiveTimeRatio(use)), ...
            'VariableNames', {'nFeatures', 'nSeeds', ...
            'passingSeedFraction', 'medianCovarianceRelativeError', ...
            'medianMaximumPredictionMeanRmseMps', ...
            'medianMaximumObservationVarianceRelativeError', ...
            'medianMaximumConditionalVarianceRelativeError', ...
            'maximumAbsoluteObjectiveDifferencePerObservation', ...
            'minimumEssFraction', ...
            'minimumFeatureReciprocalCondition', ...
            'maximumImaginaryPrediction', ...
            'estimatedFactorizationFlopRatio', ...
            'medianObservedObjectiveTimeRatio'});
    end
    featureSummary = vertcat(featureRows{:});
    accepted = featureSummary.passingSeedFraction >= ...
        cfg.rff.acceptance.minimumPassingSeedFraction;
    if any(accepted)
        recommended = min(featureSummary.nFeatures(accepted));
        passed = true;
        reason = "target-response-free covariance, likelihood, " + ...
            "prediction, importance-weight, and numerical gates passed";
    else
        recommended = NaN;
        passed = false;
        reason = "no feature count passed the prespecified seed gate";
    end
    if passed
        selected = featureSummary.nFeatures == recommended;
        estimatedRatio = ...
            featureSummary.estimatedFactorizationFlopRatio(selected);
        observedRatio = ...
            featureSummary.medianObservedObjectiveTimeRatio(selected);
        accelerationSupported = estimatedRatio < ...
            cfg.rff.acceptance.maximumEstimatedFlopRatioForAcceleration && ...
            observedRatio < 1;
    else
        estimatedRatio = NaN;
        observedRatio = NaN;
        accelerationSupported = false;
    end
    targetResponseFree = ~any(data.outerTargetResponsesAccessible);
    decision = table(passed, recommended, targetResponseFree, ...
        accelerationSupported, ...
        estimatedRatio, observedRatio, reason, ...
        cfg.rff.acceptance.minimumPassingSeedFraction, ...
        'VariableNames', {'stage0Passed', 'recommendedFeatureCount', ...
        'targetResponseFree', ...
        'accelerationSupportedAtRecommendedP', ...
        'estimatedFactorizationFlopRatioAtRecommendedP', ...
        'observedObjectiveTimeRatioAtRecommendedP', ...
        'decisionReason', 'requiredPassingSeedFraction'});
end

function make_stage0_figures(summary, cfg)
    figureDir = fullfile(cfg.paths.rffStage0Dir, 'figures');
    ensure_directory(figureDir);
    objectiveTolerance = ...
        cfg.rff.acceptance.maximumAbsoluteObjectiveDifferencePerObservation;
    h = figure('Visible', cfg.figures.visible, 'Color', 'white', ...
        'Position', [100, 100, 1350, 760]);
    tiledlayout(2, 3);
    nexttile;
    semilogy(summary.nFeatures, ...
        summary.medianCovarianceRelativeError, '-o', 'LineWidth', 1.5);
    yline(cfg.rff.acceptance.maximumMedianCovarianceError, '--k');
    xlabel('Total Fourier columns p (p/2 +/- pairs)');
    ylabel('Covariance error');
    grid on;
    nexttile;
    plot(summary.nFeatures, ...
        summary.maximumAbsoluteObjectiveDifferencePerObservation, ...
        '-o', 'LineWidth', 1.5);
    yline(objectiveTolerance, ':k');
    xlabel('Total Fourier columns p (p/2 +/- pairs)');
    ylabel('Max |RFF - exact NLL| per observation');
    grid on;
    nexttile;
    plot(summary.nFeatures, ...
        summary.medianMaximumPredictionMeanRmseMps, ...
        '-o', 'LineWidth', 1.5);
    yline(cfg.rff.acceptance.maximumPredictionMeanRmseMps, ':k');
    xlabel('Total Fourier columns p (p/2 +/- pairs)');
    ylabel('RFF/exact prediction mean RMSE');
    grid on;
    nexttile;
    plot(summary.nFeatures, ...
        summary.medianMaximumObservationVarianceRelativeError, ...
        '-o', 'LineWidth', 1.5);
    varianceTolerance = ...
        cfg.rff.acceptance.maximumMedianObservationVarianceRelativeError;
    yline(varianceTolerance, ':k');
    xlabel('Total Fourier columns p (p/2 +/- pairs)');
    ylabel('Observation-variance relative error');
    grid on;
    nexttile;
    plot(summary.nFeatures, summary.minimumEssFraction, ...
        '-o', 'LineWidth', 1.5);
    yline(cfg.rff.minimumEssFraction, ':k');
    xlabel('Total Fourier columns p (p/2 +/- pairs)');
    ylabel('Minimum importance-weight ESS fraction');
    grid on;
    nexttile;
    plot(summary.nFeatures, summary.passingSeedFraction, ...
        '-o', 'LineWidth', 1.5);
    yline(cfg.rff.acceptance.minimumPassingSeedFraction, '--k');
    ylim([0, 1]); xlabel('Total Fourier columns p (p/2 +/- pairs)');
    ylabel('Passing seed fraction'); grid on;
    sgtitle('Spatial RFF fixed-theta acceptance diagnostics');
    pacific_save_figure(h, figureDir, 'rff_stage0_acceptance');
end

