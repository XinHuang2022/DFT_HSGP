function result = run_pacific_cv(presetOrConfig, useParallel)
%RUN_PACIFIC_CV Run fixed-fold Pacific unseen-location reconstruction.

    if nargin < 1 || isempty(presetOrConfig)
        presetOrConfig = 'smoke3';
    end
    if isstruct(presetOrConfig)
        cfg = presetOrConfig;
    else
        cfg = pacific_eq9_config(presetOrConfig);
    end
    if ~cfg.runModel
        error('The audit preset does not run covariance models.');
    end
    if nargin >= 2 && ~isempty(useParallel)
        cfg.parallel.useParallel = logical(useParallel);
    end

    timerValue = tic;
    audit = run_pacific_audit(cfg.preset);
    if ~all(audit.dataChecks.passed)
        error('Pacific data-contract checks failed; inspect audit outputs.');
    end
    contract = audit.contract;
    subset = make_pacific_subset(contract, cfg.subset.name);
    if strcmpi(cfg.subset.name, 'full17') && ...
            cfg.safety.requireFullGridOptIn && ...
            ~cfg.safety.fullGridOptIn
        error(['Dense full-grid CV is opt-in. First run ', ...
            'benchmark_pacific_objective(''full17_cv5'', 1). Then set ', ...
            'cfg = pacific_eq9_config(''full17_cv5''); ', ...
            'cfg.safety.fullGridOptIn = true; and call ', ...
            'run_pacific_cv(cfg, true).']);
    end
    if any(~isfinite(subset.U), 'all')
        error(['The selected subset contains missing/nonfinite data. ', ...
            'Version %s fits complete panels only.'], cfg.version);
    end

    [folds, foldManifest, foldSummary] = make_pacific_cv_folds( ...
        subset, cfg.cv.holdoutPattern);
    if isempty(folds)
        error('The selected model preset has no CV folds.');
    end
    ensure_directory(cfg.paths.outputDir);
    writetable(subset.siteTable, fullfile(cfg.paths.outputDir, ...
        'selected_subset_manifest.csv'));
    writetable(foldManifest, fullfile(cfg.paths.outputDir, ...
        'cv_fold_manifest.csv'));
    writetable(foldSummary, fullfile(cfg.paths.outputDir, ...
        'cv_fold_summary.csv'));
    writetable(foldManifest(foldManifest.isCvTarget, :), ...
        fullfile(cfg.paths.outputDir, 'holdout_manifest.csv'));
    save(fullfile(cfg.paths.outputDir, 'configuration.mat'), 'cfg');

    nTasks = numel(folds);
    nHeldOutSites = sum(foldSummary.nTargetSites);
    tasks = cell(nTasks, 1);
    parallelUsed = false;
    requestedWorkers = cfg.parallel.numWorkers;
    actualPoolWorkers = 1;
    effectiveWorkers = 1;
    if cfg.parallel.useParallel && parallel_available()
        parallelUsed = true;
        pool = gcp('nocreate');
        if isempty(pool) && cfg.parallel.autoStartPool
            pool = parpool(cfg.parallel.numWorkers);
        end
        if isempty(pool)
            error('Parallel execution was requested but no pool is open.');
        end
        actualPoolWorkers = pool.NumWorkers;
        effectiveWorkers = min(actualPoolWorkers, nTasks);
        if actualPoolWorkers > nTasks
            warning(['The pool has %d workers but only %d fold tasks; ', ...
                '%d workers cannot accelerate this run.'], ...
                actualPoolWorkers, nTasks, actualPoolWorkers - nTasks);
        end
        parfor j = 1:nTasks
            tasks{j} = run_pacific_one_fold(cfg, subset, ...
                folds(j).targetIndex, folds(j).foldID);
        end
    else
        if cfg.parallel.useParallel
            warning(['Parallel Computing Toolbox is unavailable; ', ...
                'using serial folds.']);
        end
        for j = 1:nTasks
            labels = folds(j).targetStations;
            fprintf(['Pacific fold %d/%d: holding out %d sites ', ...
                '(first: %s).\n'], j, nTasks, numel(labels), ...
                char(labels(1)));
            tasks{j} = run_pacific_one_fold(cfg, subset, ...
                folds(j).targetIndex, folds(j).foldID);
        end
    end

    metrics = concatenate_task_field(tasks, 'metrics');
    timeBlockMetrics = concatenate_task_field(tasks, 'timeBlockMetrics');
    predictions = concatenate_task_field(tasks, 'predictions');
    fitDiagnostics = concatenate_task_field(tasks, 'fitDiagnostics');
    implementationChecks = concatenate_task_field( ...
        tasks, 'implementationChecks');
    taskTiming = concatenate_task_field(tasks, 'timing');

    methodSummary = summarize_methods(metrics);
    fitSummary = summarize_fits(fitDiagnostics);
    pairedComparisons = make_paired_comparisons(metrics);
    varianceSummary = summarize_variance_decomposition( ...
        predictions, cfg.cv.nominalCoverage, false);
    varianceByTarget = summarize_variance_decomposition( ...
        predictions, cfg.cv.nominalCoverage, true);

    writetable(metrics, fullfile(cfg.paths.outputDir, 'fold_metrics.csv'));
    writetable(timeBlockMetrics, fullfile(cfg.paths.outputDir, ...
        'time_block_metrics.csv'));
    writetable(predictions, fullfile(cfg.paths.outputDir, ...
        'predictions.csv'));
    writetable(fitDiagnostics, fullfile(cfg.paths.outputDir, ...
        'fit_diagnostics.csv'));
    writetable(fitSummary, fullfile(cfg.paths.outputDir, ...
        'fit_diagnostic_summary.csv'));
    writetable(implementationChecks, fullfile(cfg.paths.outputDir, ...
        'implementation_checks.csv'));
    writetable(methodSummary, fullfile(cfg.paths.outputDir, ...
        'method_summary.csv'));
    writetable(pairedComparisons, fullfile(cfg.paths.outputDir, ...
        'paired_comparisons.csv'));
    writetable(varianceSummary, fullfile(cfg.paths.outputDir, ...
        'variance_decomposition_summary.csv'));
    writetable(varianceByTarget, fullfile(cfg.paths.outputDir, ...
        'variance_decomposition_by_target.csv'));
    writetable(taskTiming, fullfile(cfg.paths.outputDir, ...
        'task_timing.csv'));

    make_pacific_cv_figures(subset, metrics, timeBlockMetrics, ...
        predictions, fitDiagnostics, varianceSummary, cfg);
    elapsedSeconds = toc(timerValue);
    totalOptimizerSeconds = sum(fitDiagnostics.elapsedSeconds);
    optimizerToWallRatio = totalOptimizerSeconds / elapsedSeconds;
    runSummary = table(string(cfg.version), string(cfg.preset), ...
        string(cfg.subset.name), height(subset.siteTable), nTasks, ...
        nHeldOutSites, parallelUsed, requestedWorkers, ...
        actualPoolWorkers, effectiveWorkers, elapsedSeconds, ...
        totalOptimizerSeconds, optimizerToWallRatio, ...
        all(audit.dataChecks.passed), ...
        all(implementationChecks.passed), ...
        mean(fitDiagnostics.convergenceCertified), ...
        'VariableNames', {'version', 'preset', 'subsetName', ...
        'nSubsetSites', 'nCvFolds', 'nHeldOutSites', 'parallelUsed', ...
        'requestedWorkers', 'actualPoolWorkers', 'effectiveWorkers', ...
        'elapsedSeconds', 'totalOptimizerSeconds', ...
        'optimizerToWallRatio', 'allDataChecksPassed', ...
        'allImplementationChecksPassed', ...
        'optimizerConvergenceFraction'});
    writetable(runSummary, fullfile(cfg.paths.outputDir, ...
        'run_summary.csv'));

    fprintf('\nPacific %s run complete in %.1f minutes.\n', ...
        cfg.preset, elapsedSeconds / 60);
    fprintf('  Subset: %s (%d sites); folds: %d; targets: %d.\n', ...
        cfg.subset.name, height(subset.siteTable), nTasks, ...
        nHeldOutSites);
    fprintf('  Effective parallel workers: %d.\n', effectiveWorkers);
    fprintf('  All implementation checks passed: %d.\n', ...
        all(implementationChecks.passed));
    fprintf('  Results: %s\n\n', cfg.paths.outputDir);

    result.cfg = cfg;
    result.audit = audit;
    result.subset = subset;
    result.folds = folds;
    result.foldManifest = foldManifest;
    result.foldSummary = foldSummary;
    result.metrics = metrics;
    result.timeBlockMetrics = timeBlockMetrics;
    result.predictions = predictions;
    result.fitDiagnostics = fitDiagnostics;
    result.methodSummary = methodSummary;
    result.pairedComparisons = pairedComparisons;
    result.varianceSummary = varianceSummary;
    result.varianceByTarget = varianceByTarget;
    result.implementationChecks = implementationChecks;
    result.taskTiming = taskTiming;
    result.runSummary = runSummary;
end

function output = concatenate_task_field(tasks, fieldName)
    parts = cellfun(@(x) x.(fieldName), tasks, ...
        'UniformOutput', false);
    output = vertcat(parts{:});
end

function available = parallel_available()
    available = false;
    try
        available = license('test', 'Distrib_Computing_Toolbox');
    catch
        available = false;
    end
end

function summary = summarize_methods(metrics)
    methods = unique(metrics.method, 'stable');
    rows = cell(numel(methods), 1);
    for j = 1:numel(methods)
        use = metrics.method == methods(j);
        rows{j} = table(methods(j), ...
            numel(unique(metrics.foldID(use))), sum(use), ...
            finite_mean(metrics.rmse(use)), finite_se(metrics.rmse(use)), ...
            finite_mean(metrics.mae(use)), ...
            finite_mean(metrics.correlation(use)), ...
            finite_mean(metrics.nlpd(use)), ...
            finite_mean(metrics.crps(use)), ...
            finite_mean(metrics.coverage95(use)), ...
            finite_mean(metrics.meanIntervalWidth95(use)), ...
            'VariableNames', {'method', 'nCvFolds', 'nTargetSites', ...
            'meanRmse', 'seRmseAcrossSites', 'meanMae', ...
            'meanCorrelation', 'meanNlpd', 'meanCrps', ...
            'meanCoverage95', 'meanIntervalWidth95'});
    end
    summary = vertcat(rows{:});
end

function summary = summarize_fits(fits)
    methods = unique(fits.method, 'stable');
    rows = cell(numel(methods), 1);
    for j = 1:numel(methods)
        use = fits.method == methods(j);
        rows{j} = table(methods(j), sum(use), ...
            mean(fits.convergenceCertified(use)), ...
            mean(fits.boundaryHit(use)), ...
            mean(fits.polishTriggered(use)), ...
            finite_mean(fits.elapsedSeconds(use)), ...
            finite_mean(fits.totalFunctionEvaluations(use)), ...
            finite_median(fits.signalVariance(use)), ...
            finite_median(fits.alphaPer100Km(use)), ...
            finite_median(fits.betaPerSixHours(use)), ...
            finite_median(fits.epsilon(use)), ...
            finite_median(fits.noiseVariance(use)), ...
            finite_median(fits.timeScaleHours(use)), ...
            'VariableNames', {'method', 'nFits', ...
            'convergenceFraction', 'boundaryHitFraction', ...
            'polishTriggeredFraction', 'meanElapsedSeconds', ...
            'meanFunctionEvaluations', 'medianSignalVariance', ...
            'medianAlphaPer100Km', 'medianBetaPerSixHours', ...
            'medianEpsilon', 'medianNoiseVariance', ...
            'medianTimeScaleHours'});
    end
    summary = vertcat(rows{:});
end

function comparisons = make_paired_comparisons(metrics)
    targets = unique(metrics.targetStation, 'stable');
    rows = cell(2 * numel(targets), 1);
    index = 0;
    for j = 1:numel(targets)
        full = metrics(metrics.targetStation == targets(j) & ...
            metrics.method == "fitted_eq9", :);
        for comparator = ["separable_eq9", "mean_only"]
            other = metrics(metrics.targetStation == targets(j) & ...
                metrics.method == comparator, :);
            if height(full) ~= 1 || height(other) ~= 1
                error('Each Pacific target must be scored once per method.');
            end
            index = index + 1;
            rows{index} = table(full.foldID, targets(j), comparator, ...
                full.rmse - other.rmse, full.mae - other.mae, ...
                full.correlation - other.correlation, ...
                'VariableNames', {'foldID', 'targetStation', ...
                'comparator', 'fittedMinusComparatorRmse', ...
                'fittedMinusComparatorMae', ...
                'fittedMinusComparatorCorrelation'});
        end
    end
    comparisons = vertcat(rows{:});
end

function summary = summarize_variance_decomposition( ...
        predictions, nominalCoverage, byTarget)
    keep = isfinite(predictions.observationVariance) & ...
        predictions.observationVariance > 0;
    data = predictions(keep, :);
    if byTarget
        groups = unique(data(:, {'method', 'foldID', ...
            'targetStation'}), 'rows', 'stable');
    else
        groups = unique(data(:, {'method'}), 'rows', 'stable');
    end
    rows = cell(height(groups), 1);
    critical = sqrt(2) * erfinv(nominalCoverage);
    for j = 1:height(groups)
        if byTarget
            use = data.method == groups.method(j) & ...
                data.foldID == groups.foldID(j) & ...
                data.targetStation == groups.targetStation(j);
        else
            use = data.method == groups.method(j);
        end
        part = data(use, :);
        squaredError = part.residual .^ 2;
        empiricalMse = mean(squaredError);
        meanObservationVariance = mean(part.observationVariance);
        standardizedSd = std(part.standardizedResidual, 0);
        coverage = mean(abs(part.standardizedResidual) <= critical);
        closure = max(abs(part.varianceClosureError));
        if byTarget
            rows{j} = table(groups.method(j), groups.foldID(j), ...
                groups.targetStation(j), height(part), ...
                mean(part.residual), empiricalMse, sqrt(empiricalMse), ...
                mean(part.conditionalProcessVariance), ...
                mean(part.fixedEffectVariance), ...
                mean(part.nuggetVariance), mean(part.latentVariance), ...
                meanObservationVariance, ...
                empiricalMse / meanObservationVariance, ...
                meanObservationVariance / empiricalMse, ...
                standardizedSd, coverage, closure, ...
                'VariableNames', variance_names(true));
        else
            rows{j} = table(groups.method(j), height(part), ...
                mean(part.residual), empiricalMse, sqrt(empiricalMse), ...
                mean(part.conditionalProcessVariance), ...
                mean(part.fixedEffectVariance), ...
                mean(part.nuggetVariance), mean(part.latentVariance), ...
                meanObservationVariance, ...
                empiricalMse / meanObservationVariance, ...
                meanObservationVariance / empiricalMse, ...
                standardizedSd, coverage, closure, ...
                'VariableNames', variance_names(false));
        end
    end
    summary = vertcat(rows{:});
end

function names = variance_names(byTarget)
    common = {'nValues', 'residualBias', 'empiricalMse', ...
        'pooledRmse', 'meanConditionalProcessVariance', ...
        'meanFixedEffectVariance', 'meanNuggetVariance', ...
        'meanLatentVariance', 'meanObservationVariance', ...
        'mseOverObservationVariance', 'observationVarianceOverMse', ...
        'standardizedResidualSd', 'coverage95', ...
        'maximumVarianceClosureError'};
    if byTarget
        names = [{'method', 'foldID', 'targetStation'}, common];
    else
        names = [{'method'}, common];
    end
end

function value = finite_mean(x)
    x = x(isfinite(x));
    if isempty(x), value = NaN; else, value = mean(x); end
end

function value = finite_median(x)
    x = x(isfinite(x));
    if isempty(x), value = NaN; else, value = median(x); end
end

function value = finite_se(x)
    x = x(isfinite(x));
    if numel(x) <= 1
        value = NaN;
    else
        value = std(x, 0) / sqrt(numel(x));
    end
end
