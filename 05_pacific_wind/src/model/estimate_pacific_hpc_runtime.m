function estimate = estimate_pacific_hpc_runtime( ...
        localFitCsv, fullBenchmarkCsv, safetyFactor)
%ESTIMATE_PACIFIC_HPC_RUNTIME Project five-fold dense full-grid wall time.
%
% Run local7_cv5 and benchmark_pacific_objective('full17_cv5',1) first.
% The estimate assumes five folds execute concurrently on five workers and
% uses local7 optimizer evaluation counts as a first planning proxy.

    suiteRoot = fileparts(mfilename('fullpath'));
    if nargin < 1 || isempty(localFitCsv)
        localFitCsv = fullfile(suiteRoot, 'Results', 'local7_cv5', ...
            'fit_diagnostics.csv');
    end
    if nargin < 2 || isempty(fullBenchmarkCsv)
        fullBenchmarkCsv = fullfile(suiteRoot, 'Results', ...
            'full17_cv5', 'objective_benchmark.csv');
    end
    if nargin < 3 || isempty(safetyFactor)
        safetyFactor = 1.5;
    end
    validateattributes(safetyFactor, {'numeric'}, ...
        {'scalar', 'finite', '>=', 1});
    if ~isfile(localFitCsv) || ~isfile(fullBenchmarkCsv)
        error(['Required CSV files are missing. Complete local7_cv5 and ', ...
            'the full17 objective benchmark first.']);
    end

    fits = readtable(localFitCsv, 'TextType', 'string');
    benchmark = readtable(fullBenchmarkCsv, 'TextType', 'string');
    fullEvaluations = median(fits.totalFunctionEvaluations( ...
        fits.method == "fitted_eq9"));
    separableEvaluations = median(fits.totalFunctionEvaluations( ...
        fits.method == "separable_eq9"));
    if isempty(fullEvaluations) || isempty(separableEvaluations) || ...
            height(benchmark) ~= 1
        error('The timing inputs do not have the expected method rows.');
    end
    rawFoldSeconds = fullEvaluations * ...
        benchmark.medianFullSecondsPerEvaluation + ...
        separableEvaluations * ...
        benchmark.medianSeparableSecondsPerEvaluation;
    % Prediction, output, worker imbalance, and non-benchmark operations.
    overheadFactor = 1.10;
    projectedWallHours = rawFoldSeconds * overheadFactor / 3600;
    conservativeWallHours = projectedWallHours * safetyFactor;
    projectedCoreHours = 5 * projectedWallHours;
    withinSevenDays = conservativeWallHours < 168;

    estimate = table(fullEvaluations, separableEvaluations, ...
        benchmark.medianFullSecondsPerEvaluation, ...
        benchmark.medianSeparableSecondsPerEvaluation, ...
        overheadFactor, safetyFactor, projectedWallHours, ...
        conservativeWallHours, projectedCoreHours, withinSevenDays, ...
        'VariableNames', {'expectedFullFunctionEvaluations', ...
        'expectedSeparableFunctionEvaluations', ...
        'fullSecondsPerEvaluation', 'separableSecondsPerEvaluation', ...
        'overheadFactor', 'safetyFactor', 'projectedWallHours', ...
        'conservativeWallHours', 'projectedCoreHours', ...
        'conservativeProjectionWithinSevenDays'});
    outputPath = fullfile(suiteRoot, 'Results', 'full17_cv5');
    ensure_directory(outputPath);
    writetable(estimate, fullfile(outputPath, ...
        'hpc_runtime_projection.csv'));
    fprintf(['Projected dense five-fold wall time with five workers: ', ...
        '%.1f hours; conservative %.1f hours (factor %.2f).\n'], ...
        projectedWallHours, conservativeWallHours, safetyFactor);
end
