function task = run_pacific_subset_plugin_fold(cfg, subset, ...
        targetIndex, foldID, nuggetRule)
%RUN_PACIFIC_SUBSET_PLUGIN_FOLD Subset-fit, all-site exact conditioning.

    timerValue = tic;
    nSites = size(subset.U, 2);
    targetIndex = unique(targetIndex(:), 'stable');
    observedIndex = setdiff((1:nSites)', targetIndex, 'stable');
    [outerGeometry, targetGeometry] = fold_geometry( ...
        subset.xyKm(observedIndex, :), subset.xyKm(targetIndex, :), cfg);
    nSubsetCandidate = max(1, ...
        cfg.scalable.nSubsetSeedsForSensitivity);
    subsetCandidates = cell(nSubsetCandidate, 1);
    for candidateID = 1:nSubsetCandidate
        subsetCandidates{candidateID} = fit_pacific_subset_candidate( ...
            cfg, subset, observedIndex, outerGeometry, foldID, ...
            candidateID, nuggetRule);
    end
    allTrainingObjective = cellfun(@(x) ...
        x.fullFit.objective, subsetCandidates);
    [~, selectedCandidateID] = min(allTrainingObjective);
    selectedCandidate = subsetCandidates{selectedCandidateID};
    parameterIndex = selectedCandidate.parameterIndex;
    nParameter = numel(parameterIndex);
    varianceReference = selectedCandidate.varianceReference;
    fullFitSubset = selectedCandidate.fullFitSubset;
    separableFitSubset = selectedCandidate.separableFitSubset;
    fullFit = selectedCandidate.fullFit;
    separableFit = selectedCandidate.separableFit;
    Yobserved = subset.U(:, observedIndex);
    predictionTimer = tic;
    fullPrediction = predict_pacific_eq9(Yobserved, ...
        outerGeometry.xyCovariance, targetGeometry.xyCovariance, ...
        outerGeometry.design, targetGeometry.design, fullFit, cfg);
    fullPredictionSeconds = toc(predictionTimer);
    predictionTimer = tic;
    separablePrediction = predict_pacific_eq9(Yobserved, ...
        outerGeometry.xyCovariance, targetGeometry.xyCovariance, ...
        outerGeometry.design, targetGeometry.design, separableFit, cfg);
    separablePredictionSeconds = toc(predictionTimer);

    Ytarget = subset.U(:, targetIndex);
    targetSites = subset.siteTable(targetIndex, :);
    nTarget = numel(targetIndex);
    metricRows = cell(3 * nTarget, 1);
    predictionRows = cell(3 * nTarget, 1);
    for j = 1:nTarget
        nearest = min(sqrt(sum((subset.xyKm(observedIndex, :) - ...
            subset.xyKm(targetIndex(j), :)) .^ 2, 2)));
        fullMetrics = eq9_prediction_metrics(Ytarget(:, j), ...
            fullPrediction.mean(:, j), ...
            fullPrediction.observationVariance(:, j), ...
            cfg.cv.nominalCoverage);
        separableMetrics = eq9_prediction_metrics(Ytarget(:, j), ...
            separablePrediction.mean(:, j), ...
            separablePrediction.observationVariance(:, j), ...
            cfg.cv.nominalCoverage);
        meanMetrics = pacific_point_metrics(Ytarget(:, j), ...
            fullPrediction.meanOnly(:, j));
        cursor = 3 * (j - 1);
        metricRows{cursor + 1} = metric_row("subset_plugin_eq9", ...
            foldID, targetSites(j, :), nearest, fullMetrics);
        metricRows{cursor + 2} = metric_row( ...
            "subset_plugin_separable", foldID, targetSites(j, :), ...
            nearest, separableMetrics);
        metricRows{cursor + 3} = point_metric_row("mean_only", ...
            foldID, targetSites(j, :), nearest, meanMetrics);
        predictionRows{cursor + 1} = prediction_table( ...
            "subset_plugin_eq9", foldID, targetSites(j, :), subset, ...
            Ytarget(:, j), fullPrediction, j, ...
            fullFit.theta.noiseVariance);
        predictionRows{cursor + 2} = prediction_table( ...
            "subset_plugin_separable", foldID, targetSites(j, :), ...
            subset, Ytarget(:, j), separablePrediction, j, ...
            separableFit.theta.noiseVariance);
        predictionRows{cursor + 3} = mean_prediction_table(foldID, ...
            targetSites(j, :), subset, Ytarget(:, j), ...
            fullPrediction.meanOnly(:, j));
    end

    fitDiagnostics = [fit_row("subset_plugin_eq9", foldID, ...
        nParameter, numel(observedIndex), nTarget, fullFitSubset, ...
        fullFit.objective, varianceReference, nuggetRule); ...
        fit_row("subset_plugin_separable", foldID, nParameter, ...
        numel(observedIndex), nTarget, separableFitSubset, ...
        separableFit.objective, varianceReference, nuggetRule)];
    sensitivityParts = cellfun(@(x) x.row, subsetCandidates, ...
        'UniformOutput', false);
    subsetSensitivity = vertcat(sensitivityParts{:});
    subsetSensitivity.selectedForPrediction = ...
        subsetSensitivity.subsetCandidateID == selectedCandidateID;
    manifestParts = cellfun(@(x) x.manifest, subsetCandidates, ...
        'UniformOutput', false);
    selectionTable = vertcat(manifestParts{:});
    selectionTable.selectedForPrediction = ...
        selectionTable.subsetCandidateID == selectedCandidateID;
    check = ["outer targets absent from parameter subset"; ...
        "parameter subset contained in outer training"; ...
        "all outer-training sites used for conditioning"; ...
        "full predictions finite"; ...
        "full predictive variances positive"; ...
        "separable predictions finite"; ...
        "separable predictive variances positive"];
    passed = [isempty(intersect(targetIndex, ...
        unique(selectionTable.subsetIndex))); ...
        all(ismember(parameterIndex, observedIndex)); ...
        size(Yobserved, 2) == numel(observedIndex); ...
        all(isfinite(fullPrediction.mean), 'all'); ...
        all(fullPrediction.observationVariance > 0, 'all'); ...
        all(isfinite(separablePrediction.mean), 'all'); ...
        all(separablePrediction.observationVariance > 0, 'all')];
    checks = table(repmat(foldID, numel(check), 1), check, passed, ...
        'VariableNames', {'foldID', 'check', 'passed'});
    totalSubsetFitSeconds = sum( ...
        subsetSensitivity.fullSubsetFitSeconds + ...
        subsetSensitivity.separableSubsetFitSeconds);
    timing = table(foldID, nSubsetCandidate, selectedCandidateID, ...
        nParameter, numel(observedIndex), nTarget, ...
        separableFitSubset.elapsedSeconds, fullFitSubset.elapsedSeconds, ...
        totalSubsetFitSeconds, fullPredictionSeconds, ...
        separablePredictionSeconds, ...
        toc(timerValue), 'VariableNames', {'foldID', ...
        'nSubsetCandidates', 'selectedSubsetCandidateID', ...
        'nParameterSites', 'nConditioningSites', 'nTargetSites', ...
        'separableSubsetFitSeconds', 'fullSubsetFitSeconds', ...
        'totalSubsetFitSeconds', ...
        'fullExactPredictionSeconds', ...
        'separableExactPredictionSeconds', 'foldElapsedSeconds'});

    task.metrics = vertcat(metricRows{:});
    task.predictions = vertcat(predictionRows{:});
    task.fitDiagnostics = fitDiagnostics;
    task.subsetSensitivity = subsetSensitivity;
    task.parameterManifest = selectionTable;
    task.checks = checks;
    task.timing = timing;
    task.fullFitSubset = fullFitSubset;
    task.separableFitSubset = separableFitSubset;
    task.fullFit = fullFit;
    task.separableFit = separableFit;
    task.fullPrediction = fullPrediction;
    task.observedIndex = observedIndex;
    task.targetIndex = targetIndex;
    task.outerGeometry = outerGeometry;
    task.targetGeometry = targetGeometry;
    task.subsetCandidates = subsetCandidates;
end

function row = metric_row(method, foldID, site, distance, metrics)
    row = table(method, foldID, string(site.stationID), site.gridRow, ...
        site.gridColumn, site.xKm, site.yKm, distance, metrics.nValues, ...
        metrics.rmse, metrics.mae, metrics.correlation, metrics.nlpd, ...
        metrics.crps, metrics.coverage, metrics.meanIntervalWidth, ...
        'VariableNames', {'method', 'foldID', 'targetStation', ...
        'gridRow', 'gridColumn', 'xKm', 'yKm', ...
        'nearestTrainingDistanceKm', 'nValues', 'rmse', 'mae', ...
        'correlation', 'nlpd', 'crps', 'coverage95', ...
        'meanIntervalWidth95'});
end

function row = point_metric_row(method, foldID, site, distance, metrics)
    row = table(method, foldID, string(site.stationID), site.gridRow, ...
        site.gridColumn, site.xKm, site.yKm, distance, metrics.nValues, ...
        metrics.rmse, metrics.mae, metrics.correlation, NaN, NaN, NaN, ...
        NaN, 'VariableNames', {'method', 'foldID', 'targetStation', ...
        'gridRow', 'gridColumn', 'xKm', 'yKm', ...
        'nearestTrainingDistanceKm', 'nValues', 'rmse', 'mae', ...
        'correlation', 'nlpd', 'crps', 'coverage95', ...
        'meanIntervalWidth95'});
end

function rows = prediction_table(method, foldID, site, subset, truth, ...
        prediction, column, noiseVariance)
    T = numel(truth);
    meanValue = prediction.mean(:, column);
    processVariance = prediction.conditionalProcessVariance(:, column);
    fixedVariance = prediction.fixedEffectVariance(:, column);
    nugget = repmat(noiseVariance, T, 1);
    latent = prediction.latentVariance(:, column);
    observation = prediction.observationVariance(:, column);
    residual = truth - meanValue;
    standardized = residual ./ sqrt(observation);
    rows = table(repmat(method, T, 1), repmat(foldID, T, 1), ...
        repmat(string(site.stationID), T, 1), ...
        repmat(site.gridRow, T, 1), repmat(site.gridColumn, T, 1), ...
        subset.timeIndex, subset.relativeHours, truth, meanValue, ...
        processVariance, fixedVariance, nugget, latent, observation, ...
        residual, standardized, 'VariableNames', {'method', 'foldID', ...
        'targetStation', 'gridRow', 'gridColumn', 'timeIndex', ...
        'relativeHours', 'truthUWindMps', 'predictionUWindMps', ...
        'conditionalProcessVariance', 'fixedEffectVariance', ...
        'nuggetVariance', 'latentVariance', 'observationVariance', ...
        'residual', 'standardizedResidual'});
end

function rows = mean_prediction_table(foldID, site, subset, truth, meanValue)
    T = numel(truth);
    missing = nan(T, 1);
    rows = table(repmat("mean_only", T, 1), repmat(foldID, T, 1), ...
        repmat(string(site.stationID), T, 1), ...
        repmat(site.gridRow, T, 1), repmat(site.gridColumn, T, 1), ...
        subset.timeIndex, subset.relativeHours, truth, meanValue, ...
        missing, missing, missing, missing, missing, truth - meanValue, ...
        missing, 'VariableNames', {'method', 'foldID', 'targetStation', ...
        'gridRow', 'gridColumn', 'timeIndex', 'relativeHours', ...
        'truthUWindMps', 'predictionUWindMps', ...
        'conditionalProcessVariance', 'fixedEffectVariance', ...
        'nuggetVariance', 'latentVariance', 'observationVariance', ...
        'residual', 'standardizedResidual'});
end

function row = fit_row(method, foldID, nParameter, nConditioning, ...
        nTarget, subsetFit, allTrainingObjective, varianceReference, rule)
    row = table(method, foldID, nParameter, nConditioning, nTarget, ...
        subsetFit.objective, allTrainingObjective, ...
        subsetFit.theta.signalVariance, subsetFit.theta.alpha, ...
        subsetFit.theta.beta, subsetFit.theta.epsilon, ...
        subsetFit.theta.noiseVariance, ...
        subsetFit.theta.noiseVariance / ...
        (subsetFit.theta.signalVariance + subsetFit.theta.noiseVariance), ...
        varianceReference, rule.mode, rule.residualVarianceFraction, ...
        subsetFit.convergenceCertified, subsetFit.elapsedSeconds, ...
        subsetFit.totalFunctionEvaluations, ...
        'VariableNames', {'method', 'foldID', 'nParameterSites', ...
        'nConditioningSites', 'nTargetSites', 'subsetObjective', ...
        'allTrainingObjectiveAtSubsetTheta', 'signalVariance', ...
        'alphaPer100Km', 'betaPerSixHours', 'epsilon', ...
        'noiseVariance', 'modelNuggetFraction', ...
        'residualVarianceReference', 'nuggetRule', ...
        'nuggetResidualVarianceFraction', 'convergenceCertified', ...
        'subsetFitSeconds', 'totalFunctionEvaluations'});
end

function [observed, target] = fold_geometry(xyObservedKm, xyTargetKm, cfg)
    center = mean(xyObservedKm, 1);
    scale = std(xyObservedKm, 0, 1);
    scale(scale <= sqrt(eps)) = 1;
    observed.xyMean = (xyObservedKm - center) ./ scale;
    target.xyMean = (xyTargetKm - center) ./ scale;
    observed.xyCovariance = (xyObservedKm - center) ./ ...
        cfg.spatial.coordinateScaleKm;
    target.xyCovariance = (xyTargetKm - center) ./ ...
        cfg.spatial.coordinateScaleKm;
    T = cfg.data.expectedTimePoints;
    observed.design = make_pacific_mean_design(T, observed.xyMean);
    target.design = make_pacific_mean_design(T, target.xyMean);
end
