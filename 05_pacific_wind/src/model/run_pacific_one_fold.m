function task = run_pacific_one_fold(cfg, subset, targetLocalIndex, foldID)
%RUN_PACIFIC_ONE_FOLD Fit Equation 9 for one multi-site CV fold.

    if nargin < 4 || isempty(foldID)
        foldID = 1;
    end
    foldTimer = tic;
    targetLocalIndex = unique(targetLocalIndex(:), 'stable');
    U = subset.U;
    [T, nSites] = size(U);
    if isempty(targetLocalIndex) || any(targetLocalIndex < 1) || ...
            any(targetLocalIndex > nSites)
        error('Pacific target indices are empty or out of range.');
    end
    observedIndex = setdiff((1:nSites)', targetLocalIndex, 'stable');
    targetIndex = targetLocalIndex;
    nObserved = numel(observedIndex);
    nTarget = numel(targetIndex);
    Yobserved = U(:, observedIndex);
    Ytarget = U(:, targetIndex);
    xyObservedKm = subset.xyKm(observedIndex, :);
    xyTargetKm = subset.xyKm(targetIndex, :);

    meanCenter = mean(xyObservedKm, 1);
    meanScale = std(xyObservedKm, 0, 1);
    meanScale(meanScale <= sqrt(eps)) = 1;
    xyMeanObserved = (xyObservedKm - meanCenter) ./ meanScale;
    xyMeanTarget = (xyTargetKm - meanCenter) ./ meanScale;
    xyCovObserved = (xyObservedKm - meanCenter) ./ ...
        cfg.spatial.coordinateScaleKm;
    xyCovTarget = (xyTargetKm - meanCenter) ./ ...
        cfg.spatial.coordinateScaleKm;
    observedDesign = make_pacific_mean_design(T, xyMeanObserved);
    targetDesign = make_pacific_mean_design(T, xyMeanTarget);
    seed = cfg.seed.optimizer + 101 * foldID + 17 * sum(targetIndex);

    separableFit = fit_pacific_eq9_model(Yobserved, xyCovObserved, ...
        observedDesign, cfg, 1, cfg.optimizer, seed + 1);
    embeddedTheta = separableFit.theta;
    embeddedTheta.epsilon = cfg.bounds.epsilon(2);
    fullOptimizer = cfg.optimizer;
    fullOptimizer.additionalStartZ = ...
        eq9_pack_parameters(embeddedTheta, cfg);
    fullFit = fit_pacific_eq9_model(Yobserved, xyCovObserved, ...
        observedDesign, cfg, [], fullOptimizer, seed + 2);

    predictionTimer = tic;
    separablePrediction = predict_pacific_eq9(Yobserved, ...
        xyCovObserved, xyCovTarget, observedDesign, targetDesign, ...
        separableFit, cfg);
    separablePredictionSeconds = toc(predictionTimer);
    predictionTimer = tic;
    fullPrediction = predict_pacific_eq9(Yobserved, xyCovObserved, ...
        xyCovTarget, observedDesign, targetDesign, fullFit, cfg);
    fullPredictionSeconds = toc(predictionTimer);

    sites = subset.siteTable(targetIndex, :);
    metricRows = cell(3 * nTarget, 1);
    blockRows = cell(2 * cfg.cv.timeBlocks * nTarget, 1);
    predictionRows = cell(3 * nTarget, 1);
    blockID = min(cfg.cv.timeBlocks, ceil((1:T)' * ...
        cfg.cv.timeBlocks / T));
    metricCursor = 0;
    blockCursor = 0;
    predictionCursor = 0;
    for j = 1:nTarget
        site = sites(j, :);
        nearestDistanceKm = min(sqrt(sum((xyObservedKm - ...
            xyTargetKm(j, :)) .^ 2, 2)));
        fullMetrics = eq9_prediction_metrics(Ytarget(:, j), ...
            fullPrediction.mean(:, j), ...
            fullPrediction.observationVariance(:, j), ...
            cfg.cv.nominalCoverage);
        separableMetrics = eq9_prediction_metrics(Ytarget(:, j), ...
            separablePrediction.mean(:, j), ...
            separablePrediction.observationVariance(:, j), ...
            cfg.cv.nominalCoverage);
        meanOnlyMetrics = pacific_point_metrics(Ytarget(:, j), ...
            fullPrediction.meanOnly(:, j));
        metricRows{metricCursor + 1} = probabilistic_metric_row( ...
            "fitted_eq9", foldID, site, nearestDistanceKm, fullMetrics);
        metricRows{metricCursor + 2} = probabilistic_metric_row( ...
            "separable_eq9", foldID, site, nearestDistanceKm, ...
            separableMetrics);
        metricRows{metricCursor + 3} = point_metric_row( ...
            "mean_only", foldID, site, nearestDistanceKm, ...
            meanOnlyMetrics);
        metricCursor = metricCursor + 3;

        for b = 1:cfg.cv.timeBlocks
            use = blockID == b;
            fullBlock = eq9_prediction_metrics(Ytarget(use, j), ...
                fullPrediction.mean(use, j), ...
                fullPrediction.observationVariance(use, j), ...
                cfg.cv.nominalCoverage);
            separableBlock = eq9_prediction_metrics(Ytarget(use, j), ...
                separablePrediction.mean(use, j), ...
                separablePrediction.observationVariance(use, j), ...
                cfg.cv.nominalCoverage);
            blockRows{blockCursor + 1} = block_metric_row( ...
                "fitted_eq9", foldID, site, b, fullBlock);
            blockRows{blockCursor + 2} = block_metric_row( ...
                "separable_eq9", foldID, site, b, separableBlock);
            blockCursor = blockCursor + 2;
        end

        predictionRows{predictionCursor + 1} = prediction_rows( ...
            "fitted_eq9", foldID, site, subset, Ytarget(:, j), ...
            fullPrediction, j, fullFit.theta.noiseVariance);
        predictionRows{predictionCursor + 2} = prediction_rows( ...
            "separable_eq9", foldID, site, subset, Ytarget(:, j), ...
            separablePrediction, j, separableFit.theta.noiseVariance);
        predictionRows{predictionCursor + 3} = mean_only_prediction_rows( ...
            foldID, site, subset, Ytarget(:, j), ...
            fullPrediction.meanOnly(:, j));
        predictionCursor = predictionCursor + 3;
    end

    targetLabel = strjoin(string(sites.stationID), ';');
    fitDiagnostics = [fit_diagnostic_row("fitted_eq9", foldID, ...
        targetLabel, nObserved, nTarget, fullFit, cfg); ...
        fit_diagnostic_row("separable_eq9", foldID, targetLabel, ...
        nObserved, nTarget, separableFit, cfg)];
    fitDiagnostics.objectiveDifferenceFromSeparable = ...
        [fullFit.objective - separableFit.objective; 0];

    fullClosure = variance_closure_error(fullPrediction, ...
        fullFit.theta.noiseVariance);
    separableClosure = variance_closure_error(separablePrediction, ...
        separableFit.theta.noiseVariance);
    maximumImaginary = max([fullPrediction.maximumImaginaryPrediction, ...
        fullPrediction.maximumImaginarySensitivity, ...
        separablePrediction.maximumImaginaryPrediction, ...
        separablePrediction.maximumImaginarySensitivity]);
    check = ["observed and target sites disjoint"; ...
        "target columns absent from training matrix"; ...
        "full fit convergence certified"; ...
        "separable fit convergence certified"; ...
        "full predictions finite"; ...
        "full predictive variances positive"; ...
        "full variance components nonnegative"; ...
        "full variance decomposition closes"; ...
        "separable predictions finite"; ...
        "separable predictive variances positive"; ...
        "separable variance decomposition closes"; ...
        "full model respects separable nesting"; ...
        "imaginary reconstruction negligible"];
    passed = [isempty(intersect(observedIndex, targetIndex)); ...
        size(Yobserved, 2) == nSites - nTarget; ...
        fullFit.convergenceCertified; ...
        separableFit.convergenceCertified; ...
        all(isfinite(fullPrediction.mean), 'all'); ...
        all(fullPrediction.observationVariance > 0, 'all'); ...
        all(fullPrediction.conditionalProcessVariance >= -1e-12, 'all') && ...
            all(fullPrediction.fixedEffectVariance >= -1e-12, 'all'); ...
        fullClosure <= 1e-8; ...
        all(isfinite(separablePrediction.mean), 'all'); ...
        all(separablePrediction.observationVariance > 0, 'all'); ...
        separableClosure <= 1e-8; ...
        fullFit.objective <= separableFit.objective + 1e-2; ...
        maximumImaginary <= cfg.cv.maximumAllowedImaginary];
    implementationChecks = table(repmat(foldID, numel(check), 1), ...
        repmat(targetLabel, numel(check), 1), check, passed, ...
        'VariableNames', {'foldID', 'targetStations', 'check', 'passed'});

    taskTiming = table(foldID, current_worker_id(), nObserved, nTarget, ...
        separableFit.elapsedSeconds, fullFit.elapsedSeconds, ...
        separablePredictionSeconds, fullPredictionSeconds, ...
        toc(foldTimer), 'VariableNames', {'foldID', 'workerID', ...
        'nTrainingSites', 'nTargetSites', 'separableFitSeconds', ...
        'fullFitSeconds', 'separablePredictionSeconds', ...
        'fullPredictionSeconds', 'foldElapsedSeconds'});

    task.metrics = vertcat(metricRows{:});
    task.timeBlockMetrics = vertcat(blockRows{:});
    task.predictions = vertcat(predictionRows{:});
    task.fitDiagnostics = fitDiagnostics;
    task.implementationChecks = implementationChecks;
    task.timing = taskTiming;
    task.fits.full = fullFit;
    task.fits.separable = separableFit;
end

function row = probabilistic_metric_row(method, foldID, site, ...
        distance, metrics)
    row = table(method, foldID, site.subsetIndex, ...
        string(site.stationID), site.gridRow, site.gridColumn, ...
        site.xKm, site.yKm, distance, metrics.nValues, metrics.rmse, ...
        metrics.mae, metrics.centeredUnexplainedEnergy, ...
        metrics.correlation, metrics.nlpd, metrics.crps, ...
        metrics.coverage, metrics.meanIntervalWidth, ...
        metrics.meanPredictiveSd, 'VariableNames', {'method', ...
        'foldID', 'targetSubsetIndex', 'targetStation', 'gridRow', ...
        'gridColumn', 'xKm', 'yKm', 'nearestTrainingDistanceKm', ...
        'nValues', 'rmse', 'mae', 'centeredUnexplainedEnergy', ...
        'correlation', 'nlpd', 'crps', 'coverage95', ...
        'meanIntervalWidth95', 'meanPredictiveSd'});
end

function row = point_metric_row(method, foldID, site, distance, metrics)
    row = table(method, foldID, site.subsetIndex, ...
        string(site.stationID), site.gridRow, site.gridColumn, ...
        site.xKm, site.yKm, distance, metrics.nValues, metrics.rmse, ...
        metrics.mae, metrics.centeredUnexplainedEnergy, ...
        metrics.correlation, NaN, NaN, NaN, NaN, NaN, ...
        'VariableNames', {'method', 'foldID', 'targetSubsetIndex', ...
        'targetStation', 'gridRow', 'gridColumn', 'xKm', 'yKm', ...
        'nearestTrainingDistanceKm', 'nValues', 'rmse', 'mae', ...
        'centeredUnexplainedEnergy', 'correlation', 'nlpd', 'crps', ...
        'coverage95', 'meanIntervalWidth95', 'meanPredictiveSd'});
end

function row = block_metric_row(method, foldID, site, block, metrics)
    row = table(method, foldID, string(site.stationID), block, ...
        metrics.nValues, metrics.rmse, metrics.mae, ...
        metrics.correlation, metrics.nlpd, metrics.crps, ...
        metrics.coverage, metrics.meanIntervalWidth, ...
        metrics.meanPredictiveSd, 'VariableNames', {'method', ...
        'foldID', 'targetStation', 'timeBlock', 'nValues', 'rmse', ...
        'mae', 'correlation', 'nlpd', 'crps', 'coverage95', ...
        'meanIntervalWidth95', 'meanPredictiveSd'});
end

function rows = prediction_rows(method, foldID, site, subset, truth, ...
        prediction, targetColumn, noiseVariance)
    T = numel(truth);
    meanPrediction = prediction.mean(:, targetColumn);
    observationVariance = prediction.observationVariance(:, targetColumn);
    conditionalProcessVariance = ...
        prediction.conditionalProcessVariance(:, targetColumn);
    fixedEffectVariance = prediction.fixedEffectVariance(:, targetColumn);
    latentVariance = prediction.latentVariance(:, targetColumn);
    nuggetVariance = repmat(noiseVariance, T, 1);
    residual = truth - meanPrediction;
    standardizedResidual = residual ./ sqrt(observationVariance);
    closureError = observationVariance - ...
        (conditionalProcessVariance + fixedEffectVariance + nuggetVariance);
    rows = table(repmat(method, T, 1), repmat(foldID, T, 1), ...
        repmat(string(site.stationID), T, 1), ...
        repmat(site.gridRow, T, 1), repmat(site.gridColumn, T, 1), ...
        subset.timeIndex, subset.relativeHours, truth, meanPrediction, ...
        conditionalProcessVariance, fixedEffectVariance, ...
        nuggetVariance, latentVariance, observationVariance, ...
        observationVariance, closureError, residual, ...
        standardizedResidual, 'VariableNames', {'method', 'foldID', ...
        'targetStation', 'gridRow', 'gridColumn', 'timeIndex', ...
        'relativeHours', 'truthUWindMps', 'predictionUWindMps', ...
        'conditionalProcessVariance', 'fixedEffectVariance', ...
        'nuggetVariance', 'latentVariance', 'observationVariance', ...
        'predictiveVariance', 'varianceClosureError', 'residual', ...
        'standardizedResidual'});
end

function rows = mean_only_prediction_rows(foldID, site, subset, truth, ...
        meanPrediction)
    T = numel(truth);
    missing = nan(T, 1);
    residual = truth - meanPrediction;
    rows = table(repmat("mean_only", T, 1), repmat(foldID, T, 1), ...
        repmat(string(site.stationID), T, 1), ...
        repmat(site.gridRow, T, 1), repmat(site.gridColumn, T, 1), ...
        subset.timeIndex, subset.relativeHours, truth, meanPrediction, ...
        missing, missing, missing, missing, missing, missing, missing, ...
        residual, missing, 'VariableNames', {'method', 'foldID', ...
        'targetStation', 'gridRow', 'gridColumn', 'timeIndex', ...
        'relativeHours', 'truthUWindMps', 'predictionUWindMps', ...
        'conditionalProcessVariance', 'fixedEffectVariance', ...
        'nuggetVariance', 'latentVariance', 'observationVariance', ...
        'predictiveVariance', 'varianceClosureError', 'residual', ...
        'standardizedResidual'});
end

function row = fit_diagnostic_row(method, foldID, targetLabel, ...
        nTrainingSites, nTargetSites, fit, cfg)
    row = table(method, foldID, targetLabel, nTrainingSites, ...
        nTargetSites, fit.objective, fit.profileNll, ...
        fit.remlAdjustment, fit.theta.signalVariance, fit.theta.alpha, ...
        fit.theta.beta, fit.theta.epsilon, fit.theta.noiseVariance, ...
        fit.derived.timeScaleHours, ...
        fit.derived.spatialRange10LowFrequencyKm, ...
        fit.derived.spatialRange10HighFrequencyKm, fit.exitFlag, ...
        fit.convergenceCertified, fit.elapsedSeconds, ...
        fit.totalFunctionEvaluations, fit.totalIterations, ...
        fit.boundaryHit, fit.minimumBoundaryDistance, ...
        fit.polishTriggered, fit.polishAccepted, ...
        fit.secondBestObjectiveGap, fit.nearBestStartCount, ...
        fit.details.maximumSpectralJitter, 'VariableNames', ...
        {'method', 'foldID', 'targetStations', 'nTrainingSites', ...
        'nTargetSites', 'objective', 'profileNll', 'remlAdjustment', ...
        'signalVariance', 'alphaPer100Km', 'betaPerSixHours', ...
        'epsilon', 'noiseVariance', 'timeScaleHours', ...
        'lowFrequencyRange10Km', 'highFrequencyRange10Km', ...
        'exitFlag', 'convergenceCertified', 'elapsedSeconds', ...
        'totalFunctionEvaluations', 'totalIterations', 'boundaryHit', ...
        'minimumBoundaryDistance', 'polishTriggered', ...
        'polishAccepted', 'secondBestObjectiveGap', ...
        'nearBestStartCount', 'maximumSpectralJitter'});
end

function errorValue = variance_closure_error(prediction, noiseVariance)
    reconstructed = prediction.conditionalProcessVariance + ...
        prediction.fixedEffectVariance + noiseVariance;
    errorValue = max(abs(prediction.observationVariance - ...
        reconstructed), [], 'all');
end

function id = current_worker_id()
    id = 0;
    try
        currentTask = getCurrentTask();
        if ~isempty(currentTask)
            id = currentTask.ID;
        end
    catch
        id = 0;
    end
end
