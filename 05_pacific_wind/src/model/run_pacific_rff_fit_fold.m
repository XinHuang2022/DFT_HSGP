function output = run_pacific_rff_fit_fold(cfg, subset, pluginTask, ...
        nFeatures)
%RUN_PACIFIC_RFF_FIT_FOLD Gated RFF optimization for one outer fold.

% The first RFF fit fixes sigma_n^2 at the exact subset estimate.  This
% prevents a rank-p approximation from redefining the nugget as the
% variance of the m-p directions that its features cannot represent.

    foldID = pluginTask.timing.foldID;
    observedIndex = pluginTask.observedIndex;
    targetIndex = pluginTask.targetIndex;
    Yobserved = subset.U(:, observedIndex);
    Ytarget = subset.U(:, targetIndex);
    initialFit = pluginTask.fullFit;
    if cfg.rff.fixNuggetAtExactSubsetEstimateDuringFirstFit
        fixedNoise = initialFit.theta.noiseVariance;
    else
        fixedNoise = [];
    end
    nSeed = numel(cfg.rff.fitFeatureSeeds);
    nTarget = numel(targetIndex);
    diagnosticRows = cell(nSeed, 1);
    metricRows = cell(3 * nSeed, 1);
    targetMetricRows = cell(3 * nSeed * nTarget, 1);
    fits = cell(nSeed, 1);
    for s = 1:nSeed
        timerValue = tic;
        featureSeed = cfg.rff.fitFeatureSeeds(s) + 1009 * foldID;
        bank = make_pacific_rff_bank(initialFit.theta, ...
            nFeatures, cfg, featureSeed);
        optimizerSeed = cfg.seed.optimizer + 13007 * foldID + 97 * s;
        rffFit = fit_pacific_eq9_rff(Yobserved, ...
            pluginTask.outerGeometry.xyCovariance, ...
            pluginTask.outerGeometry.design, cfg, bank, ...
            initialFit.theta, [], fixedNoise, cfg.rff.optimizer, ...
            optimizerSeed);
        rffPrediction = predict_pacific_eq9_rff(Yobserved, ...
            pluginTask.outerGeometry.xyCovariance, ...
            pluginTask.targetGeometry.xyCovariance, ...
            pluginTask.outerGeometry.design, ...
            pluginTask.targetGeometry.design, rffFit, cfg, bank);

        % One dense evaluation at the RFF estimate is an audit, not a dense
        % optimization.  It separates parameter error from feature error.
        exactAtRffTheta = pacific_refit_mean_at_theta(Yobserved, ...
            pluginTask.outerGeometry.xyCovariance, ...
            pluginTask.outerGeometry.design, rffFit.theta, cfg);
        exactPredictionAtRffTheta = predict_pacific_eq9(Yobserved, ...
            pluginTask.outerGeometry.xyCovariance, ...
            pluginTask.targetGeometry.xyCovariance, ...
            pluginTask.outerGeometry.design, ...
            pluginTask.targetGeometry.design, exactAtRffTheta, cfg);

        baselineMetrics = eq9_prediction_metrics(Ytarget(:), ...
            pluginTask.fullPrediction.mean(:), ...
            pluginTask.fullPrediction.observationVariance(:), ...
            cfg.cv.nominalCoverage);
        exactThetaMetrics = eq9_prediction_metrics(Ytarget(:), ...
            exactPredictionAtRffTheta.mean(:), ...
            exactPredictionAtRffTheta.observationVariance(:), ...
            cfg.cv.nominalCoverage);
        rffMetrics = eq9_prediction_metrics(Ytarget(:), ...
            rffPrediction.mean(:), ...
            rffPrediction.observationVariance(:), ...
            cfg.cv.nominalCoverage);
        metricRows{3 * (s - 1) + 1} = metric_row( ...
            "exact_subset_baseline", foldID, featureSeed, ...
            nFeatures, baselineMetrics);
        metricRows{3 * (s - 1) + 2} = metric_row( ...
            "rff_theta_exact_prediction", foldID, featureSeed, ...
            nFeatures, exactThetaMetrics);
        metricRows{3 * (s - 1) + 3} = metric_row( ...
            "rff_theta_rff_prediction", foldID, featureSeed, ...
            nFeatures, rffMetrics);
        targetSites = subset.siteTable(targetIndex, :);
        for j = 1:nTarget
            baselineTarget = eq9_prediction_metrics(Ytarget(:, j), ...
                pluginTask.fullPrediction.mean(:, j), ...
                pluginTask.fullPrediction.observationVariance(:, j), ...
                cfg.cv.nominalCoverage);
            exactThetaTarget = eq9_prediction_metrics(Ytarget(:, j), ...
                exactPredictionAtRffTheta.mean(:, j), ...
                exactPredictionAtRffTheta.observationVariance(:, j), ...
                cfg.cv.nominalCoverage);
            rffTarget = eq9_prediction_metrics(Ytarget(:, j), ...
                rffPrediction.mean(:, j), ...
                rffPrediction.observationVariance(:, j), ...
                cfg.cv.nominalCoverage);
            base = 3 * ((s - 1) * nTarget + (j - 1));
            targetMetricRows{base + 1} = target_metric_row( ...
                "exact_subset_baseline", foldID, featureSeed, ...
                nFeatures, targetSites(j, :), baselineTarget);
            targetMetricRows{base + 2} = target_metric_row( ...
                "rff_theta_exact_prediction", foldID, featureSeed, ...
                nFeatures, targetSites(j, :), exactThetaTarget);
            targetMetricRows{base + 3} = target_metric_row( ...
                "rff_theta_rff_prediction", foldID, featureSeed, ...
                nFeatures, targetSites(j, :), rffTarget);
        end
        exactDifference = (exactAtRffTheta.objective - ...
            initialFit.objective) / ...
            (numel(observedIndex) * size(Yobserved, 1));
        valid = rffFit.convergenceCertified && ...
            rffFit.details.minimumEssFraction >= ...
            cfg.rff.minimumEssFraction && ...
            rffPrediction.minimumFeatureReciprocalCondition > ...
            1 / cfg.rff.maximumConditionNumber;
        diagnosticRows{s} = table(foldID, featureSeed, nFeatures, ...
            numel(observedIndex), max(0, numel(observedIndex) - ...
            nFeatures), rffFit.theta.noiseVariance, rffFit.objective, ...
            initialFit.objective, exactAtRffTheta.objective, ...
            exactDifference, rffFit.theta.signalVariance, ...
            rffFit.theta.alpha, rffFit.theta.beta, ...
            rffFit.theta.epsilon, rffFit.theta.noiseVariance, ...
            rffFit.details.minimumEssFraction, ...
            rffFit.details.medianEssFraction, ...
            rffPrediction.minimumFeatureReciprocalCondition, ...
            rffFit.convergenceCertified, valid, ...
            rffFit.elapsedSeconds, toc(timerValue), ...
            'VariableNames', {'foldID', 'featureSeed', 'nFeatures', ...
            'nConditioningSites', ...
            'rankDeficientDirectionsBeforeNugget', ...
            'noiseVarianceDuringRffFit', 'rffObjective', ...
            'initialExactObjective', 'exactObjectiveAtRffTheta', ...
            'exactObjectiveDifferencePerObservation', ...
            'signalVariance', 'alphaPer100Km', 'betaPerSixHours', ...
            'epsilon', 'noiseVariance', 'minimumEssFraction', ...
            'medianEssFraction', 'minimumFeatureReciprocalCondition', ...
            'convergenceCertified', 'fitPassedNumericalGates', ...
            'optimizerElapsedSeconds', 'totalElapsedSeconds'});
        fits{s}.bank = bank;
        fits{s}.rffFit = rffFit;
        fits{s}.exactAtRffTheta = exactAtRffTheta;
        fits{s}.rffPrediction = rffPrediction;
        fits{s}.exactPredictionAtRffTheta = exactPredictionAtRffTheta;
    end
    output.diagnostics = vertcat(diagnosticRows{:});
    output.metrics = vertcat(metricRows{:});
    output.targetMetrics = vertcat(targetMetricRows{:});
    output.fits = fits;
end

function row = metric_row(method, foldID, seed, nFeatures, metrics)
    row = table(method, foldID, seed, nFeatures, metrics.nValues, ...
        metrics.rmse, metrics.mae, metrics.correlation, metrics.nlpd, ...
        metrics.crps, metrics.coverage, metrics.meanIntervalWidth, ...
        'VariableNames', {'method', 'foldID', 'featureSeed', ...
        'nFeatures', 'nValues', 'rmse', 'mae', 'correlation', ...
        'nlpd', 'crps', 'coverage95', 'meanIntervalWidth95'});
end

function row = target_metric_row(method, foldID, seed, nFeatures, ...
        site, metrics)
    row = table(method, foldID, seed, nFeatures, ...
        string(site.stationID), site.gridRow, site.gridColumn, ...
        site.xKm, site.yKm, metrics.nValues, metrics.rmse, metrics.mae, ...
        metrics.correlation, metrics.nlpd, metrics.crps, ...
        metrics.coverage, metrics.meanIntervalWidth, ...
        'VariableNames', {'method', 'foldID', 'featureSeed', ...
        'nFeatures', 'targetStation', 'gridRow', 'gridColumn', ...
        'xKm', 'yKm', 'nValues', 'rmse', 'mae', 'correlation', ...
        'nlpd', 'crps', 'coverage95', 'meanIntervalWidth95'});
end
