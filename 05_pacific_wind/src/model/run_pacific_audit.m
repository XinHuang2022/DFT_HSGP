function result = run_pacific_audit(preset)
%RUN_PACIFIC_AUDIT Validate data and diagnose primitive nonstationarity.

    if nargin < 1 || isempty(preset)
        preset = 'audit';
    end
    cfg = pacific_eq9_config(preset);
    ensure_directory(cfg.paths.outputDir);
    ensure_directory(cfg.paths.figureDir);
    contract = load_pacific_wind_data(cfg);
    U = contract.U;
    [T, nStations] = size(U);
    missingCount = sum(isnan(U), 'all');
    nonfiniteCount = sum(~isfinite(U), 'all');
    implausibleFillCount = sum(abs(U) > ...
        cfg.data.absolutePlausibilityLimitMps, 'all');

    fullDistance = eq9_pairwise_distances(contract.xyKm, contract.xyKm);
    fullDistance(1:(nStations + 1):end) = Inf;
    nearestDistance = min(fullDistance, [], 2);
    medianGridSpacingKm = median(nearestDistance);
    occupancy = accumarray([contract.siteTable.gridRow, ...
        contract.siteTable.gridColumn], 1, [17, 17]);

    checkName = ["wind matrix is 480-by-289"; ...
        "coordinate matrix is 289-by-2"; ...
        "coordinate order identified"; ...
        "17 latitude and longitude levels"; ...
        "complete 17-by-17 coordinate grid"; ...
        "all wind observations finite"; ...
        "no implausible numeric fill codes"; ...
        "nearest-neighbor spacing plausible"];
    passed = [isequal(size(U), [480, 289]); ...
        isequal(size(contract.coordinatesRaw), [289, 2]); ...
        strlength(contract.coordinateOrder) > 0; ...
        numel(contract.latitudeLevels) == 17 && ...
            numel(contract.longitudeLevels) == 17; ...
        all(occupancy == 1, 'all'); nonfiniteCount == 0; ...
        implausibleFillCount == 0; ...
        medianGridSpacingKm > 150 && medianGridSpacingKm < 300];
    details = [string(sprintf('%d-by-%d', size(U, 1), size(U, 2))); ...
        string(sprintf('%d-by-%d', size(contract.coordinatesRaw, 1), ...
            size(contract.coordinatesRaw, 2))); ...
        contract.coordinateOrder; ...
        string(sprintf('%d latitude; %d longitude', ...
            numel(contract.latitudeLevels), ...
            numel(contract.longitudeLevels))); ...
        string(sprintf('occupancy range %d to %d', ...
            min(occupancy, [], 'all'), max(occupancy, [], 'all'))); ...
        string(sprintf('%d missing; %d nonfinite', ...
            missingCount, nonfiniteCount)); ...
        string(sprintf('%d values with |u| > %.1f m/s', ...
            implausibleFillCount, ...
            cfg.data.absolutePlausibilityLimitMps)); ...
        string(sprintf('median %.2f km', medianGridSpacingKm))];
    dataChecks = table(checkName, passed, details);
    writetable(dataChecks, fullfile(cfg.paths.outputDir, ...
        'data_contract_checks.csv'));

    siteSummary = make_site_summary(contract);
    timeSummary = make_time_summary(contract);
    [blockSummary, blockSiteSummary] = make_block_summaries(contract, ...
        cfg.cv.timeBlocks);
    writetable(siteSummary, fullfile(cfg.paths.outputDir, ...
        'site_summary.csv'));
    writetable(timeSummary, fullfile(cfg.paths.outputDir, ...
        'time_summary.csv'));
    writetable(blockSummary, fullfile(cfg.paths.outputDir, ...
        'time_block_summary.csv'));
    writetable(blockSiteSummary, fullfile(cfg.paths.outputDir, ...
        'site_by_time_block_summary.csv'));

    subsetNames = ["local3"; "local5"; "local6"; "sparse3"];
    manifests = cell(numel(subsetNames), 1);
    for j = 1:numel(subsetNames)
        part = make_pacific_subset(contract, subsetNames(j));
        manifests{j} = part.siteTable;
    end
    subsetManifest = vertcat(manifests{:});
    writetable(subsetManifest, fullfile(cfg.paths.outputDir, ...
        'subset_manifest.csv'));

    finiteDistances = fullDistance(isfinite(fullDistance));
    distanceProbability = [0; 0.1; 0.25; 0.5; 0.75; 0.9; 1];
    distanceSummary = table(distanceProbability, ...
        local_quantile(finiteDistances, distanceProbability), ...
        'VariableNames', {'probability', 'pairwiseDistanceKm'});
    writetable(distanceSummary, fullfile(cfg.paths.outputDir, ...
        'pairwise_distance_summary.csv'));

    acf = average_site_acf(U, cfg.audit.maximumAcfLag);
    acfTable = table((0:cfg.audit.maximumAcfLag)', ...
        cfg.data.samplingHours * (0:cfg.audit.maximumAcfLag)', acf, ...
        'VariableNames', {'lagSteps', 'lagHours', 'averageSiteAcf'});
    writetable(acfTable, fullfile(cfg.paths.outputDir, ...
        'average_site_acf.csv'));

    make_pacific_audit_figures(contract, siteSummary, timeSummary, ...
        blockSiteSummary, acfTable, cfg);

    runSummary = table(string(cfg.version), string(cfg.preset), T, ...
        nStations, missingCount, nonfiniteCount, implausibleFillCount, ...
        medianGridSpacingKm, ...
        all(passed), 'VariableNames', {'version', 'preset', ...
        'nTimePoints', 'nStations', 'missingCount', 'nonfiniteCount', ...
        'implausibleFillCount', ...
        'medianNearestNeighborKm', 'allDataContractChecksPassed'});
    writetable(runSummary, fullfile(cfg.paths.outputDir, ...
        'audit_run_summary.csv'));

    fprintf('\nPacific wind audit complete.\n');
    fprintf('  Wind matrix: %d time points by %d stations.\n', T, nStations);
    fprintf('  Missing/nonfinite values: %d/%d.\n', ...
        missingCount, nonfiniteCount);
    fprintf('  Possible numeric fill codes: %d.\n', ...
        implausibleFillCount);
    fprintf('  Median nearest-neighbor distance: %.2f km.\n', ...
        medianGridSpacingKm);
    fprintf('  All contract checks passed: %d.\n', all(passed));
    fprintf('  Results: %s\n\n', cfg.paths.outputDir);

    result.cfg = cfg;
    result.contract = contract;
    result.dataChecks = dataChecks;
    result.siteSummary = siteSummary;
    result.timeSummary = timeSummary;
    result.blockSummary = blockSummary;
    result.blockSiteSummary = blockSiteSummary;
    result.subsetManifest = subsetManifest;
    result.acf = acfTable;
end

function summary = make_site_summary(contract)
    U = contract.U;
    sites = contract.siteTable;
    n = size(U, 2);
    siteMean = mean(U, 1, 'omitnan').';
    siteSd = std(U, 0, 1, 'omitnan').';
    siteMin = min(U, [], 1, 'omitnan').';
    siteMax = max(U, [], 1, 'omitnan').';
    missingCount = sum(~isfinite(U), 1).';
    siteSkewness = nan(n, 1);
    siteExcessKurtosis = nan(n, 1);
    for j = 1:n
        [siteSkewness(j), siteExcessKurtosis(j)] = ...
            moment_shape(U(:, j));
    end
    summary = [sites, table(siteMean, siteSd, siteMin, siteMax, ...
        missingCount, siteSkewness, siteExcessKurtosis)];
end

function summary = make_time_summary(contract)
    U = contract.U;
    crossSectionMean = mean(U, 2, 'omitnan');
    crossSectionSd = std(U, 0, 2, 'omitnan');
    crossSectionMin = min(U, [], 2, 'omitnan');
    crossSectionMax = max(U, [], 2, 'omitnan');
    activeStations = sum(isfinite(U), 2);
    summary = table(contract.timeIndex, contract.relativeHours, ...
        crossSectionMean, crossSectionSd, crossSectionMin, ...
        crossSectionMax, activeStations, 'VariableNames', ...
        {'timeIndex', 'relativeHours', 'crossSectionMean', ...
        'crossSectionSd', 'crossSectionMin', 'crossSectionMax', ...
        'activeStations'});
end

function [blockSummary, blockSiteSummary] = make_block_summaries( ...
        contract, nBlocks)
    U = contract.U;
    T = size(U, 1);
    blockID = min(nBlocks, ceil((1:T)' * nBlocks / T));
    blockRows = cell(nBlocks, 1);
    siteRows = cell(nBlocks, 1);
    for b = 1:nBlocks
        use = blockID == b;
        values = U(use, :);
        blockRows{b} = table(b, sum(use), min(contract.timeIndex(use)), ...
            max(contract.timeIndex(use)), mean(values, 'all', 'omitnan'), ...
            std(values, 0, 'all', 'omitnan'), ...
            mean(std(values, 0, 1, 'omitnan')), ...
            std(mean(values, 1, 'omitnan'), 0), ...
            'VariableNames', {'timeBlock', 'nTimePoints', ...
            'firstTimeIndex', 'lastTimeIndex', 'overallMean', ...
            'overallSd', 'meanWithinSiteSd', 'sdOfSiteMeans'});
        block = repmat(b, height(contract.siteTable), 1);
        siteRows{b} = [table(block), contract.siteTable, ...
            table(mean(values, 1, 'omitnan').', ...
            std(values, 0, 1, 'omitnan').', ...
            'VariableNames', {'blockSiteMean', 'blockSiteSd'})];
    end
    blockSummary = vertcat(blockRows{:});
    blockSiteSummary = vertcat(siteRows{:});
end

function [skewnessValue, excessKurtosis] = moment_shape(x)
    x = x(isfinite(x));
    if isempty(x)
        skewnessValue = NaN;
        excessKurtosis = NaN;
        return;
    end
    centered = x - mean(x);
    second = mean(centered .^ 2);
    if second <= 0
        skewnessValue = 0;
        excessKurtosis = -3;
        return;
    end
    skewnessValue = mean(centered .^ 3) / second ^ 1.5;
    excessKurtosis = mean(centered .^ 4) / second ^ 2 - 3;
end

function acf = average_site_acf(U, maximumLag)
    acf = nan(maximumLag + 1, 1);
    centered = U - mean(U, 1, 'omitnan');
    for lag = 0:maximumLag
        left = centered(1:(end - lag), :);
        right = centered((1 + lag):end, :);
        numerator = sum(left .* right, 1, 'omitnan');
        denominator = sqrt(sum(left .^ 2, 1, 'omitnan') .* ...
            sum(right .^ 2, 1, 'omitnan'));
        correlations = numerator ./ denominator;
        acf(lag + 1) = mean(correlations(isfinite(correlations)));
    end
end

function q = local_quantile(x, probability)
    x = sort(x(isfinite(x)));
    probability = probability(:);
    if isempty(x)
        q = nan(size(probability));
        return;
    end
    position = 1 + (numel(x) - 1) * probability;
    lo = floor(position);
    hi = ceil(position);
    weight = position - lo;
    q = (1 - weight) .* x(lo) + weight .* x(hi);
end
