function task = run_pacific_nugget_fold(cfg, subset, targetIndex, foldID)
%RUN_PACIFIC_NUGGET_FOLD Nested training-only nugget study for one fold.

% Outer targets are removed before both parameter-subset selection and the
% inner validation split.  Candidate nuggets are compared by validation
% NLPD, a proper scoring rule.  Outer-target metrics are computed only after
% the candidate has been selected.

    timerValue = tic;
    nSites = size(subset.U, 2);
    targetIndex = unique(targetIndex(:), 'stable');
    observedIndex = setdiff((1:nSites)', targetIndex, 'stable');
    subsetSeed = cfg.scalable.subsetSeed + 1009 * foldID;
    selection = make_pacific_parameter_subset(subset.siteTable, ...
        observedIndex, min(cfg.scalable.parameterSubsetSize, ...
        numel(observedIndex)), cfg.scalable.localPairFraction, subsetSeed);
    split = make_pacific_inner_split(subset.siteTable, selection.index, ...
        cfg.nugget.innerValidationFoldCount, ...
        cfg.nugget.innerValidationFold, subsetSeed + 17);

    innerFitIndex = split.fitIndex;
    innerValidationIndex = split.validationIndex;
    [innerFitGeometry, innerValidationGeometry] = fold_geometry( ...
        subset.xyKm(innerFitIndex, :), ...
        subset.xyKm(innerValidationIndex, :), cfg);
    YinnerFit = subset.U(:, innerFitIndex);
    YinnerValidation = subset.U(:, innerValidationIndex);
    [varianceReference, ~, ~] = pacific_empirical_residual_variance( ...
        YinnerFit, subset.xyKm(innerFitIndex, :));
    seed = cfg.seed.optimizer + 10007 * foldID;

    freeFit = fit_pacific_eq9_model(YinnerFit, ...
        innerFitGeometry.xyCovariance, innerFitGeometry.design, cfg, ...
        [], cfg.nugget.optimizer, seed, [], []);
    freePrediction = predict_pacific_eq9(YinnerFit, ...
        innerFitGeometry.xyCovariance, ...
        innerValidationGeometry.xyCovariance, ...
        innerFitGeometry.design, innerValidationGeometry.design, ...
        freeFit, cfg);
    freeMetrics = eq9_prediction_metrics(YinnerValidation(:), ...
        freePrediction.mean(:), freePrediction.observationVariance(:), ...
        cfg.cv.nominalCoverage);

    fractions = cfg.nugget.residualVarianceFractions(:);
    nCandidate = numel(fractions) + 1;
    profileRows = cell(nCandidate, 1);
    fits = cell(nCandidate, 1);
    fits{1} = freeFit;
    profileRows{1} = candidate_row(foldID, "free_current", NaN, ...
        varianceReference, cfg.bounds.noiseVariance(1), ...
        freeFit.theta.noiseVariance, ...
        freeFit.objective, freeFit.objective, freeFit, freeMetrics);

    prepared = prepare_pacific_whittle_data(YinnerFit, ...
        innerFitGeometry.xyCovariance, innerFitGeometry.design);
    for j = 1:numel(fractions)
        rho = fractions(j);
        noiseFloor = max(cfg.bounds.noiseVariance(1), ...
            rho * varianceReference);
        conditionalTheta = freeFit.theta;
        conditionalTheta.noiseVariance = noiseFloor;
        conditionalNll = pacific_profiled_whittle_theta( ...
            conditionalTheta, prepared, cfg);
        candidateCfg = cfg;
        candidateCfg.bounds.noiseVariance(1) = noiseFloor;
        candidateStart = freeFit.theta;
        candidateStart.noiseVariance = max( ...
            candidateStart.noiseVariance, noiseFloor * (1 + 1e-6));
        candidateStart.noiseVariance = min( ...
            candidateStart.noiseVariance, ...
            candidateCfg.bounds.noiseVariance(2) * (1 - 1e-6));
        candidateFit = fit_pacific_eq9_model(YinnerFit, ...
            innerFitGeometry.xyCovariance, innerFitGeometry.design, ...
            candidateCfg, [], cfg.nugget.optimizer, seed + 31 * j, ...
            [], candidateStart);
        prediction = predict_pacific_eq9(YinnerFit, ...
            innerFitGeometry.xyCovariance, ...
            innerValidationGeometry.xyCovariance, ...
            innerFitGeometry.design, innerValidationGeometry.design, ...
            candidateFit, cfg);
        metrics = eq9_prediction_metrics(YinnerValidation(:), ...
            prediction.mean(:), prediction.observationVariance(:), ...
            cfg.cv.nominalCoverage);
        label = string(sprintf('floor_rho_%0.0e', rho));
        fits{j + 1} = candidateFit;
        profileRows{j + 1} = candidate_row(foldID, label, rho, ...
            varianceReference, noiseFloor, ...
            candidateFit.theta.noiseVariance, conditionalNll, ...
            candidateFit.objective, candidateFit, metrics);
    end
    profile = vertcat(profileRows{:});
    [~, selectedCandidate] = min(profile.validationNlpd);
    selectedLabel = profile.candidate(selectedCandidate);
    selectedRho = profile.residualVarianceFraction(selectedCandidate);
    selectedInnerFit = fits{selectedCandidate};

    % Refit covariance on every parameter-subset site using the selected
    % rule, then profile the mean once on every outer-training site.
    parameterIndex = selection.index;
    [outerGeometry, targetGeometry] = fold_geometry( ...
        subset.xyKm(observedIndex, :), subset.xyKm(targetIndex, :), cfg);
    [present, parameterPosition] = ismember(parameterIndex, observedIndex);
    if ~all(present)
        error('A parameter-subset site is absent from outer training.');
    end
    parameterGeometry.xyCovariance = ...
        outerGeometry.xyCovariance(parameterPosition, :);
    parameterGeometry.xyMean = outerGeometry.xyMean(parameterPosition, :);
    parameterGeometry.design = make_pacific_mean_design( ...
        size(subset.U, 1), parameterGeometry.xyMean);
    Yparameter = subset.U(:, parameterIndex);
    [fullVarianceReference, ~, ~] = ...
        pacific_empirical_residual_variance(Yparameter, ...
        subset.xyKm(parameterIndex, :));
    parameterCfg = cfg;
    parameterStart = selectedInnerFit.theta;
    if ~isnan(selectedRho)
        selectedFloor = max(cfg.bounds.noiseVariance(1), ...
            selectedRho * fullVarianceReference);
        parameterCfg.bounds.noiseVariance(1) = selectedFloor;
        parameterStart.noiseVariance = max( ...
            parameterStart.noiseVariance, selectedFloor * (1 + 1e-6));
    end
    parameterFit = fit_pacific_eq9_model(Yparameter, ...
        parameterGeometry.xyCovariance, parameterGeometry.design, ...
        parameterCfg, [], cfg.nugget.optimizer, seed + 7001, [], ...
        parameterStart);
    Yobserved = subset.U(:, observedIndex);
    pluginFit = pacific_refit_mean_at_theta(Yobserved, ...
        outerGeometry.xyCovariance, outerGeometry.design, ...
        parameterFit.theta, cfg);
    outerPrediction = predict_pacific_eq9(Yobserved, ...
        outerGeometry.xyCovariance, targetGeometry.xyCovariance, ...
        outerGeometry.design, targetGeometry.design, pluginFit, cfg);
    Ytarget = subset.U(:, targetIndex);
    outerMetrics = eq9_prediction_metrics(Ytarget(:), ...
        outerPrediction.mean(:), outerPrediction.observationVariance(:), ...
        cfg.cv.nominalCoverage);
    outerMetricTable = table(foldID, selectedLabel, selectedRho, ...
        numel(observedIndex), numel(parameterIndex), numel(targetIndex), ...
        outerMetrics.rmse, outerMetrics.mae, outerMetrics.nlpd, ...
        outerMetrics.crps, outerMetrics.coverage, ...
        outerMetrics.meanIntervalWidth, ...
        'VariableNames', {'foldID', 'selectedCandidate', ...
        'selectedResidualVarianceFraction', 'nOuterTrainingSites', ...
        'nParameterSites', 'nOuterTargetSites', 'outerRmse', ...
        'outerMae', 'outerNlpd', 'outerCrps', 'outerCoverage95', ...
        'outerMeanIntervalWidth95'});

    selectionTable = selection.table;
    selectionTable.foldID = repmat(foldID, height(selectionTable), 1);
    splitTable = split.table;
    splitTable.foldID = repmat(foldID, height(splitTable), 1);
    selectionRow = table(foldID, selectedLabel, selectedRho, ...
        varianceReference, fullVarianceReference, ...
        parameterFit.theta.noiseVariance, ...
        parameterFit.theta.noiseVariance / ...
        (parameterFit.theta.signalVariance + ...
        parameterFit.theta.noiseVariance), ...
        'VariableNames', {'foldID', 'selectedCandidate', ...
        'selectedResidualVarianceFraction', ...
        'innerResidualVarianceReference', ...
        'parameterSubsetResidualVarianceReference', ...
        'finalNoiseVariance', 'finalModelNuggetFraction'});
    timing = table(foldID, toc(timerValue), nCandidate, ...
        numel(innerFitIndex), numel(innerValidationIndex), ...
        numel(parameterIndex), numel(observedIndex), ...
        'VariableNames', {'foldID', 'elapsedSeconds', 'nCandidates', ...
        'nInnerFitSites', 'nInnerValidationSites', ...
        'nParameterSites', 'nOuterTrainingSites'});

    task.profile = profile;
    task.selection = selectionRow;
    task.outerMetrics = outerMetricTable;
    task.parameterManifest = selectionTable;
    task.innerManifest = splitTable;
    task.timing = timing;
    task.parameterFit = parameterFit;
    task.pluginFit = pluginFit;
    task.outerPrediction = outerPrediction;
    task.observedIndex = observedIndex;
    task.targetIndex = targetIndex;
end

function row = candidate_row(foldID, label, rho, varianceReference, ...
        noiseFloor, fittedNoiseVariance, conditionalNll, profiledNll, ...
        fit, metrics)
    actualFraction = fittedNoiseVariance / ...
        (fit.theta.signalVariance + fittedNoiseVariance);
    floorActive = fittedNoiseVariance <= noiseFloor * (1 + 1e-4);
    row = table(foldID, label, rho, varianceReference, ...
        noiseFloor, fittedNoiseVariance, floorActive, actualFraction, ...
        conditionalNll, profiledNll, ...
        fit.theta.signalVariance, fit.theta.alpha, fit.theta.beta, ...
        fit.theta.epsilon, fit.convergenceCertified, fit.elapsedSeconds, ...
        metrics.rmse, metrics.mae, metrics.nlpd, metrics.crps, ...
        metrics.coverage, metrics.meanIntervalWidth, ...
        'VariableNames', {'foldID', 'candidate', ...
        'residualVarianceFraction', 'residualVarianceReference', ...
        'noiseVarianceFloor', 'fittedNoiseVariance', 'floorActive', ...
        'modelNuggetFraction', 'conditionalNll', 'profiledNll', ...
        'signalVariance', 'alphaPer100Km', ...
        'betaPerSixHours', 'epsilon', 'convergenceCertified', ...
        'fitElapsedSeconds', 'validationRmse', 'validationMae', ...
        'validationNlpd', 'validationCrps', 'validationCoverage95', ...
        'validationMeanIntervalWidth95'});
end

function [observed, target] = fold_geometry(xyObservedKm, xyTargetKm, cfg)
    center = mean(xyObservedKm, 1);
    scale = std(xyObservedKm, 0, 1);
    scale(scale <= sqrt(eps)) = 1;
    observed.xyMean = (xyObservedKm - center) ./ scale;
    target.xyMean = (xyTargetKm - center) ./ scale;
    observed.xyCovariance = (xyObservedKm - center) ./ ...
        cfg.spatial.coordinateScaleKm;
    target.xyCovariance = (xyTargetKm - center) ./ ...
        cfg.spatial.coordinateScaleKm;
    T = cfg.data.expectedTimePoints;
    observed.design = make_pacific_mean_design(T, observed.xyMean);
    target.design = make_pacific_mean_design(T, target.xyMean);
end
