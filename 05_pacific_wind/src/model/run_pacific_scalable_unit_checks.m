function checks = run_pacific_scalable_unit_checks(preset)
%RUN_PACIFIC_SCALABLE_UNIT_CHECKS Algebraic checks for nugget/RFF stages.

    if nargin < 1 || isempty(preset)
        preset = 'local7_cv5';
    end
    cfg = pacific_scalable_config(preset);
    outputDir = fullfile(cfg.paths.resultsRoot, ...
        [char(cfg.preset), '_scalable_unit_checks']);
    ensure_directory(outputDir);

    theta.signalVariance = 0.72;
    theta.alpha = 0.108;
    theta.beta = 0.86;
    theta.epsilon = 0.23;
    theta.noiseVariance = 0.018;
    theta.nu = cfg.model.nu;
    transformError = constrained_transform_error(theta, cfg);

    eta = theta.nu - cfg.model.dimension / 2;
    radius = logspace(-7, 5, 40000).';
    density = pacific_matern_spectral_density( ...
        [radius, zeros(size(radius))], 0.7, eta);
    densityIntegral = trapz(radius, 2 * pi * radius .* density);
    densityIntegralError = abs(densityIntegral - 1);

    xy = [-2, -1; -1, 0.5; 0, 0; 0.7, -0.4; 1.5, 1.2; 2, -1];
    lambda = [0, pi / 3, pi];
    bank = make_pacific_rff_bank(theta, 8192, cfg, 47291);
    Phi = pacific_rff_features(xy, bank);
    [weights, weightDetails] = pacific_rff_weights( ...
        theta, lambda, bank, cfg);
    exact = eq9_frequency_covariances(theta, xy, lambda, cfg, false);
    covarianceError = zeros(numel(lambda), 1);
    minimumEigenvalue = Inf;
    maximumImaginary = 0;
    for k = 1:numel(lambda)
        approximate = pacific_rff_covariance( ...
            Phi, Phi, weights(:, k), 0, true);
        covarianceError(k) = norm(approximate - exact(:, :, k), 'fro') / ...
            norm(exact(:, :, k), 'fro');
        minimumEigenvalue = min(minimumEigenvalue, ...
            min(real(eig((approximate + approximate') / 2))));
        rawComplex = Phi * (weights(:, k) .* Phi');
        maximumImaginary = max(maximumImaginary, ...
            max(abs(imag(rawComplex)), [], 'all'));
    end
    maximumCovarianceError = max(covarianceError);

    smallBank = make_pacific_rff_bank(theta, 8, cfg, 17311);
    smallPhi = pacific_rff_features(xy, smallBank);
    smallWeight = pacific_rff_weights(theta, 0.4, smallBank, cfg);
    noise = 0.17;
    dense = smallPhi * (smallWeight .* smallPhi') + ...
        noise * eye(size(smallPhi, 1));
    dense = (dense + dense') / 2;
    rightHandSide = reshape(sin(1:(2 * size(xy, 1))), ...
        size(xy, 1), 2);
    factor = pacific_rff_factor(smallPhi, smallWeight, noise);
    woodburySolution = pacific_rff_solve(factor, rightHandSide);
    denseSolution = dense \ rightHandSide;
    woodburySolveError = norm(woodburySolution - denseSolution, 'fro') / ...
        norm(denseSolution, 'fro');
    Ldense = chol(dense, 'lower');
    denseLogDeterminant = 2 * sum(log(real(diag(Ldense))));
    woodburyLogDeterminantError = abs( ...
        factor.logDeterminant - denseLogDeterminant);

    [columnGrid, rowGrid] = meshgrid(1:17, 1:17);
    nSite = numel(rowGrid);
    siteTable = table((1:nSite)', "G" + string((1:nSite)'), ...
        rowGrid(:), columnGrid(:), 100 * columnGrid(:), ...
        100 * rowGrid(:), 'VariableNames', {'subsetIndex', ...
        'stationID', 'gridRow', 'gridColumn', 'xKm', 'yKm'});
    targets = find(mod(rowGrid(:) + 2 * columnGrid(:), 5) == 0);
    candidates = setdiff((1:nSite)', targets, 'stable');
    selection = make_pacific_parameter_subset( ...
        siteTable, candidates, 49, 0.25, 51917);
    subsetLeakCount = numel(intersect(selection.index, targets));
    subsetDuplicateCount = 49 - numel(unique(selection.index));
    localPairCount = sum(selection.table.selectionRole == "local_pair");

    check = ["constrained transforms round trip"; ...
        "normalized Matern spectral density integrates to one"; ...
        "paired RFF covariance approximates exact latent covariance"; ...
        "paired RFF covariance is positive semidefinite"; ...
        "paired RFF covariance is real"; ...
        "RFF importance weights have adequate ESS"; ...
        "Woodbury solve equals dense solve"; ...
        "matrix-determinant lemma equals dense log determinant"; ...
        "parameter subset excludes outer targets"; ...
        "parameter subset contains no duplicate sites"; ...
        "parameter subset contains short-distance pairs"];
    value = [transformError; densityIntegralError; ...
        maximumCovarianceError; minimumEigenvalue; maximumImaginary; ...
        weightDetails.minimumEssFraction; woodburySolveError; ...
        woodburyLogDeterminantError; subsetLeakCount; ...
        subsetDuplicateCount; localPairCount];
    tolerance = [1e-9; 3e-4; 0.12; -1e-9; 1e-10; ...
        cfg.rff.minimumEssFraction; 1e-10; 1e-10; 0; 0; 1];
    passed = [transformError < tolerance(1); ...
        densityIntegralError < tolerance(2); ...
        maximumCovarianceError < tolerance(3); ...
        minimumEigenvalue > tolerance(4); ...
        maximumImaginary < tolerance(5); ...
        weightDetails.minimumEssFraction >= tolerance(6); ...
        woodburySolveError < tolerance(7); ...
        woodburyLogDeterminantError < tolerance(8); ...
        subsetLeakCount == tolerance(9); ...
        subsetDuplicateCount == tolerance(10); ...
        localPairCount >= tolerance(11)];
    checks = table(check, passed, value, tolerance);
    writetable(checks, fullfile(outputDir, ...
        'scalable_unit_checks.csv'));
    if ~all(passed)
        error('One or more Pacific scalable unit checks failed.');
    end
    fprintf('All %d Pacific scalable unit checks passed.\n', ...
        height(checks));
end

function errorValue = constrained_transform_error(theta, cfg)
    constraints = {[], []; 1, []; [], theta.noiseVariance; ...
        1, theta.noiseVariance};
    errorValue = 0;
    for j = 1:size(constraints, 1)
        fixedEpsilon = constraints{j, 1};
        fixedNoise = constraints{j, 2};
        z = pacific_pack_constrained_parameters(theta, cfg, ...
            fixedEpsilon, fixedNoise);
        recovered = pacific_unpack_constrained_parameters(z, cfg, ...
            fixedEpsilon, fixedNoise);
        expectedEpsilon = theta.epsilon;
        if ~isempty(fixedEpsilon)
            expectedEpsilon = fixedEpsilon;
        end
        expectedNoise = theta.noiseVariance;
        if ~isempty(fixedNoise)
            expectedNoise = fixedNoise;
        end
        errorValue = max(errorValue, max(abs([ ...
            recovered.signalVariance - theta.signalVariance, ...
            recovered.alpha - theta.alpha, ...
            recovered.beta - theta.beta, ...
            recovered.epsilon - expectedEpsilon, ...
            recovered.noiseVariance - expectedNoise])));
    end
end
