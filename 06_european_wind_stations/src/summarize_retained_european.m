function result = summarize_retained_european(experimentRoot)
%SUMMARIZE_RETAINED_EUROPEAN Read preserved five-fold summaries.

    retainedRoot = fullfile(experimentRoot, 'input', 'retained');
    result.fivefoldSummary = readtable(fullfile(retainedRoot, ...
        'fivefold_bootstrap_summary.csv'), 'VariableNamingRule', 'preserve');
    result.pairedDifferences = readtable(fullfile(retainedRoot, ...
        'fivefold_paired_differences.csv'), 'VariableNamingRule', 'preserve');
    result.algorithmComparison = readtable(fullfile(retainedRoot, ...
        'exact_kl_solve_trace_fold_summary.csv'), ...
        'VariableNamingRule', 'preserve');
    result.relaxedSummary = readtable(fullfile(retainedRoot, ...
        'relaxed_cycle_sensitivity', 'relaxed_fivefold_summary.csv'), ...
        'VariableNamingRule', 'preserve');
end
