function validation=validate_solve_trace_fold(foldID)
%VALIDATE_SOLVE_TRACE_FOLD Compare Algorithm 2 ranks with exact KL values.

    if nargin<1, foldID=1; end
    C=ghcnh_trace_config(); [cfg,subset,folds,A,E]=ghcnh_expanded_setup();
    methodDir=fullfile(E.resultsDir,sprintf('fold_%02d',foldID),'solve_trace');
    completeFile=fullfile(methodDir,'complete_task.mat');
    if ~isfile(completeFile), error('Completed solve-trace fold is absent.'); end
    S=load(completeFile,'task'); task=S.task;
    if ~task.rankStable, error('Solve-trace fold is not rank stable.'); end

    targetIndex=folds(foldID).targetIndex(:);
    observedIndex=setdiff((1:size(subset.U,2))',targetIndex,'stable');
    allCenter=mean(subset.xyKm,1);
    domainXy=(subset.xyKm-allCenter)/cfg.spatial.coordinateScaleKm;
    observedXy=domainXy(observedIndex,:);
    master=adaptive_basis_bank(domainXy,cfg.hsgp.boundaryFactor, ...
        C.referenceJ,A,cfg);
    logFile=fullfile(methodDir,'validation.log');
    [exactJ,exactAudit,exactSummary]=exact_rank_audit(task.fit.theta, ...
        observedXy,cfg,master,C,A,logFile, ...
        sprintf('solve_trace_fold%d_validation',foldID));

    solveJ=task.rankProfile.selectedJ;
    finalCycle=height(task.history);
    requiredFile=fullfile(methodDir,sprintf('cycle_%d_rank_profile.csv', ...
        finalCycle));
    required=readtable(requiredFile);
    solveRequiredJ=required.selectedJ;
    K=numel(solveJ); exactAtFinal=zeros(K,1);
    for k=1:K
        if solveJ(k)==C.referenceJ
            exactAtFinal(k)=0;
        else
            row=exactAudit.frequencyIndex==k-1 & ...
                exactAudit.candidateJ==solveJ(k);
            if nnz(row)~=1
                error('Exact audit row missing for k=%d, J=%d.',k-1,solveJ(k));
            end
            exactAtFinal(k)=exactAudit.exactKlPerSite(row);
        end
    end
    validation=table((0:K-1)',solveJ,solveRequiredJ,exactJ,exactAtFinal, ...
        solveJ>=solveRequiredJ,solveRequiredJ>=exactJ, ...
        exactAtFinal<=C.epsilonKlPerSite+1e-10, ...
        'VariableNames',{'frequencyIndex','finalSolveJ', ...
        'finalSolveRequiredJ','exactRequiredJ','exactKlAtFinalSolveRank', ...
        'monotoneCorrectionValid','certificateDominatesExactRank', ...
        'exactToleranceSatisfied'});
    writetable(validation,fullfile(methodDir,'exact_validation.csv'));
    writetable(exactAudit,fullfile(methodDir,'final_parameter_exact_audit.csv'));
    writetable(exactSummary, ...
        fullfile(methodDir,'final_parameter_exact_audit_summary.csv'));
    summary=table(foldID,K,max(exactAtFinal), ...
        sum(solveJ==exactJ),sum(solveJ>exactJ),sum(solveJ<exactJ), ...
        all(validation.monotoneCorrectionValid), ...
        all(validation.certificateDominatesExactRank), ...
        all(validation.exactToleranceSatisfied), ...
        'VariableNames',{'foldID','nFrequencies','maximumExactKlAtFinalRank', ...
        'sameRankFrequencies','conservativeRankFrequencies', ...
        'invalidLowerRankFrequencies','monotoneCorrectionValid', ...
        'certificateDominatesExactRank','exactToleranceSatisfied'});
    writetable(summary,fullfile(methodDir,'validation_summary.csv'));
    save(fullfile(methodDir,'validation.mat'),'validation','summary', ...
        'exactAudit','exactSummary','-v7.3');
end
