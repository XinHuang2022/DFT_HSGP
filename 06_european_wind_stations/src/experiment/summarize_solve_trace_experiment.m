function summary=summarize_solve_trace_experiment()
%SUMMARIZE_SOLVE_TRACE_EXPERIMENT Collect five-fold method diagnostics.

    [~,~,~,~,E]=ghcnh_expanded_setup();
    methods=["exact_kl","solve_trace"];
    rows=cell(10,1); cursor=0;
    for method=methods
        for foldID=1:5
            folder=fullfile(E.resultsDir,sprintf('fold_%02d',foldID), ...
                char(method));
            metrics=readtable(fullfile(folder,'metrics.csv'), ...
                'TextType','string');
            timing=readtable(fullfile(folder,'timing.csv'));
            parameters=readtable(fullfile(folder,'parameters.csv'));
            profile=readtable(fullfile(folder,'rank_profile.csv'));
            history=readtable(fullfile(folder,'iterations.csv'));
            cursor=cursor+1;
            rows{cursor}=table(method,foldID,metrics.rmse(1),metrics.mae(1), ...
                metrics.nlpd(1),metrics.coverage95(1), ...
                metrics.meanSiteCorrelation(1),height(history), ...
                mean(profile.selectedM),median(profile.selectedM), ...
                max(profile.selectedM),sum(profile.selectedJ==48), ...
                timing.totalAuditSeconds(1),timing.adaptiveFitSeconds(1), ...
                timing.equivalentFirstUseSeconds(1),parameters.objective(1), ...
                parameters.noiseVariance(1),parameters.exitFlag(1), ...
                parameters.convergenceCertified(1),parameters.boundaryHit(1), ...
                'VariableNames',{'method','foldID','rmse','mae','nlpd', ...
                'coverage95','meanSiteCorrelation','cycles','meanM', ...
                'medianM','maximumM','referenceRankFrequencies', ...
                'auditSeconds','adaptiveFitSeconds','firstUseSeconds', ...
                'objective','noiseVariance','exitFlag', ...
                'convergenceCertified','boundaryHit'});
        end
    end
    summary=vertcat(rows{:});
    writetable(summary,fullfile(E.resultsDir, ...
        'exact_kl_solve_trace_fold_summary.csv'));
    bootstrap=bootstrap_ghcnh_expanded_cv(methods);
    writetable(bootstrap,fullfile(E.resultsDir, ...
        'exact_kl_solve_trace_bootstrap_summary.csv'));

    validationRows=cell(5,1);
    for foldID=1:5
        validationFile=fullfile(E.resultsDir,sprintf('fold_%02d',foldID), ...
            'solve_trace','validation_summary.csv');
        if ~isfile(validationFile)
            error('Missing solve-aware exact-validation summary for fold %d.', ...
                foldID);
        end
        validationRows{foldID}=readtable(validationFile);
    end
    validationSummary=vertcat(validationRows{:});
    writetable(validationSummary,fullfile(E.resultsDir, ...
        'solve_trace_exact_validation_summary.csv'));
end
