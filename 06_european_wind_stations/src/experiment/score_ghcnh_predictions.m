function [summary,siteMetrics,predictions]=score_ghcnh_predictions( ...
        truth,prediction,subset,targetIndex,foldID,cfg,method)
%SCORE_GHCNH_PREDICTIONS Harmonized held-site metrics and predictions.

    nTarget=numel(targetIndex); rows=cell(nTarget,1); pred=cell(nTarget,1);
    for j=1:nTarget
        value=eq9_prediction_metrics(truth(:,j),prediction.mean(:,j), ...
            prediction.observationVariance(:,j),cfg.cv.nominalCoverage);
        rows{j}=table(string(method),foldID, ...
            string(subset.siteTable.stationID(targetIndex(j))), ...
            value.rmse,value.mae,value.correlation,value.nlpd,value.crps, ...
            value.coverage,value.meanIntervalWidth,'VariableNames', ...
            {'method','foldID','stationID','rmse','mae','correlation', ...
            'nlpd','crps','coverage95','meanIntervalWidth95'});
        T=size(truth,1);
        pred{j}=table(repmat(string(method),T,1),repmat(foldID,T,1), ...
            repmat(string(subset.siteTable.stationID(targetIndex(j))),T,1), ...
            subset.timeIndex,truth(:,j),prediction.mean(:,j), ...
            prediction.observationVariance(:,j),'VariableNames', ...
            {'method','foldID','stationID','timeIndex','truthWindMps', ...
            'predictionWindMps','observationVariance'});
    end
    siteMetrics=vertcat(rows{:}); predictions=vertcat(pred{:});
    error=prediction.mean-truth;
    variance=max(prediction.observationVariance,1e-10);
    summary=table(string(method),foldID,sqrt(mean(error.^2,'all')), ...
        mean(abs(error),'all'), ...
        mean(0.5*(log(2*pi*variance)+error.^2./variance),'all'), ...
        mean(siteMetrics.coverage95),mean(siteMetrics.correlation,'omitnan'), ...
        'VariableNames',{'method','foldID','rmse','mae','nlpd', ...
        'coverage95','meanSiteCorrelation'});
end
