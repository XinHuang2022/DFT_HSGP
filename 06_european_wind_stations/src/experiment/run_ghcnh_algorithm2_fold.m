function task = run_ghcnh_algorithm2_fold(foldID)
%RUN_GHCNH_ALGORITHM2_FOLD Fit and evaluate trace-certified adaptive HSGP.

    if nargin<1, foldID=1; end
    C=ghcnh_trace_config();
    [cfg,subset,folds,A]=ghcnh_algorithm2_setup();
    fold=folds(foldID); targetIndex=fold.targetIndex(:);
    observedIndex=setdiff((1:size(subset.U,2))',targetIndex,'stable');
    Yo=subset.U(:,observedIndex); Yt=subset.U(:,targetIndex);
    [observed,target,domainXy]=fold_geometry(subset,observedIndex, ...
        targetIndex,cfg,A);
    foldDir=fullfile(C.resultsDir,sprintf('fold_%02d',foldID));
    if ~isfolder(foldDir), mkdir(foldDir); end
    logFile=fullfile(foldDir,'progress.log');
    totalTimer=tic;
    ghcnh_log(logFile,sprintf('fold%d',foldID),sprintf( ...
        'Algorithm 2 started with %d training and %d test stations', ...
        numel(observedIndex),numel(targetIndex)));

    timer=tic;
    master=adaptive_basis_bank(domainXy,cfg.hsgp.boundaryFactor, ...
        C.referenceJ,A,cfg);
    basisSeconds=toc(timer);
    ghcnh_log(logFile,sprintf('fold%d',foldID),sprintf( ...
        'nested basis built: Jref=%d Mref=%d in %.2fs', ...
        C.referenceJ,C.referenceJ^2,basisSeconds));

    pilotFile=fullfile(foldDir,'algorithm2_pilot_fit.mat');
    if isfile(pilotFile)
        loaded=load(pilotFile,'pilotFit','pilotSeconds');
        pilotFit=loaded.pilotFit; pilotSeconds=loaded.pilotSeconds;
        ghcnh_log(logFile,sprintf('fold%d',foldID),'pilot loaded from checkpoint');
    else
        pilotBasis=subset_adaptive_basis(master,C.initialJ);
        timer=tic;
        ghcnh_log(logFile,sprintf('fold%d_pilot',foldID),sprintf( ...
            'fitting J=%d M=%d pilot',C.initialJ,C.initialJ^2));
        pilotFit=A.fitFixed(Yo,observed.xyCovariance,observed.design, ...
            cfg,pilotBasis,cfg.start,[],[],cfg.hsgp.optimizer, ...
            cfg.seed.optimizer+1000*foldID);
        pilotSeconds=toc(timer);
        save(pilotFile,'pilotFit','pilotSeconds','-v7.3');
        ghcnh_log(logFile,sprintf('fold%d_pilot',foldID),sprintf( ...
            'finished in %.2f min; objective %.6g; nugget %.6g', ...
            pilotSeconds/60,pilotFit.objective,pilotFit.theta.noiseVariance));
    end

    timer=tic;
    [selectedJ,initialAudit,initialChecks]=trace_rank_audit( ...
        pilotFit.theta,observed.xyCovariance,cfg,master,C,A,logFile, ...
        sprintf('fold%d_initial_trace',foldID));
    initialTraceSeconds=toc(timer);
    write_audit(foldDir,'initial',selectedJ,initialAudit,initialChecks);
    ghcnh_log(logFile,sprintf('fold%d',foldID),sprintf( ...
        'initial trace profile J=%d--%d in %.2fs', ...
        min(selectedJ),max(selectedJ),initialTraceSeconds));

    fit=pilotFit; adaptiveFitSeconds=0; verificationSeconds=0;
    iterations=cell(C.maxCorrectionFits,1); stabilized=false;
    for cycle=1:C.maxCorrectionFits
        timer=tic;
        ghcnh_log(logFile,sprintf('fold%d_cycle%d',foldID,cycle),sprintf( ...
            'adaptive fit starting; J range %d--%d', ...
            min(selectedJ),max(selectedJ)));
        fit=adaptive_hsgp_fit(Yo,observed.xyCovariance,observed.design, ...
            cfg,master,selectedJ,fit.theta,cfg.hsgp.optimizer, ...
            cfg.seed.optimizer+1000*foldID+100*cycle,A);
        fitSeconds=toc(timer); adaptiveFitSeconds=adaptiveFitSeconds+fitSeconds;
        ghcnh_log(logFile,sprintf('fold%d_cycle%d',foldID,cycle),sprintf( ...
            'adaptive fit finished in %.2f min; objective %.6g; nugget %.6g', ...
            fitSeconds/60,fit.objective,fit.theta.noiseVariance));

        timer=tic;
        [requiredJ,audit,checks]=trace_rank_audit(fit.theta, ...
            observed.xyCovariance,cfg,master,C,A,logFile, ...
            sprintf('fold%d_cycle%d_trace',foldID,cycle));
        verifySeconds=toc(timer); verificationSeconds=verificationSeconds+verifySeconds;
        enlarged=max(selectedJ,requiredJ); nEnlarged=sum(enlarged>selectedJ);
        stabilized=nEnlarged==0;
        write_audit(foldDir,sprintf('cycle_%d',cycle),requiredJ,audit,checks);
        iterations{cycle}=table(cycle,fitSeconds,verifySeconds,fit.objective, ...
            fit.theta.noiseVariance,min(selectedJ),median(selectedJ), ...
            max(selectedJ),nEnlarged,stabilized,'VariableNames', ...
            {'cycle','fitSeconds','verificationSeconds','objective', ...
            'noiseVariance','minimumJ','medianJ','maximumJ', ...
            'nFrequenciesEnlarged','stabilized'});
        if stabilized, break; end
        selectedJ=enlarged;
    end
    iterations=vertcat(iterations{1:cycle});

    if ~stabilized
        timer=tic;
        ghcnh_log(logFile,sprintf('fold%d_final_correction',foldID), ...
            'fitting the final enlarged profile before prediction');
        fit=adaptive_hsgp_fit(Yo,observed.xyCovariance,observed.design, ...
            cfg,master,selectedJ,fit.theta,cfg.hsgp.optimizer, ...
            cfg.seed.optimizer+1000*foldID+999,A);
        finalCorrectionSeconds=toc(timer);
    else
        finalCorrectionSeconds=0;
    end
    fit.selectedJ=selectedJ;

    timer=tic;
    prediction=predict_adaptive_hsgp(Yo,observed.xyCovariance, ...
        target.xyCovariance,observed.design,target.design,fit,cfg,master,A);
    predictionSeconds=toc(timer);
    [metrics,siteMetrics,predictions]=score_fold(Yt,prediction,subset, ...
        targetIndex,foldID,cfg);
    totalSeconds=toc(totalTimer);
    timing=table(foldID,basisSeconds,pilotSeconds,initialTraceSeconds, ...
        adaptiveFitSeconds,verificationSeconds,finalCorrectionSeconds, ...
        predictionSeconds,totalSeconds,'VariableNames',{'foldID', ...
        'basisSeconds','pilotFitSeconds','initialTraceSeconds', ...
        'adaptiveFitSeconds','verificationSeconds','finalCorrectionSeconds', ...
        'predictionSeconds','totalSeconds'});
    parameters=struct2table(fit.theta,'AsArray',true);
    parameters.foldID=foldID; parameters.objective=fit.objective;
    profile=table((0:numel(selectedJ)-1)',selectedJ,selectedJ.^2, ...
        'VariableNames',{'frequencyIndex','selectedJ','selectedM'});
    writetable(metrics,fullfile(foldDir,'algorithm2_metrics.csv'));
    writetable(siteMetrics,fullfile(foldDir,'algorithm2_site_metrics.csv'));
    writetable(predictions,fullfile(foldDir,'algorithm2_predictions.csv'));
    writetable(timing,fullfile(foldDir,'algorithm2_timing.csv'));
    writetable(parameters,fullfile(foldDir,'algorithm2_parameters.csv'));
    writetable(profile,fullfile(foldDir,'algorithm2_final_rank_profile.csv'));
    writetable(iterations,fullfile(foldDir,'algorithm2_iterations.csv'));
    task=struct('foldID',foldID,'metrics',metrics,'siteMetrics',siteMetrics, ...
        'timing',timing,'parameters',parameters,'rankProfile',profile, ...
        'iterations',iterations,'fit',fit,'prediction',prediction, ...
        'observedIndex',observedIndex,'targetIndex',targetIndex, ...
        'stabilized',stabilized,'version',C.version);
    save(fullfile(foldDir,'algorithm2_complete_task.mat'),'task','C','cfg','-v7.3');
    ghcnh_log(logFile,sprintf('fold%d_complete',foldID),sprintf( ...
        'RMSE %.4f, MAE %.4f, NLPD %.4f; total %.2f min', ...
        metrics.rmse,metrics.mae,metrics.nlpd,totalSeconds/60));
end

function [observed,target,domainXy]=fold_geometry(subset,observedIndex, ...
        targetIndex,cfg,A)
    allCenter=mean(subset.xyKm,1);
    domainXy=(subset.xyKm-allCenter)/cfg.spatial.coordinateScaleKm;
    observed.xyCovariance=domainXy(observedIndex,:);
    target.xyCovariance=domainXy(targetIndex,:);
    center=mean(subset.xyKm(observedIndex,:),1);
    scale=std(subset.xyKm(observedIndex,:),0,1); scale(scale==0)=1;
    observedMean=(subset.xyKm(observedIndex,:)-center)./scale;
    targetMean=(subset.xyKm(targetIndex,:)-center)./scale;
    observed.design=A.makeDesign(size(subset.U,1),observedMean);
    target.design=A.makeDesign(size(subset.U,1),targetMean);
end

function write_audit(folder,prefix,selectedJ,audit,checks)
    writetable(audit,fullfile(folder,[prefix '_trace_audit.csv']));
    writetable(checks,fullfile(folder,[prefix '_exact_spot_checks.csv']));
    profile=table((0:numel(selectedJ)-1)',selectedJ,selectedJ.^2, ...
        'VariableNames',{'frequencyIndex','selectedJ','selectedM'});
    writetable(profile,fullfile(folder,[prefix '_rank_profile.csv']));
end

function [summary,siteMetrics,predictions]=score_fold(truth,prediction, ...
        subset,targetIndex,foldID,cfg)
    nTarget=numel(targetIndex); rows=cell(nTarget,1); pred=cell(nTarget,1);
    for j=1:nTarget
        value=eq9_prediction_metrics(truth(:,j),prediction.mean(:,j), ...
            prediction.observationVariance(:,j),cfg.cv.nominalCoverage);
        rows{j}=table(foldID,string(subset.siteTable.stationID(targetIndex(j))), ...
            value.rmse,value.mae,value.correlation,value.nlpd,value.crps, ...
            value.coverage,value.meanIntervalWidth,'VariableNames', ...
            {'foldID','stationID','rmse','mae','correlation','nlpd','crps', ...
            'coverage95','meanIntervalWidth95'});
        T=size(truth,1);
        pred{j}=table(repmat(foldID,T,1), ...
            repmat(string(subset.siteTable.stationID(targetIndex(j))),T,1), ...
            subset.timeIndex,truth(:,j),prediction.mean(:,j), ...
            prediction.observationVariance(:,j),'VariableNames', ...
            {'foldID','stationID','timeIndex','truthWindMps', ...
            'predictionWindMps','observationVariance'});
    end
    siteMetrics=vertcat(rows{:}); predictions=vertcat(pred{:});
    error=prediction.mean-truth;
    variance=max(prediction.observationVariance,1e-10);
    summary=table(foldID,sqrt(mean(error.^2,'all')),mean(abs(error),'all'), ...
        mean(0.5*(log(2*pi*variance)+error.^2./variance),'all'), ...
        mean(siteMetrics.coverage95),mean(siteMetrics.correlation), ...
        'VariableNames',{'foldID','rmse','mae','nlpd','coverage95', ...
        'meanSiteCorrelation'});
end
