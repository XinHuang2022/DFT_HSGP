function comparison=summarize_algorithm1_vs_algorithm2()
%SUMMARIZE_ALGORITHM1_VS_ALGORITHM2 Record the fold-1 audit comparison.

    C=ghcnh_trace_config();
    foldDir=fullfile(C.resultsDir,'fold_01');
    a=load(fullfile(foldDir,'algorithm1','continuation_task.mat'),'task');
    b=load(fullfile(foldDir,'algorithm2_continuation.mat'),'continuation');
    A=a.task; B=b.continuation;

    aJ=A.rankProfile.selectedJ(:); bJ=B.selectedJ(:);
    aM=aJ.^2; bM=bJ.^2;
    aLast=A.history(end,:); bLast=B.history(end,:);
    comparison=table( ...
        ["Algorithm 1: exact KL";"Algorithm 2: trace bound"], ...
        [A.metrics.rmse;B.metrics.rmse], ...
        [A.metrics.mae;B.metrics.mae], ...
        [A.metrics.nlpd;B.metrics.nlpd], ...
        [A.metrics.coverage95;B.metrics.coverage95], ...
        [A.metrics.meanSiteCorrelation;B.metrics.meanSiteCorrelation], ...
        [A.fit.objective;B.fit.objective], ...
        [A.fit.totalFunctionEvaluations;B.fit.totalFunctionEvaluations], ...
        [aLast.fitSeconds;bLast.fitSeconds], ...
        [aLast.auditSeconds;bLast.auditSeconds], ...
        [A.timing.predictionSeconds;B.predictionSeconds], ...
        [mean(aJ);mean(bJ)],[median(aJ);median(bJ)], ...
        [mean(aM);mean(bM)],[median(aM);median(bM)], ...
        [sum(aJ==48);sum(bJ==48)], ...
        [A.fit.exitFlag;B.fit.exitFlag], ...
        [A.fit.convergenceCertified;B.fit.convergenceCertified], ...
        [A.fit.boundaryHit;B.fit.boundaryHit], ...
        'VariableNames',{'method','rmse','mae','nlpd','coverage95', ...
        'meanSiteCorrelation','objective','finalFunctionEvaluations', ...
        'finalFitSeconds','finalAuditSeconds','predictionSeconds', ...
        'meanJ','medianJ','meanM','medianM','referenceFrequencies', ...
        'exitFlag','convergenceCertified','boundaryHit'});
    writetable(comparison,fullfile(foldDir, ...
        'algorithm1_algorithm2_comparison.csv'));

    ladder=unique([aJ;bJ]);
    counts=table(ladder,arrayfun(@(x)sum(aJ==x),ladder), ...
        arrayfun(@(x)sum(bJ==x),ladder),'VariableNames', ...
        {'J','algorithm1FrequencyCount','algorithm2FrequencyCount'});
    writetable(counts,fullfile(foldDir, ...
        'algorithm1_algorithm2_rank_counts.csv'));

    figuresDir=fullfile(C.resultsDir,'figures');
    if ~isfolder(figuresDir), mkdir(figuresDir); end
    fig=figure('Color','w','Position',[100 100 1120 420]);
    tiledlayout(1,2,'TileSpacing','compact','Padding','compact');
    nexttile;
    stairs(A.rankProfile.frequencyIndex,aJ,'LineWidth',1.7, ...
        'Color',[0.00 0.35 0.70]); hold on;
    stairs((0:numel(bJ)-1)',bJ,'--','LineWidth',1.7, ...
        'Color',[0.85 0.45 0.05]);
    xlabel('Temporal frequency index, k'); ylabel('Selected J_k');
    legend({'Algorithm 1: exact KL','Algorithm 2: trace bound'}, ...
        'Location','northeast'); grid on; box on;

    nexttile;
    times=[aLast.fitSeconds,aLast.auditSeconds,A.timing.predictionSeconds; ...
        bLast.fitSeconds,bLast.auditSeconds,B.predictionSeconds];
    bar(times,'stacked');
    set(gca,'XTickLabel',{'Algorithm 1','Algorithm 2'});
    ylabel('Final stable-stage wall time (s)');
    legend({'Likelihood fit','Rank audit','Prediction'}, ...
        'Location','northwest'); grid on; box on;
    exportgraphics(fig,fullfile(figuresDir, ...
        'algorithm1_algorithm2_fold1_comparison.pdf'),'ContentType','vector');
    exportgraphics(fig,fullfile(figuresDir, ...
        'algorithm1_algorithm2_fold1_comparison.png'),'Resolution',220);
    savefig(fig,fullfile(figuresDir, ...
        'algorithm1_algorithm2_fold1_comparison.fig'));
    close(fig);
end
