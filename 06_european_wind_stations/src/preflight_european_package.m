function report = preflight_european_package(experimentRoot)
%PREFLIGHT_EUROPEAN_PACKAGE Validate the local panel and five-fold contract.

    panelFile = fullfile(experimentRoot, 'input', 'data', ...
        'ghcnh_complete_panel_expanded.mat');
    stationFile = fullfile(experimentRoot, 'input', 'data', ...
        'ghcnh_complete_station_manifest_expanded.csv');
    foldFile = fullfile(experimentRoot, 'input', 'data', ...
        'cv_fold_manifest.csv');
    loaded = load(panelFile, 'subset');
    subset = loaded.subset;
    stationManifest = readtable(stationFile, ...
        'VariableNamingRule', 'preserve');
    retainedFolds = readtable(foldFile, 'VariableNamingRule', 'preserve');
    folds = make_ghcnh_cv_folds(subset, 5);
    foldSizes = arrayfun(@(x) numel(x.targetIndex), folds);
    generatedFold = zeros(size(subset.U, 2), 1);
    for f = 1:numel(folds)
        generatedFold(folds(f).targetIndex) = folds(f).foldID;
    end

    sameStationOrder = height(stationManifest) == size(subset.U, 2) && ...
        isequal(string(stationManifest.stationID), ...
        string(subset.siteTable.stationID));
    allAssigned = isequal(sort(vertcat(folds.targetIndex)), ...
        (1:size(subset.U, 2))') && ...
        isequal(string(retainedFolds.stationID), ...
        string(subset.siteTable.stationID)) && ...
        isequal(retainedFolds.foldID, generatedFold);
    cfg = era5_northsea_config();
    cfg.data.expectedTimePoints = 360;
    cfg.spatial.coordinateScaleKm = 1000;
    domainXy = (subset.xyKm - mean(subset.xyKm, 1)) / ...
        cfg.spatial.coordinateScaleKm;
    adapter = struct('prefix', "era5");
    basis = adaptive_basis_bank(domainXy, 2.5, 8, adapter, cfg);
    basisValid = size(basis.Phi, 1) == 839 && size(basis.Phi, 2) == 64;

    check = ["finite 360-by-839 station panel"; ...
        "station manifest order"; "five whole-site folds"; ...
        "local HSGP basis interface"];
    passed = [isequal(size(subset.U), [360 839]) && ...
        all(isfinite(subset.U), 'all'); sameStationOrder; ...
        allAssigned && isequal(sort(foldSizes(:))', [167 168 168 168 168]); ...
        basisValid];
    detail = [string(sprintf('%d-by-%d', size(subset.U))); ...
        string(sprintf('%d ordered stations', height(stationManifest))); ...
        string(sprintf('fold sizes %s', mat2str(foldSizes))); ...
        string(sprintf('%d-by-%d basis', size(basis.Phi)))];
    report = table(check, passed, detail);
    disp(report);
    if ~all(passed)
        error('European station reproducibility-package preflight failed.');
    end
end
